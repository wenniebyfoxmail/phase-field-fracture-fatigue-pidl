function rows = localReadCycleIndex(path)
localRequire(isfile(path), 'cycle_index.csv is missing.');
text = string(fileread(path));
lines = splitlines(text);
if ~isempty(lines) && lines(end) == ""
    lines(end) = [];
end
header = "cycle,Umax_N,peak_substep_ordinal,raw_step_1_based," + ...
    "branch,phase,file,mesh_sha256,event_hit,first_hit," + ...
    "consecutive_post_hit,confirmed";
localRequire(numel(lines) >= 2 && lines(1) == header, ...
    'cycle_index.csv header is invalid.');
template = struct( ...
    'cycle', 0, 'Umax_N', 0, 'peak_substep_ordinal', 0, ...
    'raw_step_1_based', 0, 'branch', "", 'phase', "", 'file', "", ...
    'mesh_sha256', "", 'event_hit', false, 'first_hit', NaN, ...
    'consecutive_post_hit', 0, 'confirmed', NaN);
rows = repmat(template, numel(lines) - 1, 1);
for index = 2:numel(lines)
    fields = split(lines(index), ',');
    localRequire(numel(fields) == 12, ...
        'cycle_index.csv row %d has the wrong field count.', index);
    eventHit = localCsvNumber(fields(9), false);
    localRequire(any(eventHit == [0 1]), ...
        'cycle_index.csv event_hit must be exactly 0 or 1.');
    rows(index - 1) = struct( ...
        'cycle', localCsvNumber(fields(1), false), ...
        'Umax_N', localCsvNumber(fields(2), false), ...
        'peak_substep_ordinal', localCsvNumber(fields(3), false), ...
        'raw_step_1_based', localCsvNumber(fields(4), false), ...
        'branch', fields(5), 'phase', fields(6), 'file', fields(7), ...
        'mesh_sha256', fields(8), ...
        'event_hit', logical(eventHit), ...
        'first_hit', localCsvNumber(fields(10), true), ...
        'consecutive_post_hit', localCsvNumber(fields(11), false), ...
        'confirmed', localCsvNumber(fields(12), true));
end
end

function value = localCsvNumber(text, optional)
if optional && strlength(text) == 0
    value = NaN;
    return;
end
value = str2double(text);
localRequire(isscalar(value) && isfinite(value), ...
    'cycle_index.csv contains a nonnumeric required field.');
end

