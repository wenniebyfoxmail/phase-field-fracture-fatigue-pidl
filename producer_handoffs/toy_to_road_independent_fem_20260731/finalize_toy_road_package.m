function localRequireExactFiles(outputRoot, expected)
actual = localRelativeFiles(outputRoot, false);
localRequire(isequal(sort(actual), sort(string(expected))), ...
    'Output contains missing or extra pre-finalization artifacts.');
end

function files = localRelativeFiles(outputRoot, includeManifest)
listing = dir(fullfile(outputRoot, '**', '*'));
listing = listing(~[listing.isdir]);
files = strings(numel(listing), 1);
prefixLength = strlength(string(outputRoot)) + 2;
for index = 1:numel(listing)
    fullPath = string(fullfile(listing(index).folder, listing(index).name));
    files(index) = replace(extractAfter(fullPath, prefixLength - 1), '\', '/');
end
if ~includeManifest
    files(files == "SHA256SUMS.txt") = [];
end
end

function localRejectSymlinksAndCaseCollisions(outputRoot)
files = localRelativeFiles(outputRoot, true);
folded = lower(files);
localRequire(numel(unique(folded)) == numel(folded), ...
    'Output contains duplicate or case-colliding paths.');
rootEntries = dir(outputRoot);
rootEntries = rootEntries(~ismember({rootEntries.name}, {'.', '..'}));
rootDirectories = string({rootEntries([rootEntries.isdir]).name});
localRequire(isequal(sort(rootDirectories(:)), "states"), ...
    'Output root must contain exactly the canonical states directory.');
statesPath = fullfile(outputRoot, 'states');
localRequire(~java.nio.file.Files.isSymbolicLink( ...
    java.io.File(statesPath).toPath()) && ~localIsReparsePoint(statesPath), ...
    'The canonical states directory cannot be a symbolic link.');
stateEntries = dir(statesPath);
stateEntries = stateEntries(~ismember({stateEntries.name}, {'.', '..'}));
localRequire(~any([stateEntries.isdir]), ...
    'Nested or extra directories are forbidden inside states.');
for index = 1:numel(files)
    path = fullfile(outputRoot, char(replace(files(index), '/', filesep)));
    localRequire(~java.nio.file.Files.isSymbolicLink(java.io.File(path).toPath()) && ...
        ~localIsReparsePoint(path), ...
        'Output contains a forbidden symlink/reparse point: %s.', files(index));
end
end

function localWriteManifest(outputRoot)
manifestPath = fullfile(outputRoot, 'SHA256SUMS.txt');
if localPathExists(manifestPath)
    error('toyRoad:ManifestExists', ...
        'Refusing to overwrite pre-existing output manifest.');
end
localRejectSymlinksAndCaseCollisions(outputRoot);
files = sort(localRelativeFiles(outputRoot, false));
lines = strings(numel(files), 1);
for index = 1:numel(files)
    path = fullfile(outputRoot, char(replace(files(index), '/', filesep)));
    lines(index) = localFileSha256(path) + "  " + files(index);
end
bytes = unicode2native(char(strjoin(lines, newline) + newline), 'UTF-8');
localPublishBytesNoClobber(manifestPath, bytes);
end

function summary = localVerifyManifest(outputRoot, caseId)
try
    localRequire(isfolder(outputRoot), 'Output root does not exist.');
    localRejectSymlinksAndCaseCollisions(outputRoot);
    runResult = validate_toy_road_run_result( ...
        fullfile(outputRoot, 'RUN_RESULT.json'), caseId);
    localRequire(runResult.complete, 'RUN_RESULT.json is not complete.');
    manifestPath = fullfile(outputRoot, 'SHA256SUMS.txt');
    localRequire(isfile(manifestPath), 'Output manifest is missing.');
    bytes = localReadBytes(manifestPath);
    localRequire(~any(bytes == 13), 'Output manifest must use LF bytes.');
    lines = splitlines(string(native2unicode(bytes.', 'UTF-8')));
    if ~isempty(lines) && lines(end) == ""
        lines(end) = [];
    end
    entries = strings(numel(lines), 2);
    for index = 1:numel(lines)
        token = regexp(char(lines(index)), '^([0-9a-f]{64})  (.+)$', ...
            'tokens', 'once');
        localRequire(~isempty(token), 'Malformed output manifest line.');
        entries(index, :) = string(token);
    end
    paths = entries(:, 2);
    localRequire(isequal(paths, sort(paths)) && ...
        numel(unique(lower(paths))) == numel(paths) && ...
        ~any(paths == "SHA256SUMS.txt"), ...
        'Output manifest paths are unsorted, duplicated, or self-referential.');
    actualFiles = sort(localRelativeFiles(outputRoot, false));
    localRequire(isequal(paths, actualFiles), ...
        'Output manifest has missing or extra artifacts.');
    for index = 1:numel(paths)
        path = fullfile(outputRoot, char(replace(paths(index), '/', filesep)));
        localRequire(strcmp(entries(index, 1), localFileSha256(path)), ...
            'Output manifest SHA256 mismatch: %s.', paths(index));
    end
    summary = struct('is_valid', true, 'file_count', numel(paths), ...
        'manifest_sha256', localFileSha256(manifestPath));
catch exception
    if strcmp(exception.identifier, 'toyRoad:ManifestVerificationFailed')
        rethrow(exception);
    end
    wrapped = MException('toyRoad:ManifestVerificationFailed', ...
        'Output manifest verification failed: %s', exception.message);
    wrapped = addCause(wrapped, exception);
    throw(wrapped);
end
end

function localPublishBytesNoClobber(outputPath, bytes)
outputDir = fileparts(outputPath);
lockPath = [outputPath '.publish.lock'];
localRequire(~localPathExists(outputPath) && ...
    java.io.File(lockPath).createNewFile(), ...
    'Manifest target or publication lock already exists.');
lockCleanup = onCleanup(@() localDeleteIfExists(lockPath));
tempPath = [tempname(outputDir) '.tmp.sha256'];
tempCleanup = onCleanup(@() localDeleteIfExists(tempPath));
fileId = fopen(tempPath, 'wb');
localRequire(fileId >= 0, 'Cannot create manifest temporary file.');
fileCleanup = onCleanup(@() fclose(fileId));
written = fwrite(fileId, bytes, 'uint8');
localRequire(written == numel(bytes), 'Cannot write complete manifest bytes.');
clear fileCleanup
try
    java.nio.file.Files.createLink(java.io.File(outputPath).toPath(), ...
        java.io.File(tempPath).toPath());
catch exception
    wrapped = MException('toyRoad:PackagePublicationFailed', ...
        'No-clobber hard-link manifest publication failed.');
    wrapped = addCause(wrapped, exception);
    throw(wrapped);
end
java.nio.file.Files.delete(java.io.File(tempPath).toPath());
end

function value = localReadJson(path)
localRequire(isfile(path), 'Required JSON file is missing: %s.', path);
value = jsondecode(fileread(path));
end

function value = localCanonicalize(value)
if isstruct(value)
    value = orderfields(value);
    names = fieldnames(value);
    for elementIndex = 1:numel(value)
        for fieldIndex = 1:numel(names)
            name = names{fieldIndex};
            value(elementIndex).(name) = localCanonicalize(value(elementIndex).(name));
        end
    end
elseif iscell(value)
    for index = 1:numel(value)
        value{index} = localCanonicalize(value{index});
    end
end
end

function value = localOptionalEqual(left, right)
value = (isnan(left) && isnan(right)) || isequal(left, right);
end

function value = localJsonOptionalEqual(jsonValue, number)
if isnan(number)
    value = isempty(jsonValue);
else
    value = isequal(jsonValue, number);
end
end

function value = localJsonOptional(number)
if isnan(number)
    value = [];
else
    value = number;
end
end

function digest = localFileSha256(path)
bytes = localReadBytes(path);
hasher = java.security.MessageDigest.getInstance('SHA-256');
hasher.update(bytes);
digestBytes = typecast(hasher.digest(), 'uint8');
digest = lower(string(reshape(dec2hex(digestBytes, 2).', 1, [])));
end

function bytes = localReadBytes(path)
fileId = fopen(path, 'rb');
localRequire(fileId >= 0, 'Cannot read required file: %s.', path);
cleanup = onCleanup(@() fclose(fileId));
bytes = fread(fileId, Inf, '*uint8');
end

function value = localPathExists(path)
value = isfile(path) || isfolder(path);
end

function value = localIsReparsePoint(path)
options = javaArray('java.nio.file.LinkOption', 1);
options(1) = java.nio.file.LinkOption.NOFOLLOW_LINKS;
attributes = java.nio.file.Files.readAttributes( ...
    java.io.File(path).toPath(), ...
    java.lang.Class.forName('java.nio.file.attribute.BasicFileAttributes'), ...
    options);
value = attributes.isSymbolicLink() || attributes.isOther();
end

function localDeleteIfExists(path)
if isfile(path)
    delete(path);
end
end

function localRequire(condition, message, varargin)
if ~condition
    error('toyRoad:PackageValidationFailed', message, varargin{:});
end
