function value = localValidCommit(commit)
commit = char(string(commit));
value = ~isempty(regexp(commit, '^[0-9a-f]{40}$', 'once')) && ...
    numel(unique(commit)) > 1;
end

function value = localNormalizedAbsolutePath(path)
path = string(path);
value = isscalar(path) && strlength(path) > 0 && ~contains(path, '\') && ...
    (~isempty(regexp(char(path), '^[A-Za-z]:/', 'once')) || startsWith(path, '/'));
end

function expectedMeshHash = localValidateMesh(mesh, cfg, caseId, contract)
required = {'node_coords', 'connectivity', 'element_material_ids', ...
    'element_centroids', 'element_areas', 'quadrature_points', ...
    'quadrature_weights', 'mesh_sha256', 'mesh_ordering_id', ...
    'parent_node_coords', 'mesh_transfer_audit'};
localRequire(isstruct(mesh) && isscalar(mesh) && all(isfield(mesh, required)), ...
    'mesh_geometry.mat is incomplete.');
coords = mesh.node_coords;
connectivity = mesh.connectivity;
localRequire(isnumeric(coords) && isreal(coords) && size(coords, 2) == 2 && ...
    all(isfinite(coords), 'all') && isnumeric(connectivity) && ...
    isreal(connectivity) && size(connectivity, 2) == 4 && ...
    all(isfinite(connectivity), 'all') && ...
    all(connectivity == floor(connectivity), 'all') && ...
    all(connectivity >= 1, 'all') && all(connectivity <= size(coords, 1), 'all'), ...
    'mesh_geometry contains invalid Q4 coordinates/connectivity.');
localRequire(isequal(size(mesh.parent_node_coords), [contract.num_nodes 2]) && ...
    isequal(size(connectivity), [contract.num_elem 4]) && ...
    size(coords, 1) == contract.num_nodes, ...
    'mesh_geometry does not have the exact locked parent dimensions.');
parentMeshHash = toy_road_mesh_sha256(mesh.parent_node_coords, connectivity);
localRequire(strcmp(parentMeshHash, contract.task4_parent_mesh_sha256), ...
    'Parent coordinates/connectivity do not match the sealed Task 4 identity.');
elementCount = size(connectivity, 1);
localRequire(isequal(size(mesh.element_material_ids), [elementCount 1]) && ...
    all(isfinite(mesh.element_material_ids), 'all') && ...
    isequal(size(mesh.element_centroids), [elementCount 2]) && ...
    isequal(size(mesh.element_areas), [elementCount 1]) && ...
    all(mesh.element_areas > 0, 'all') && ...
    size(mesh.quadrature_points, 2) == 2 && ...
    numel(mesh.quadrature_weights) == size(mesh.quadrature_points, 1) && ...
    all(mesh.quadrature_weights > 0, 'all'), ...
    'mesh_geometry dimensions or quadrature data are invalid.');
localRequire(isequal(mesh.quadrature_points, contract.quadrature_points) && ...
    isequal(mesh.quadrature_weights, contract.quadrature_weights), ...
    'mesh_geometry quadrature differs from the locked Q4 rule.');
x = reshape(coords(connectivity, 1), size(connectivity));
y = reshape(coords(connectivity, 2), size(connectivity));
next = [2:4 1];
centroids = [mean(x, 2) mean(y, 2)];
areas = 0.5 * abs(sum(x .* y(:, next) - y .* x(:, next), 2));
localRequire(max(abs(mesh.element_centroids - centroids), [], 'all') <= 1e-14 && ...
    max(abs(mesh.element_areas - areas), [], 'all') <= 1e-14 && ...
    strcmp(string(mesh.mesh_sha256), ...
        toy_road_mesh_sha256(coords, connectivity)) && ...
    strcmp(string(mesh.mesh_ordering_id), ...
        "q4_node_connectivity_1_based_v1"), ...
    'mesh_geometry derived values, ordering, or hash are invalid.');
localRequire(isequal(size(mesh.parent_node_coords), size(coords)) && ...
    all(isfinite(mesh.parent_node_coords), 'all') && ...
    isstruct(mesh.mesh_transfer_audit) && isscalar(mesh.mesh_transfer_audit) && ...
    isfield(mesh.mesh_transfer_audit, 'applied'), ...
    'mesh_geometry parent/audit evidence is invalid.');
if caseId == "T1_initial_defect"
    [expectedCoords, expectedAudit] = apply_t1_mesh_transfer( ...
        mesh.parent_node_coords, connectivity, cfg.physics.ell);
    expectedMeshHash = toy_road_mesh_sha256(expectedCoords, connectivity);
    recordedAudit = rmfield(mesh.mesh_transfer_audit, 'applied');
    localRequire(logical(mesh.mesh_transfer_audit.applied) && ...
        isequal(coords, expectedCoords) && ...
        strcmp(string(mesh.mesh_sha256), expectedMeshHash) && ...
        isequaln(recordedAudit, expectedAudit), ...
        'T1 mesh transfer audit does not reproduce the sealed map.');
else
    expectedMeshHash = contract.task4_parent_mesh_sha256;
    localRequire(~logical(mesh.mesh_transfer_audit.applied) && ...
        isequal(coords, mesh.parent_node_coords) && ...
        strcmp(string(mesh.mesh_sha256), expectedMeshHash), ...
        'Non-T1 case changed the parent mesh.');
end
end

