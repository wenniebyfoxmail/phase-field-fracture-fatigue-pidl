function summary = finalize_toy_road_package(outputRoot, caseId, launchReceiptPath, mode)
%FINALIZE_TOY_ROAD_PACKAGE Deeply validate and seal one completed case.

if nargin < 4
    mode = "finalize";
    dependencies = struct();
elseif isstruct(mode)
    dependencies = mode;
    mode = "finalize";
else
    dependencies = struct();
end
outputRoot = char(outputRoot);
caseId = string(caseId);
mode = string(mode);
if ~isscalar(mode) || ~any(mode == ["finalize" "verify_manifest"])
    error('toyRoad:PackageValidationFailed', 'Unknown finalizer mode.');
end
if mode == "verify_manifest"
    summary = localVerifyManifest(outputRoot, caseId);
    return;
end

try
    [summary, provenance] = localValidatePackage( ...
        outputRoot, caseId, launchReceiptPath, dependencies);
catch exception
    if strcmp(exception.identifier, 'toyRoad:PackageValidationFailed')
        rethrow(exception);
    end
    wrapped = MException('toyRoad:PackageValidationFailed', ...
        'Package validation failed before publication: %s', exception.message);
    wrapped = addCause(wrapped, exception);
    throw(wrapped);
end

try
    write_toy_road_json(fullfile(outputRoot, 'PRODUCER_PROVENANCE.json'), provenance);
    write_toy_road_json(fullfile(outputRoot, 'VALIDATION_SUMMARY.json'), summary);
    localWriteManifest(outputRoot);
catch exception
    wrapped = MException('toyRoad:PackagePublicationFailed', ...
        'Validated package outputs could not be published without clobbering.');
    wrapped = addCause(wrapped, exception);
    throw(wrapped);
end
end

function [summary, provenance] = localValidatePackage( ...
        outputRoot, caseId, launchReceiptPath, dependencies)
localRequire(isfolder(outputRoot), 'Output root does not exist.');
validCases = ["T1_initial_defect" "T2_material_state" "T3_loading_history"];
localRequire(isscalar(caseId) && any(caseId == validCases), ...
    'Case ID is not one of the three sealed cases.');

finalNames = {'PRODUCER_PROVENANCE.json', 'VALIDATION_SUMMARY.json', ...
    'SHA256SUMS.txt'};
for index = 1:numel(finalNames)
    localRequire(~localPathExists(fullfile(outputRoot, finalNames{index})), ...
        'Refusing to clobber pre-existing final output %s.', finalNames{index});
end
localRejectSymlinksAndCaseCollisions(outputRoot);

runPath = fullfile(outputRoot, 'RUN_RESULT.json');
localRequire(isfile(runPath), ...
    'RUN_RESULT.json sole completion marker is missing.');
runResult = validate_toy_road_run_result(runPath, caseId);
localRequire(runResult.complete && strcmp(string(runResult.status), "complete"), ...
    'RUN_RESULT.json does not mark a complete run.');

handoffDir = fileparts(mfilename('fullpath'));
cfg = build_toy_road_case_config(caseId, handoffDir);
caseLockPath = fullfile(handoffDir, sprintf('%s_INPUT_LOCK.json', ...
    extractBefore(caseId, 3)));
caseLockHash = localFileSha256(caseLockPath);
parentLockHash = localFileSha256(fullfile(handoffDir, 'PARENT_LOCK.json'));
parentLock = localReadJson(fullfile(handoffDir, 'PARENT_LOCK.json'));
meshContract = localLoadParentMeshContract(parentLock, dependencies);

snapshot = localReadJson(fullfile(outputRoot, 'INPUT_SNAPSHOT.json'));
localValidateSnapshot(snapshot, cfg, caseId, caseLockHash);
provenance = localReadLaunchReceipt(launchReceiptPath, outputRoot);
localValidateProvenance(provenance, snapshot, caseId, caseLockHash, ...
    parentLockHash, handoffDir, parentLock);

mesh = load(fullfile(outputRoot, 'mesh_geometry.mat'));
expectedMeshHash = localValidateMesh(mesh, cfg, caseId, meshContract);
localValidateState0(outputRoot, mesh, caseId);

indexRows = localReadCycleIndex(fullfile(outputRoot, 'cycle_index.csv'));
terminalCycle = double(runResult.terminal_cycle);
localRequire(terminalCycle >= 1 && terminalCycle <= cfg.censor_cap && ...
    terminalCycle == floor(terminalCycle), 'Terminal cycle is invalid.');
localRequire(numel(indexRows) == terminalCycle, ...
    'Cycle index row count does not equal the terminal cycle.');
expectedBaseFiles = [ ...
    "EVENT_METADATA.json"; "INPUT_SNAPSHOT.json"; "LAUNCH_RECEIPT.json"; ...
    "RUN_RESULT.json"; ...
    "cycle_index.csv"; "initial_state_metadata.mat"; "mesh_geometry.mat"; ...
    "state0_analysis.mat"; ...
    compose("states/cycle_%04d.mat", (1:terminalCycle).')];
localRequireExactFiles(outputRoot, expectedBaseFiles);

eventState = struct();
previous = [];
damageMin = inf;
damageMax = -inf;
alphaBarMin = inf;
alphaBarMax = -inf;
activeIdentityMax = 0;
for cycle = 1:terminalCycle
    relativePath = sprintf('states/cycle_%04d.mat', cycle);
    state = load(fullfile(outputRoot, relativePath));
    if cycle == 1
        metrics = validate_toy_road_state(state);
    else
        metrics = validate_toy_road_state(state, previous);
    end
    localRequire(isequal(state.node_coords, mesh.node_coords) && ...
        isequal(state.connectivity, mesh.connectivity), ...
        'State %d mesh arrays differ from mesh_geometry.mat.', cycle);
    localRequire(strcmp(string(state.mesh_sha256), string(mesh.mesh_sha256)), ...
        'State %d mesh hash differs from mesh_geometry.mat.', cycle);
    localRequire(strcmp(string(state.mesh_sha256), expectedMeshHash) && ...
        isequal(state.quadrature_points, mesh.quadrature_points) && ...
        isequal(state.quadrature_weights, mesh.quadrature_weights), ...
        'State %d quadrature or case mesh identity differs from mesh_geometry.mat.', ...
        cycle);
    expectedUmax = cfg.umax_for_cycle(cycle);
    localRequire(state.cycle == cycle && abs(state.Umax_N - expectedUmax) <= 1e-14, ...
        'State %d case amplitude or cycle identity is invalid.', cycle);
    localValidateIndexRow(indexRows(cycle), state, relativePath);

    eventState = advance_toy_road_event(eventState, mesh.node_coords, ...
        mesh.connectivity, cycle, state.d_node);
    localRequire(indexRows(cycle).event_hit == eventState.hit && ...
        localOptionalEqual(indexRows(cycle).first_hit, eventState.first_hit) && ...
        indexRows(cycle).consecutive_post_hit == eventState.consecutive_post_hit && ...
        localOptionalEqual(indexRows(cycle).confirmed, eventState.confirmed), ...
        'Cycle index event state is invalid at cycle %d.', cycle);
    localRequire(metrics.right_boundary_hit == eventState.hit, ...
        'State and event hit diagnostics differ at cycle %d.', cycle);
    damageMin = min(damageMin, metrics.damage_min);
    damageMax = max(damageMax, metrics.damage_max);
    alphaBarMin = min(alphaBarMin, metrics.alpha_bar_min);
    alphaBarMax = max(alphaBarMax, metrics.alpha_bar_max);
    activeIdentityMax = max(activeIdentityMax, ...
        metrics.active_identity_max_abs_error);
    previous = state;
end

event = localReadJson(fullfile(outputRoot, 'EVENT_METADATA.json'));
localValidateTerminalMetadata(event, runResult, eventState, caseId, cfg, ...
    terminalCycle);

summary = struct( ...
    'schema_version', 'toy_road_validation_summary_v1', ...
    'is_valid', true, ...
    'case_id', char(caseId), ...
    'source_commit', char(string(snapshot.source_commit)), ...
    'terminal_cycle', terminalCycle, ...
    'terminal_reason', char(string(runResult.terminal_reason)), ...
    'terminal_state_file', char(string(runResult.terminal_state_file)), ...
    'state_count', terminalCycle, ...
    'mesh_sha256', char(string(mesh.mesh_sha256)), ...
    'first_hit', localJsonOptional(eventState.first_hit), ...
    'confirmed', localJsonOptional(eventState.confirmed), ...
    'damage_min', damageMin, ...
    'damage_max', damageMax, ...
    'alpha_bar_min', alphaBarMin, ...
    'alpha_bar_max', alphaBarMax, ...
    'active_identity_max_abs_error', activeIdentityMax, ...
    'run_result_is_sole_completion_marker', true, ...
    'latent_fem_fields_are_direct_road_sensors', false, ...
    'pidl_network_training_authorized', false, ...
    'road_validation_authorized', false);
end

function localValidateSnapshot(snapshot, cfg, caseId, caseLockHash)
required = {'case_configuration', 'case_id', 'lock_sha256', 'source_commit', ...
    'fresh_state', 'line_search', 'cycle_jump', 'normalized_substeps'};
localRequire(isstruct(snapshot) && isscalar(snapshot) && ...
    all(isfield(snapshot, required)), 'INPUT_SNAPSHOT.json is incomplete.');
localRequire(strcmp(string(snapshot.case_id), caseId) && ...
    strcmpi(string(snapshot.lock_sha256), caseLockHash) && ...
    islogical(snapshot.fresh_state) && isscalar(snapshot.fresh_state) && ...
    snapshot.fresh_state && islogical(snapshot.line_search) && ...
    ~snapshot.line_search && islogical(snapshot.cycle_jump) && ...
    ~snapshot.cycle_jump && ...
    isequal(reshape(snapshot.normalized_substeps, 1, []), ...
        [0.25 0.5 0.75 1.0 0.0]), ...
    'INPUT_SNAPSHOT.json violates fresh locked execution.');
sourceCommit = string(snapshot.source_commit);
localRequire(isscalar(sourceCommit) && ...
    ~isempty(regexp(char(sourceCommit), '^[0-9a-f]{40}$', 'once')), ...
    'INPUT_SNAPSHOT source commit is not a full lowercase Git hash.');
cfgSnapshot = rmfield(cfg, 'umax_for_cycle');
snapshotJson = jsonencode(localCanonicalize(snapshot.case_configuration));
lockedJson = jsonencode(localCanonicalize(cfgSnapshot));
localRequire(strcmp(snapshotJson, lockedJson), ...
    'INPUT_SNAPSHOT case configuration differs from the sealed lock.');
end

function provenance = localReadLaunchReceipt(input, outputRoot)
localRequire((ischar(input) && isrow(input)) || ...
    (isstring(input) && isscalar(input)), ...
    'Launch receipt input must be the canonical JSON path.');
expectedPath = fullfile(outputRoot, 'LAUNCH_RECEIPT.json');
localRequire(strcmpi(char(java.io.File(char(input)).getCanonicalPath()), ...
        char(java.io.File(expectedPath).getCanonicalPath())) && ...
    isfile(expectedPath), ...
    'The canonical no-clobber LAUNCH_RECEIPT.json is required.');
provenance = localReadJson(expectedPath);
end

function localValidateProvenance(provenance, snapshot, caseId, ...
        caseLockHash, parentLockHash, handoffDir, parentLock)
required = {'schema_version', 'case_id', 'source_commit', ...
    'source_root', 'source_manifest_sha256', 'source_hashes', ...
    'case_lock_sha256', 'parent_lock_sha256', ...
    'griphfith_commit', 'griphfith_root', 'griphfith_source_hashes', ...
    'runtime_hashes', 'parent_root', 'parent_source_hashes', ...
    'matlab_exit_code'};
localRequire(isstruct(provenance) && isscalar(provenance) && ...
    all(isfield(provenance, required)), 'Producer provenance is incomplete.');
manifestHash = localFileSha256(fullfile(handoffDir, 'SHA256SUMS.txt'));
localRequire(strcmp(string(provenance.schema_version), ...
        "toy_road_launch_receipt_v1") && ...
    strcmp(string(provenance.case_id), caseId) && ...
    strcmp(string(provenance.source_commit), string(snapshot.source_commit)) && ...
    strcmpi(string(provenance.source_manifest_sha256), manifestHash) && ...
    strcmpi(string(provenance.case_lock_sha256), caseLockHash) && ...
    strcmpi(string(provenance.parent_lock_sha256), parentLockHash) && ...
    strcmpi(string(provenance.griphfith_commit), ...
        "355d4c83fefc2db88c32031a2dd2623b3de85c89") && ...
    localValidCommit(provenance.source_commit) && ...
    localNormalizedAbsolutePath(provenance.source_root) && ...
    localNormalizedAbsolutePath(provenance.griphfith_root) && ...
    localNormalizedAbsolutePath(provenance.parent_root) && ...
    isnumeric(provenance.matlab_exit_code) && ...
    isscalar(provenance.matlab_exit_code) && provenance.matlab_exit_code == 0 && ...
    ~isempty(provenance.griphfith_source_hashes) && ...
    ~isempty(provenance.runtime_hashes) && ...
    ~isempty(provenance.parent_source_hashes), ...
    'Producer provenance does not match locked source/runtime identities.');
localValidateHashReceipts(provenance.source_hashes, ...
    localReadSourceManifest(fullfile(handoffDir, 'SHA256SUMS.txt')), ...
    'sealed source');
localValidateHashReceipts(provenance.griphfith_source_hashes, ...
    localExpectedGripfithSourceHashes(), 'GRIPHFiTH source');
localValidateHashReceipts(provenance.runtime_hashes, ...
    localExpectedRuntimeHashes(), 'runtime');
localValidateHashReceipts(provenance.parent_source_hashes, ...
    localExpectedParentHashes(parentLock), 'parent source');
end

function localValidateHashReceipts(records, expectedRecords, label)
localRequire(isstruct(records) && numel(records) == numel(expectedRecords) && ...
    isequal(sort(string(fieldnames(records))), sort(["path"; "sha256"])), ...
    '%s hash receipt schema is invalid.', label);
paths = strings(numel(records), 1);
hashes = strings(numel(records), 1);
for index = 1:numel(records)
    paths(index) = string(records(index).path);
    hashes(index) = string(records(index).sha256);
    localRequire(isscalar(paths(index)) && strlength(paths(index)) > 0 && ...
        isscalar(hashes(index)) && ...
        ~isempty(regexp(char(hashes(index)), '^[0-9a-f]{64}$', 'once')), ...
        '%s hash receipt contains an invalid path or digest.', label);
end
localRequire(numel(unique(lower(paths))) == numel(paths) && ...
    all(~contains(paths, '\')) && all(~startsWith(paths, '/')) && ...
    all(cellfun(@isempty, regexp(cellstr(paths), '(^|/)\.\.(/|$)', 'once'))), ...
    '%s hash receipt contains duplicate, case-colliding, or unsafe paths.', label);
expectedPaths = string({expectedRecords.path}).';
expectedHashes = string({expectedRecords.sha256}).';
[paths, order] = sort(paths);
hashes = hashes(order);
[expectedPaths, order] = sort(expectedPaths);
expectedHashes = expectedHashes(order);
localRequire(isequal(paths, expectedPaths) && isequal(hashes, expectedHashes), ...
    '%s hash receipt does not contain the exact locked path-to-SHA256 mapping.', ...
    label);
end

function records = localReadSourceManifest(path)
bytes = localReadBytes(path);
localRequire(~any(bytes == 13), 'Sealed source manifest must use LF bytes.');
lines = splitlines(string(native2unicode(bytes.', 'UTF-8')));
lines(lines == "") = [];
records = repmat(struct('path', '', 'sha256', ''), numel(lines), 1);
for index = 1:numel(lines)
    token = regexp(char(lines(index)), '^([0-9a-f]{64})  (.+)$', ...
        'tokens', 'once');
    localRequire(~isempty(token), 'Sealed source manifest line is malformed.');
    records(index).path = token{2};
    records(index).sha256 = token{1};
end
end

