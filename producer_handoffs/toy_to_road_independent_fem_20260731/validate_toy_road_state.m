function localValidateCycleIndex(state)
row = state.cycle_index;
localRequire(isstruct(row) && isscalar(row), 'cycle_index must be a scalar struct.');
required = {'cycle', 'Umax_N', 'peak_substep_ordinal', 'raw_step_1_based', ...
    'branch', 'phase', 'file', 'mesh_sha256', 'state_semantics_id', ...
    'mesh_ordering_id', 'state_ordering_id'};
for index = 1:numel(required)
    localRequire(isfield(row, required{index}), ...
        'Missing cycle_index field %s.', required{index});
end
localRequire(localPositiveInteger(row.cycle) && ...
    localPositiveInteger(row.peak_substep_ordinal) && ...
    localPositiveInteger(row.raw_step_1_based) && ...
    isnumeric(row.Umax_N) && isreal(row.Umax_N) && isscalar(row.Umax_N) && ...
    isfinite(row.Umax_N) && row.Umax_N >= 0, ...
    'cycle_index numeric metadata must contain valid scalar values.');
localRequire(isequal(row.cycle, state.cycle) && ...
    isequal(row.Umax_N, state.Umax_N) && ...
    isequal(row.peak_substep_ordinal, state.peak_substep_ordinal) && ...
    isequal(row.raw_step_1_based, state.raw_step_1_based) && ...
    localTextScalarEquals(row.branch, state.branch) && ...
    localTextScalarEquals(row.phase, state.phase) && ...
    localTextScalarEquals(row.mesh_sha256, state.mesh_sha256) && ...
    localTextScalarEquals(row.state_semantics_id, state.state_semantics_id) && ...
    localTextScalarEquals(row.mesh_ordering_id, state.mesh_ordering_id) && ...
    localTextScalarEquals(row.state_ordering_id, state.state_ordering_id), ...
    'cycle_index does not match the exported state metadata.');
localRequire(localTextScalarEquals(row.file, ...
    sprintf('states/cycle_%04d.mat', state.cycle)), ...
    'cycle_index.file does not name the canonical cycle shard.');
end

function localValidatePrevious(state, previous, irreversibilityTolerance)
localRequire(isstruct(previous) && isscalar(previous), ...
    'previous metadata/state must be a scalar struct.');
required = {'cycle', 'raw_step_1_based', 'mesh_sha256', 'n_substeps'};
for index = 1:numel(required)
    localRequire(isfield(previous, required{index}), ...
        'Missing previous field %s.', required{index});
end
localRequire(state.cycle == previous.cycle + 1, ...
    'Exported cycles must be consecutive.');
localRequire(state.n_substeps == previous.n_substeps && ...
    state.raw_step_1_based == previous.raw_step_1_based + state.n_substeps, ...
    'Exported raw steps must be consecutive under the locked cadence.');
localRequire(strcmp(string(state.mesh_sha256), string(previous.mesh_sha256)), ...
    'Mesh hash changed between consecutive states.');
if isfield(previous, 'd_node')
    localRequire(isequal(size(previous.d_node), size(state.d_node)) && ...
        all(state.d_node >= previous.d_node - irreversibilityTolerance, 'all'), ...
        'Nodal damage violated the declared irreversibility tolerance.');
end
if isfield(previous, 'alpha_bar_gp')
    localRequire(isequal(size(previous.alpha_bar_gp), size(state.alpha_bar_gp)) && ...
        all(state.alpha_bar_gp >= previous.alpha_bar_gp - irreversibilityTolerance, 'all'), ...
        'GP alpha_bar violated the declared irreversibility tolerance.');
end
end

function localCheckRange(value, lower, upper, tolerance, name)
localRequire(all(value >= lower - tolerance, 'all') && ...
    all(value <= upper + tolerance, 'all'), ...
    '%s lies outside [%g, %g] beyond tolerance.', name, lower, upper);
end

function value = localPositiveInteger(value)
value = isnumeric(value) && isreal(value) && isscalar(value) && ...
    isfinite(value) && value >= 1 && value == floor(value);
end

function value = localTextScalarEquals(actual, expected)
actualIsScalarText = (ischar(actual) && isrow(actual)) || ...
    (isstring(actual) && isscalar(actual));
expectedIsScalarText = (ischar(expected) && isrow(expected)) || ...
    (isstring(expected) && isscalar(expected));
value = actualIsScalarText && expectedIsScalarText && ...
    strcmp(string(actual), string(expected));
end

function value = localAllNumericFinite(input)
value = true;
if isstruct(input)
    names = fieldnames(input);
    for index = 1:numel(names)
        value = value && localAllNumericFinite(input.(names{index}));
    end
elseif isnumeric(input)
    value = isreal(input) && all(isfinite(input), 'all');
end
end

function digest = localMeshSha256(coords, connectivity)
hasher = java.security.MessageDigest.getInstance('SHA-256');
hasher.update(typecast(double(coords(:)), 'uint8'));
hasher.update(typecast(int64(connectivity(:)), 'uint8'));
digestBytes = typecast(hasher.digest(), 'uint8');
digest = lower(string(reshape(dec2hex(digestBytes, 2).', 1, [])));
end

function localRequire(condition, message, varargin)
if ~condition
    error('toyRoad:StateValidationFailed', message, varargin{:});
end
end
