function shard = applyContract(shard, contract)
fields = {'mesh_sha256','element_ordering_id','gp_ordering_id', ...
    'state_semantics_id','runtime_lock_sha256','family_contract_sha256', ...
    'case_physics_contract_sha256','execution_input_lock_sha256'};
for index = 1:numel(fields), shard.(fields{index}) = contract.(fields{index}); end
end

function writeJson(path, value), writeText(path, [jsonencode(value) newline]); end
function writeText(path, value)
fileId = fopen(path,'wb'); cleanup = onCleanup(@() fclose(fileId));
fwrite(fileId,unicode2native(value,'UTF-8'),'uint8');
end

function digest = fileSha256(path)
fileId = fopen(path,'rb'); cleanup = onCleanup(@() fclose(fileId));
bytes = fread(fileId,Inf,'*uint8');
hasher = java.security.MessageDigest.getInstance('SHA-256'); hasher.update(bytes);
raw = typecast(hasher.digest(),'uint8');
digest = lower(reshape(dec2hex(raw,2).',1,[]));
end
