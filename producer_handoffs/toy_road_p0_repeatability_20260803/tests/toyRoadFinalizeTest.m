function setupOnce(testCase)
handoff = fileparts(fileparts(mfilename('fullpath')));
addpath(handoff);
testCase.addTeardown(@() rmpath(handoff));
end

function testFinalizesAndValidatesExactPackage(testCase)
[root, contractPath, attemptPath] = makeRawPackage(testCase);
summary = finalize_toy_road_family_package(root, ...
    'T1_initial_defect', contractPath, attemptPath);
verifyTrue(testCase, summary.is_valid);
verifyTrue(testCase, isfile(fullfile(root, 'TERMINAL_MANIFEST.json')));
verifyTrue(testCase, isfile(fullfile(root, 'SHA256SUMS.txt')));
verifyTrue(testCase, isfile(fullfile(root, 'VALIDATION_SUMMARY.json')));
verifyTrue(testCase, validate_toy_road_terminal_package(root, ...
    'T1_initial_defect', contractPath).is_valid);
end

