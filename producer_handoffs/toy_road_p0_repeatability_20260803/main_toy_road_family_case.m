function result = main_toy_road_family_case(varargin)
%MAIN_TOY_ROAD_FAMILY_CASE Build state0 and run one authorized fresh case.

if nargin == 0
    request = localReadEnvironment();
    dependencies = localProductionDependencies();
    injected = false;
elseif nargin == 2
    request = varargin{1};
    dependencies = varargin{2};
    injected = true;
else
    error('toyRoadP0:InvalidDriverRequest', ...
        'Use no inputs for production or request/dependencies for controlled tests.');
end
localValidateRequest(request,injected);
localValidateAuthorization(request,injected);
localValidateDependencies(dependencies);
localValidateFreshRoots(request);
localCreateWritableRoots(request);

parentMesh = dependencies.load_parent_mesh(request.input_assets_root);
cfg = build_toy_road_family_case(request.case_id,parentMesh);
localRequire(cfg.sol_step_par.n_step == 5 && ...
    ~cfg.sol_step_par.line_search && ~cfg.sol_jump_par.cycle_jump && ...
    ~cfg.resume_allowed, 'The built case violates the Hard5 solver contract.');
recoveryInput = dependencies.build_recovery_input(cfg,parentMesh);
[sys,d,dOld,history,recoveryDetails] = ...
    recover_toy_road_family_state(recoveryInput);
state0 = struct( ...
    'd_node',d, ...
    'alpha_bar_gp',history(:,:,2), ...
    'history_vars',history, ...
    'd_node_old',dOld, ...
    'recovery_residual',recoveryDetails.recovery_residual, ...
    'state_semantics_id','fresh_hard_recovered_state0_v2');
runtimeReceipt = dependencies.runtime_receipt(request);
localValidateRuntimeReceipt(runtimeReceipt,request);
localPublishInitialAssets(request,cfg,state0,runtimeReceipt);

recovery = struct('sys',sys,'d',d,'d_old',dOld,'history_vars',history, ...
    'details',recoveryDetails);
context = dependencies.build_solver_context(cfg,recovery,request);
context = localBindApprovedSolverContext(context,cfg,state0,request);
result = dependencies.solve_family_case(context);
end

