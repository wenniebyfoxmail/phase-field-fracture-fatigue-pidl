function localPublishJson(path,payload)
content = [jsonencode(payload) newline];
localPublishBytes(path,unicode2native(content,'UTF-8'));
end

function localPublishBytes(path,bytes)
directory = fileparts(path);
temporary = localReserveTemporary(directory,'.asset_','.tmp');
cleanup = onCleanup(@() localDeleteIfPresent(temporary));
fileId = fopen(temporary,'wb');
if fileId < 0
    error('toyRoadP0:PublicationFailed','Cannot open temporary asset.');
end
fileCleanup = onCleanup(@() fclose(fileId));
count = fwrite(fileId,bytes,'uint8');
if count ~= numel(bytes)
    error('toyRoadP0:PublicationFailed','Cannot write complete temporary asset.');
end
clear fileCleanup
localCreateExclusiveHardLink(temporary,path);
delete(temporary);
clear cleanup
end

function path = localReserveTemporary(directory,prefix,suffix)
try
    attributes = javaArray('java.nio.file.attribute.FileAttribute',0);
    temporary = java.nio.file.Files.createTempFile( ...
        java.io.File(directory).toPath(),prefix,suffix,attributes);
    path = char(temporary.toString());
catch exception
    error('toyRoadP0:PublicationFailed', ...
        'Cannot reserve temporary asset: %s',exception.message);
end
end

function localCreateExclusiveHardLink(temporary,path)
try
    java.nio.file.Files.createLink( ...
        java.io.File(path).toPath(),java.io.File(temporary).toPath());
catch exception
    if isfile(path) || isfolder(path)
        error('toyRoadP0:PublicationClobber', ...
            'Refusing to overwrite published asset: %s',path);
    end
    error('toyRoadP0:PublicationFailed', ...
        'Cannot publish immutable asset: %s',exception.message);
end
end

function localDeleteIfPresent(path)
if isfile(path)
    delete(path);
end
end

function value = localText(value)
value = (ischar(value) && isrow(value) && ~isempty(value)) || ...
    (isstring(value) && isscalar(value) && strlength(value) > 0);
end

function value = localHex(value,lengthRequired)
if ~localText(value)
    value = false;
    return;
end
text = char(value);
value = numel(text) == lengthRequired && ...
    all(ismember(lower(text),'0123456789abcdef'));
end

function localRequire(condition,message)
if ~condition
    error('toyRoadP0:InvalidDriverContext',message);
end
