names = { ...
    'TOY_ROAD_CASE_ROLE', ...
    'TOY_ROAD_SOURCE_COMMIT', ...
    'TOY_ROAD_RUNTIME_LOCK_SHA256', ...
    'TOY_ROAD_FAMILY_CONTRACT_SHA256', ...
    'TOY_ROAD_CASE_PHYSICS_CONTRACT_SHA256', ...
    'TOY_ROAD_EXECUTION_INPUT_LOCK_SHA256', ...
    'TOY_ROAD_OUTPUT_ROOT', ...
    'TOY_ROAD_WORK_ROOT', ...
    'TOY_ROAD_TEMP_ROOT', ...
    'TOY_ROAD_TMP_ROOT', ...
    'TOY_ROAD_PREF_ROOT', ...
    'TOY_ROAD_CACHE_ROOT', ...
    'TOY_ROAD_INPUT_ASSETS_ROOT', ...
    'TOY_ROAD_AUTHORIZATION_RECEIPT'};
values = cellfun(@getenv,names,'UniformOutput',false);
missing = names(cellfun(@(value) isempty(strtrim(value)),values));
if ~isempty(missing)
    error('toyRoadP0:MissingEnvironment', ...
        'Required environment variable is empty: %s',strjoin(missing,', '));
end
authorizationPath = values{14};
if ~isfile(authorizationPath)
    error('toyRoadP0:AuthorizationRejected', ...
        'The launcher authorization receipt is absent.');
end
authorizationReceipt = jsondecode(fileread(authorizationPath));
request = struct( ...
    'authorization_scope',localReceiptScope(authorizationReceipt), ...
    'authorization_receipt',authorizationReceipt, ...
    'case_id',values{1}, ...
    'source_commit',values{2}, ...
