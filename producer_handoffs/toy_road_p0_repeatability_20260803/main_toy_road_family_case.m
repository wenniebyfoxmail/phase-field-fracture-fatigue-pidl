    'family_contract_sha256',lower(values{4}), ...
    'case_physics_contract_sha256',lower(values{5}), ...
    'execution_input_lock_sha256',lower(values{6}), ...
    'output_root',values{7}, ...
    'work_root',values{8}, ...
    'temp_root',values{9}, ...
    'tmp_root',values{10}, ...
    'pref_root',values{11}, ...
    'cache_root',values{12}, ...
    'input_assets_root',values{13});
end

function value = localReceiptScope(receipt)
if ~isstruct(receipt) || ~isscalar(receipt) || ...
        ~isfield(receipt,'authorization_scope')
    error('toyRoadP0:AuthorizationRejected', ...
        'The launcher receipt has no authorization scope.');
end
value = receipt.authorization_scope;
end

function localValidateRequest(request,injected)
required = {'authorization_scope','authorization_receipt','case_id', ...
    'source_commit','runtime_lock_sha256','family_contract_sha256', ...
    'case_physics_contract_sha256','execution_input_lock_sha256', ...
    'output_root','work_root','temp_root','tmp_root','pref_root','cache_root', ...
    'input_assets_root'};
valid = isstruct(request) && isscalar(request) && ...
    isequal(sort(fieldnames(request)),sort(required(:)));
if valid
    roles = {'P0_parent','P0R_parent_repeat','T1_initial_defect', ...
        'T2_material_state','T3_loading_history'};
    valid = localText(request.authorization_scope) && ...
        localText(request.case_id) && any(strcmp(char(request.case_id),roles)) && ...
        localHex(request.source_commit,40) && ...
        localHex(request.runtime_lock_sha256,64) && ...
        localHex(request.family_contract_sha256,64) && ...
        localHex(request.case_physics_contract_sha256,64) && ...
        localHex(request.execution_input_lock_sha256,64) && ...
        isstruct(request.authorization_receipt) && ...
        isscalar(request.authorization_receipt);
    paths = required(9:end);
    for index = 1:numel(paths)
        valid = valid && localText(request.(paths{index}));
    end
end
if ~valid
    error('toyRoadP0:InvalidDriverRequest', ...
        'Driver request fields, identities, or paths are invalid.');
end
if injected && strcmp(char(request.authorization_scope),'production_authorized')
    error('toyRoadP0:AuthorizationRejected', ...
        'Production authorization may only enter through the no-input launcher path.');
end
end

function localValidateAuthorization(request,injected)
scope = char(request.authorization_scope);
if injected
    allowed = strcmp(scope,'test_only_non_authorizing');
else
    allowed = strcmp(scope,'production_authorized');
end
if ~allowed
    error('toyRoadP0:AuthorizationRejected', ...
        'This authorization scope cannot execute the producer driver.');
end
receipt = request.authorization_receipt;
required = {'status','authorization_scope','authorized_entrypoint','case_id', ...
    'source_commit','runtime_lock_sha256','family_contract_sha256', ...
    'case_physics_contract_sha256','execution_input_lock_sha256'};
valid = all(isfield(receipt,required)) && ...
    strcmp(char(receipt.status),'PASS') && ...
    strcmp(char(receipt.authorization_scope),scope) && ...
    strcmp(char(receipt.authorized_entrypoint),'main_toy_road_family_case') && ...
    strcmp(char(receipt.case_id),char(request.case_id)) && ...
    strcmpi(char(receipt.source_commit),char(request.source_commit)) && ...
    strcmpi(char(receipt.runtime_lock_sha256),char(request.runtime_lock_sha256)) && ...
    strcmpi(char(receipt.family_contract_sha256),char(request.family_contract_sha256)) && ...
    strcmpi(char(receipt.case_physics_contract_sha256), ...
        char(request.case_physics_contract_sha256)) && ...
    strcmpi(char(receipt.execution_input_lock_sha256), ...
        char(request.execution_input_lock_sha256));
if ~valid
    error('toyRoadP0:AuthorizationRejected', ...
        'Authorization receipt does not bind this exact execution.');
end
end

function localValidateDependencies(dependencies)
required = {'load_parent_mesh','build_recovery_input','build_solver_context', ...
    'runtime_receipt','solve_family_case'};
valid = isstruct(dependencies) && isscalar(dependencies) && ...
    isequal(sort(fieldnames(dependencies)),sort(required(:)));
for index = 1:numel(required)
    valid = valid && isa(dependencies.(required{index}),'function_handle');
end
if ~valid
    error('toyRoadP0:InvalidDriverDependencies', ...
        'Driver dependencies must contain only the declared callable interfaces.');
end
end

function localValidateFreshRoots(request)
writeFields = {'output_root','work_root','temp_root','tmp_root','pref_root','cache_root'};
canonical = strings(1,numel(writeFields));
for index = 1:numel(writeFields)
    path = char(request.(writeFields{index}));
    canonical(index) = lower(string(java.io.File(path).getCanonicalPath()));
    if isfile(path) || isfolder(path)
        error('toyRoadP0:FreshRootRequired', ...
            'Writable root must be initially absent: %s',path);
    end
end
if numel(unique(canonical)) ~= numel(canonical)
    error('toyRoadP0:FreshRootRequired', ...
        'Output, work, TEMP, TMP, preference, and cache roots must be distinct.');
end
if ~isfolder(request.input_assets_root)
    error('toyRoadP0:InvalidDriverRequest', ...
        'The read-only input-assets root must already exist.');
end
inputCanonical = lower(string(java.io.File( ...
    char(request.input_assets_root)).getCanonicalPath()));
if any(canonical == inputCanonical)
    error('toyRoadP0:FreshRootRequired', ...
        'A writable root cannot alias the input-assets root.');
end
end

function localCreateWritableRoots(request)
fields = {'output_root','work_root','temp_root','tmp_root','pref_root','cache_root'};
for index = 1:numel(fields)
    [created,message] = mkdir(request.(fields{index}));
    if ~created
        error('toyRoadP0:RootCreationFailed', ...
            'Cannot create fresh %s: %s',fields{index},message);
    end
end
end

