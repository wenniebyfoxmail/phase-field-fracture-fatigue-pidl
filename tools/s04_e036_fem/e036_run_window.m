function result=e036_run_window(sys,native_eq,native_pf,par,predecessor,request,policy,budget,authority,out_dir,initial_fields)
%E036_RUN_WINDOW Explicit admitted-predecessor window; no recovery or resume.
% PREPARED SOURCE ONLY: not executed, checkcode-checked or numerically validated.
% Reuses the native Newton/staggered interfaces and E011 c1 arm's predictor.
% Caller must bind sys/functions and admitted predecessor before this entry.
% No target/future-reference argument is accepted. Helpers must be on MATLAB's
% explicitly verified path. External watchdog is mandatory: MATLAB callbacks
% cannot interrupt a long single MEX/CHOLMOD call or an operating-system hang.
if nargin<11,initial_fields=[];end
required(par,{'solver','stag','step','regularize_pf_newton'},'parameters');
required(request,{'cycle','substeps','role'},'request');
assert(isequal(sort(fieldnames(request)),sort({'cycle';'substeps';'role'})), ...
 'E036:Request','Request contains unsupported fields (including future targets)');
integer(request.cycle,1,83);steps=request.substeps(:)';
assert(isnumeric(steps) && isreal(steps) && all(isfinite(steps)) && ...
 all(steps==fix(steps)) && ~isempty(steps),'E036:Steps','Explicit integer substeps required');
main=isequal(string(request.role),"main");tight=isequal(string(request.role),"tightening");oracle=isequal(string(request.role),"nodal_oracle");
allowed=main && ((ismember(request.cycle,[1 83]) && isequal(steps,1:5)) || ...
 (ismember(request.cycle,[20 60]) && isequal(steps,4)));
allowed=allowed || ((tight || oracle) && ismember(request.cycle,[1 83]) && isscalar(steps) && ismember(steps,[2 4]));
assert(allowed,'E036:Scope','Only the declared windows/endpoints/tightening are supported');
assert(oracle==~isempty(initial_fields),'E036:OracleScope','Initial fields are exclusive to declared oracle jobs');
required(authority,{'execution_approved','approval_id','producer_hostname', ...
 'run_id','source_commit','manifest_sha256','native_bindings_verified', ...
 'native_eq_name','native_pf_name','thread_controls_verified','watchdog_id', ...
 'request','solver','stag','policy','budget','binding','predecessor_sha256'},'authority');
assert(isequal(authority.execution_approved,true) && ...
 isequal(authority.native_bindings_verified,true) && ...
 isequal(authority.thread_controls_verified,true) && ...
 strlength(string(authority.approval_id))>0 && strlength(string(authority.watchdog_id))>0, ...
 'E036:Authority','Explicit execution approval, binding, thread and watchdog records required');
assert(strlength(string(getenv('COMPUTERNAME')))>0 && ...
 strcmpi(string(getenv('COMPUTERNAME')),string(authority.producer_hostname)), ...
 'E036:Producer','This entry requires the explicitly authorized Windows producer');
hexstring(authority.source_commit,40);hexstring(authority.manifest_sha256,64);
hexstring(authority.predecessor_sha256,64);
if oracle
 required(authority,{'initial_fields_sha256','initial_source_snapshot_sha256','initial_source_completion_sha256'},'oracle authority');
 hexstring(authority.initial_fields_sha256,64);hexstring(authority.initial_source_snapshot_sha256,64);
end
assert(isequal(authority.request,request) && isequal(authority.solver,par.solver) && ...
 isequal(authority.stag,par.stag) && isequal(authority.policy,policy), ...
 'E036:Authority','Actual request/solver/staggered/policy differs from the approved envelope');
assert(isa(native_eq,'function_handle') && isa(native_pf,'function_handle') && ...
 strcmp(func2str(native_eq),authority.native_eq_name) && ...
 strcmp(func2str(native_pf),authority.native_pf_name), ...
 'E036:Binding','Native function handles do not match the recorded bindings');
required(budget,{'total_timer','total_wall_seconds','window_wall_seconds', ...
 'step_wall_seconds','max_outer','max_threads','authority_file','authority_sha256', ...
 'authority_id','watchdog_id','global_deadline'},'budget');
positive(budget.total_wall_seconds);positive(budget.window_wall_seconds);
positive(budget.step_wall_seconds);integer(budget.max_outer,1,1500);integer(budget.max_threads,1,4);
budget_names={'total_wall_seconds','window_wall_seconds','step_wall_seconds','max_outer','max_threads'};
required(authority.budget,budget_names,'approved budget');
for k=1:numel(budget_names)
 name=budget_names{k};assert(isequal(budget.(name),authority.budget.(name)), ...
  'E036:Authority','Actual budget differs from the approved envelope');
end
assert(isa(budget.total_timer,'uint64') && isscalar(budget.total_timer), ...
 'E036:Budget','total_timer must be the current authorized job tic token');
assert(budget.window_wall_seconds<=budget.total_wall_seconds && ...
 budget.step_wall_seconds<=budget.window_wall_seconds, ...
 'E036:Budget','Step/window timeouts exceed the explicit job guard');
assert(strcmp(budget.authority_id,authority.approval_id) && ...
 strcmp(budget.watchdog_id,authority.watchdog_id), ...
 'E036:Authority','Window and process authority differ');
e036_job_clock(budget,budget.total_timer,budget.total_wall_seconds);
required(par.solver,{'max_iter_displ','tol_displ','max_iter_pf','tol_p_field'},'solver');
integer(par.solver.max_iter_displ,1,500);integer(par.solver.max_iter_pf,1,250);
required(par.stag,{'max_iter','tol'},'staggered');
assert(par.stag.max_iter==budget.max_outer,'E036:Budget','Native outer cap differs from envelope');
u_tol=1e-6;d_tol=4e-4;if tight,u_tol=1e-8;d_tol=4e-6;end
assert(par.solver.tol_displ==u_tol && par.solver.tol_p_field==d_tol && ...
 par.stag.tol==d_tol && isequal(par.regularize_pf_newton,true), ...
 'E036:SolverPolicy','Native tolerances/regularization must match the declared arm');
policy_name='fresh_original_tolerances';if tight,policy_name='fresh_strict_e011';end
assert(isequal(policy,e036_policy(policy_name,'nodal_box_kkt')), ...
 'E036:Policy','Only the exact predeclared common policy is supported');
assert(numel(sys.MAT_CHAR)==1 && sys.stress_state.as_number==1 && strcmp(sys.diss_fct,'AT1'), ...
 'E036:Material','Expected the homogeneous plane-strain AT1 problem');
assert(isfield(sys.GEOM,'t') && isequal(sys.GEOM.t,1) && ...
 all(sys.MESH.elem_material_id==1), ...
 'E036:Material','Common residuals require unit thickness and homogeneous element material IDs');
material_names=fieldnames(policy.expected_material);
for k=1:numel(material_names)
 name=material_names{k};value=policy.expected_material.(name);
 assert(isfield(sys.MAT_CHAR,name) && abs(sys.MAT_CHAR.(name)-value)<=1e-12*max(1,abs(value)), ...
  'E036:Material','Native material differs before the first solve');
end
loads=[.02999988 .05999988 .08999988 .11999988 0];
required(par.step,{'n_step','line_search','ux_increment','uy_increment'},'step');
assert(par.step.n_step==5 && isequal(par.step.line_search,false) && ...
 numel(par.step.ux_increment)==5 && all(par.step.ux_increment==0) && ...
 numel(par.step.uy_increment)==5 && ...
 max(abs(cumsum(par.step.uy_increment(:)')-loads))<=1e-14, ...
 'E036:Loading','Explicit native increments do not match the locked five-step loads');
required(predecessor,{'u','d','lower','history','version','state_key','admission'},'predecessor');
required(predecessor.admission,{'accepted','native_residual_checked','checkpoint_readback_verified', ...
 'predecessor_sha256','state_key','ordered_mesh_sha256_f32_i64'},'admission');
assert(isequal(predecessor.admission.accepted,true) && ...
 isequal(predecessor.admission.native_residual_checked,true) && ...
 isequal(predecessor.admission.checkpoint_readback_verified,true) && ...
 strcmp(predecessor.admission.predecessor_sha256,authority.predecessor_sha256) && ...
 isequal(predecessor.admission.state_key,predecessor.state_key), ...
 'E036:Admission','Admitted predecessor binding is missing or differs');
required(predecessor.state_key,{'trajectory','cycle','substep','displacement','timing', ...
 'nominal_umax','gp_order'},'predecessor key');
prev_cycle=request.cycle;prev_step=steps(1)-1;
if prev_step==0 && request.cycle>1,prev_cycle=request.cycle-1;prev_step=5;end
assert(predecessor.state_key.cycle==prev_cycle && predecessor.state_key.substep==prev_step && ...
 predecessor.version==(request.cycle-1)*5+steps(1)-1 && ...
 strcmp(predecessor.state_key.timing,'post_commit') && predecessor.state_key.nominal_umax==.12 && ...
 strcmp(predecessor.state_key.gp_order,'(+,+),(-,+),(+,-),(-,-)') && ...
 strlength(string(predecessor.state_key.trajectory))>0, ...
 'E036:PredecessorKey','Predecessor is not the declared immediately preceding accepted state');
prev_load=0;if prev_step>0,prev_load=loads(prev_step);end
assert(abs(predecessor.state_key.displacement-prev_load)<=1e-14, ...
 'E036:PredecessorLoad','Predecessor displacement differs from the explicit state key');
bind=authority.binding;
required(bind,{'nodes','cells','Nxi','dNdxi','gauss_W','active_u','active_d', ...
 'fixed_damage_nodes_zero_based','ordered_mesh_sha256_f32_i64'},'support binding');
assert(strcmp(bind.ordered_mesh_sha256_f32_i64,predecessor.admission.ordered_mesh_sha256_f32_i64) && ...
 strcmp(bind.ordered_mesh_sha256_f32_i64,'c675e3fd05399cf16cc56884396f46b2af9e6b8e3c5c349e188246692d8bc174'), ...
 'E036:Mesh','The admitted ordered mesh identity differs');
assert(isequal(size(bind.nodes),[86756 2]) && isequal(size(bind.cells),[86408 4]) && ...
 isequal(sys.MESH.node(:,1:2),bind.nodes) && isequal(sys.MESH.elem(:,1:4),bind.cells) && ...
 sys.MESH.num_node==86756 && sys.MESH.num_elem==86408 && sys.QUADRATURE.num_gauss_pts==4 && ...
 isequal(size(bind.Nxi),[4 4]) && numel(bind.gauss_W)==4 && all(bind.gauss_W>0) && ...
 isequal(sys.QUADRATURE.Nxi,bind.Nxi) && isequal(sys.QUADRATURE.dNdxi,bind.dNdxi) && ...
 isequal(sys.QUADRATURE.gauss_W,bind.gauss_W) && ...
 isequal(sys.DOFS.active_dof(:),bind.active_u(:)) && ...
 isequal(sys.DOFS.active_dof_pf(:),bind.active_d(:)), ...
 'E036:Support','Actual mesh/quadrature/DOFs differ from the admitted support');
fixed_u=setdiff((1:2*86756)',bind.active_u(:));fixed_d=setdiff((1:86756)',bind.active_d(:));
assert(isequal(sort(bind.fixed_damage_nodes_zero_based(:)),[4;5;(695:943)']) && ...
 numel(fixed_d)==251 && isequal(sort(fixed_d),sort(bind.fixed_damage_nodes_zero_based(:)+1)) && ...
 all(predecessor.d(fixed_d)==1),'E036:CrackBC','Common hard-crack DOFs differ');
assert(isequal(size(predecessor.u),[2*86756 1]) && ...
 isequal(size(predecessor.d),[86756 1]) && isequal(predecessor.lower,predecessor.d) && ...
 isequal(size(predecessor.history),[86408 4 4]),'E036:Shape','Native predecessor shape mismatch');
finite(predecessor.u);finite(predecessor.d);finite(predecessor.history);
assert(all(predecessor.d>=0 & predecessor.d<=1) && ...
 all(predecessor.history(:,:,2:3)>=0,'all'),'E036:Domain','Invalid predecessor bounds/history');
old_A=predecessor.history(:,:,2);old_f=min(1,(1./(old_A+.5)).^2);
assert(max(abs(old_f-predecessor.history(:,:,4)),[],'all')<=1e-10, ...
 'E036:History','Admitted predecessor f does not match its accumulated history');
check_bc(predecessor.u,prev_load);
assert(~isfile(out_dir) && ~isfolder(out_dir) && isfolder(fileparts(out_dir)), ...
 'E036:Output','Require a new output directory with an existing parent');
[ok,msg]=mkdir(out_dir);assert(ok,'E036:Output','%s',msg);
window_timer=tic;step_timer=[];accepted=predecessor;initial_version=accepted.version;
stage='prepared';step=0;outer=0;trace=[];candidate=[];last_native=[];e036_audit=[];e036_proposal=[];
pre=accepted;step_dir='';counts=struct('u',0,'d',0);rows=[];
try
 persist(fullfile(out_dir,'input_binding.mat'),struct('predecessor',predecessor, ...
  'request',request,'policy',policy,'par',par,'authority',authority,'budget',budget));
 for step=steps
  step_timer=tic;pre=accepted;outer=0;trace=[];candidate=[];last_native=[];e036_audit=[];e036_proposal=[];
  counts=struct('u',0,'d',0);stage='predecessor';check_time();
  assert(pre.version==(request.cycle-1)*5+step-1,'E036:Version','Window version drift');
  step_dir=fullfile(out_dir,sprintf('c%04d_s%02d',request.cycle,step));
  assert(~isfolder(step_dir) && ~isfile(step_dir),'E036:Output','Never overwrite a step');
  [ok,msg]=mkdir(step_dir);assert(ok,'E036:Output','%s',msg);
  persist(fullfile(step_dir,'predecessor.mat'),struct('pre',pre));
  [kv,~,pre_raw,~]=eq_counted(sys.MESH,sys.DOFS,sys.GEOM.t,sys.QUADRATURE,sys.MAT_CHAR, ...
   sys.CC,pre.u,0.0,pre.d,sys.stress_state.as_number,0.0);
  d_gp=pre.d(sys.MESH.elem(:,1:4))*sys.QUADRATURE.Nxi;
  assert(max(abs((1-d_gp).^2.*pre_raw-pre.history(:,:,3)),[],'all')<=1e-10, ...
   'E036:History','Predecessor active driver differs from its actual native field');
  sys.STIFFNESS_MATRIX.KK=sparse(sys.STIFFNESS_MATRIX.i_row,sys.STIFFNESS_MATRIX.j_col,kv);
  stage='initial_candidate';check_time();
  if oracle
   key=pre.state_key;key.cycle=request.cycle;key.substep=step;key.displacement=loads(step);
   prescribed=zeros(size(pre.u));top=find(sys.MESH.node(:,2)==max(sys.MESH.node(:,2)));
   prescribed(top+sys.MESH.num_node)=loads(step);
   [initial,projection]=e036_initial_candidate(initial_fields,pre,key,fixed_u,prescribed(fixed_u), ...
    fixed_d,authority.initial_source_snapshot_sha256,authority.initial_source_completion_sha256,authority.predecessor_sha256);
   initial_candidate_file=fullfile(step_dir,'initial_candidate.mat');
   persist(initial_candidate_file,struct('initial_fields',initial_fields,'projection',projection));
   initial_candidate_sha256=e036_sha256_file(initial_candidate_file);
   u=initial.u;d=initial.d;traction=zeros(size(u));
   [~,res_u,~,~]=eq_counted(sys.MESH,sys.DOFS,sys.GEOM.t,sys.QUADRATURE,sys.MAT_CHAR, ...
    sys.CC,u,0.0,d,sys.stress_state.as_number,0.0);
  else
   [u,res_u,traction]=phase_field.fem.solver.step.pre_iter_update(step,sys,pre.u,par.step);d=pre.d;
  end
  check_time();assert(all(traction==0),'E036:Traction','Only the declared displacement control is supported');
  check_bc(u,loads(step));
  bc=struct('fixed_u',fixed_u,'fixed_d',fixed_d,'u',u(fixed_u),'d',d(fixed_d));
  table_state=phase_field.fem.solver.stag.vars(par.stag);res_u0=norm(res_u(sys.DOFS.active_dof));
  for outer=1:par.stag.max_iter
   stage='native_equilibrium';check_time();
   [res_u0,res_u,u,raw,~,nonconv]=phase_field.fem.solver.newton_raphson( ...
    @eq_counted,sys,u,0.0,d,0.0,sys.DOFS.active_dof, ...
    sys.STIFFNESS_MATRIX.i_row,sys.STIFFNESS_MATRIX.j_col, ...
    'D_RHS_tract',traction,'max_iter',par.solver.max_iter_displ, ...
    'res_tol',par.solver.tol_displ,'line_search',par.step.line_search);
   candidate=struct('u',u,'d',d,'raw',raw,'scope','last returned native state');
   check_time();assert(isfinite(res_u) && ~nonconv,'E036:NativeU','Native equilibrium did not converge');
   stage='native_phase';
   [rdi,res_d,d,~,inner_history,nonconv]=phase_field.fem.solver.newton_raphson( ...
    @pf_counted,sys,d,pre.lower,raw,pre.history,sys.DOFS.active_dof_pf, ...
    sys.STIFFNESS_MATRIX.i_row_pf,sys.STIFFNESS_MATRIX.j_col_pf, ...
    'max_iter',par.solver.max_iter_pf,'res_tol',par.solver.tol_p_field, ...
    'line_search',par.step.line_search,'regularize_pf_only',par.regularize_pf_newton);
   candidate=struct('u',u,'d',d,'raw',raw,'scope','last returned native state before projection');
   check_time();assert(isfinite(res_d) && ~nonconv,'E036:NativeD','Native phase solve did not converge');
   d=min(max(d,pre.lower),1);if outer==1,res_d0=rdi;end
   stage='native_staggered_refresh';
   [table_state,raw,native_accepted,sys.STIFFNESS_MATRIX.KK]= ...
    phase_field.fem.solver.stag.post_iter_update(@eq_counted,outer,table_state,sys, ...
     traction,d,u,res_d0,res_d,res_u0,par.stag);
   check_time();assert(isequaln(accepted,pre),'E036:Preimage','Accepted predecessor changed during solve');
   candidate=struct('u',u,'d',d,'raw',raw);stage='fresh_acceptance';
   [e036_audit,e036_proposal]=e036_native_candidate(sys,@eq_counted,@pf_counted,u,d,1,pre,bc, ...
    traction,policy,inner_history(:,:,4));
   check_time();
   row=struct('outer',outer,'native_accepted',native_accepted,'joint_pass',e036_audit.joint_pass, ...
    'criterion',e036_audit.criterion,'u_l2',e036_audit.u_free_l2, ...
    'd_raw_l2',e036_audit.d_raw_free_l2,'d_box_l2',e036_audit.d_nodal_box_l2, ...
    'u_calls',counts.u,'d_calls',counts.d);
   if isempty(trace),trace=row;else,trace(end+1)=row;end %#ok<AGROW>
   if e036_audit.joint_pass,break;end
  end
  assert(~isempty(e036_proposal) && e036_audit.joint_pass, ...
   'E036:OuterExhausted','Fresh same-state acceptance not reached; no commit or next step');
  stage='proposal_persistence';check_time();
  assert(isequaln(accepted,pre),'E036:Preimage','Accepted predecessor changed before persistence');
  e036_old=pre;e036_status='validated_proposal_before_native_assignment';e036_trace=trace;
  proposal_file=fullfile(step_dir,'proposal.mat');
  persist(proposal_file,struct('e036_audit',e036_audit,'e036_proposal',e036_proposal, ...
   'e036_old',e036_old,'e036_status',e036_status,'e036_trace',e036_trace));
  stage='candidate_checkpoint';check_time();
  % Native field schema only. Not an original full-cycle solver resume record.
  packet=struct('displ',e036_proposal.u,'p_field',e036_proposal.d, ...
   'p_field_old',e036_proposal.lower,'history_vars_old',e036_proposal.history, ...
   'SOL_CYCL_VAR',struct('n_cycle',request.cycle),'i_step_completed',step, ...
   'e036_checkpoint_scope','conditional-window field schema; no full native resume metadata');
  checkpoint_file=fullfile(step_dir,'step_checkpoint.mat');persist(checkpoint_file,packet);
  stage='readback';check_time();
  [readback,loaded]=e036_verify_persisted(proposal_file,checkpoint_file, ...
   struct('cycle',request.cycle,'substep',step,'n_step',5));
  readback_file=fullfile(step_dir,'readback.mat');
  check_time();persist(readback_file,struct('readback',readback));
  readback_sha256=e036_sha256_file(readback_file);
  key=pre.state_key;key.cycle=request.cycle;key.substep=step;key.displacement=loads(step);
  next=pre;next.u=loaded.displ;next.d=loaded.p_field;next.lower=loaded.p_field_old;
  next.history=loaded.history_vars_old;next.version=pre.version+1;next.state_key=key;
  % The original admission remains in input_binding.mat. Do not relabel it as
  % admission evidence for a newly solved state.
  next.admission=struct('source','verified local window step','readback',readback);
  completion=struct('state_key',key,'pre_version',pre.version,'version',next.version, ...
   'history_commits',1,'checkpoint','step_checkpoint.mat','proposal','proposal.mat', ...
   'readback','readback.mat','proposal_sha256',readback.proposal_sha256, ...
   'checkpoint_sha256',readback.checkpoint_sha256,'readback_sha256',readback_sha256, ...
   'elapsed_seconds',toc(step_timer),'counts',counts);
  if oracle
   completion.initial_candidate='initial_candidate.mat';
   completion.initial_candidate_sha256=initial_candidate_sha256;
   completion.declared_initial_fields_sha256=authority.initial_fields_sha256;
   completion.initial_source_snapshot_sha256=authority.initial_source_snapshot_sha256;
   completion.initial_source_completion_sha256=authority.initial_source_completion_sha256;
  end
  % Save a temporary completion record, then check the exact already-verified
  % files again immediately before publishing it. Do not deserialize again.
  check_time();persist(fullfile(step_dir,'completion.mat'),struct('completion',completion),@verify_publication);
  accepted=next; % Sole accepted-state assignment, using only verified loaded data.
  check_time();
  if isempty(rows),rows=completion;else,rows(end+1)=completion;end %#ok<AGROW>
 end
 check_time();
 result=struct('status','completed','request',request,'rows',rows, ...
  'history_commits',accepted.version-initial_version,'accepted',accepted, ...
  'elapsed_before_publication_seconds',toc(window_timer));
 persist(fullfile(out_dir,'window_result.mat'),struct('result',result),@check_time);
 check_time(); % Final I/O consumes the same envelope; prior commits remain real.
catch ex
 failure=struct('identifier',ex.identifier,'message',ex.message,'stage',stage, ...
  'cycle',request.cycle,'substep',step,'outer',outer,'counts',counts, ...
  'history_commits',accepted.version-initial_version,'accepted_version',accepted.version, ...
  'predecessor_unchanged',isequaln(accepted,pre),'elapsed_seconds',toc(window_timer));
 try
  persist(fullfile(out_dir,'failure.mat'),struct('failure',failure,'accepted',accepted, ...
   'pre',pre,'candidate',candidate,'last_native_input',last_native, ...
   'audit',e036_audit,'proposal',e036_proposal,'trace',trace));
 catch write_error
  try
   warning('E036:FailurePersistence','Could not preserve failure: %s',write_error.message);
  catch
   % Even warning-as-error policy must retain the original native exception.
  end
 end
 rethrow(ex);
end

 function check_time()
  e036_job_clock(budget,budget.total_timer,budget.total_wall_seconds);
  assert(toc(budget.total_timer)<=budget.total_wall_seconds && ...
   toc(window_timer)<=budget.window_wall_seconds && ...
   (isempty(step_timer) || toc(step_timer)<=budget.step_wall_seconds), ...
   'E036:WallBudget','Wall-time cap reached; no retry or continuation');
 end
 function verify_publication()
  check_time();
  assert(strcmp(e036_sha256_file(proposal_file),completion.proposal_sha256) && ...
   strcmp(e036_sha256_file(checkpoint_file),completion.checkpoint_sha256) && ...
   strcmp(e036_sha256_file(readback_file),completion.readback_sha256), ...
   'E036:PublicationDrift','A verified artifact changed before completion publication');
  if oracle
   assert(strcmp(e036_sha256_file(initial_candidate_file),completion.initial_candidate_sha256), ...
    'E036:PublicationDrift','Oracle initial candidate changed before completion publication');
  end
  check_time();
 end
 function [kv,r,raw,h]=eq_counted(varargin)
  check_time();counts.u=counts.u+1;
  last_native=struct('kind','equilibrium input','u',varargin{7},'d',varargin{9}, ...
   'scope','last assembly input; not an unreturned inner solver endpoint');
  [kv,r,raw,h]=native_eq(varargin{:});
  check_time();finite(kv);finite(r);finite(raw);
 end
 function [kv,r,aux,h]=pf_counted(varargin)
  check_time();counts.d=counts.d+1;
  last_native=struct('kind','phase input','d',varargin{7},'lower',varargin{8},'raw',varargin{9}, ...
   'scope','last assembly input; not an unreturned inner solver endpoint');
  [kv,r,aux,h]=native_pf(varargin{:});
