 end
 function check_bc(u,load_value)
  uv=reshape(u,86756,2);y=sys.MESH.node(:,2);bot=y==min(y);top=y==max(y);
  expected_fixed=sort([find(bot);find(top);find(bot)+86756;find(top)+86756]);
  assert(isequal(sort(fixed_u),expected_fixed) && ...
   max(abs(uv(bot|top,1)))<=5e-8 && max(abs(uv(bot,2)))<=5e-8 && ...
   max(abs(uv(top,2)-load_value))<=5e-8, ...
   'E036:BC','Actual boundary DOFs/values do not match the common physical state');
