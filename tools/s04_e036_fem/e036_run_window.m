function required(x,names,label)
assert(isstruct(x) && isscalar(x) && all(isfield(x,names)), ...
 'E036:Schema','Missing fields in %s',label);
end
function positive(x)
assert(isnumeric(x) && isreal(x) && isscalar(x) && isfinite(x) && x>0, ...
 'E036:Value','Expected a finite positive scalar');
end
function integer(x,lo,hi)
positive(x);assert(x==fix(x) && x>=lo && x<=hi,'E036:Integer','Integer outside permitted range');
end
function finite(x)
assert(isnumeric(x) && isreal(x) && ~isempty(x) && all(isfinite(x),'all'), ...
 'E036:Nonfinite','Native numerical array is nonfinite or invalid');
end
function hexstring(x,n)
assert(ischar(x) && isrow(x) && numel(x)==n && all(ismember(x,'0123456789abcdef')), ...
 'E036:Identity','Expected a lower-case hexadecimal identity');
end
function persist(path,packet,before_publish)
tmp=[path '.tmp'];assert(~isfile(path) && ~isfolder(path) && ~isfile(tmp) && ~isfolder(tmp), ...
 'E036:ExistingOutput','Refusing to replace an existing artifact');
save(tmp,'-struct','packet','-v7.3');
if nargin==3,before_publish();end
assert(~isfile(path) && ~isfolder(path),'E036:ExistingOutput','Destination appeared during write');
[ok,msg]=movefile(tmp,path);assert(ok,'E036:Persistence','%s',msg);
end
