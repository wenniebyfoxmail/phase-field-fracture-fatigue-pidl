function e036_stage_a_clock(budget,local_timer,local_cap)
%E036_STAGE_A_CLOCK Cooperative checks; external watchdog covers native calls.
assert(isstruct(budget) && isa(budget.total_timer,'uint64') && ...
 isscalar(budget.total_timer) && budget.total_wall_seconds>0 && ...
 budget.total_wall_seconds<=10800 && budget.max_threads>=1 && ...
 budget.max_threads<=4 && budget.max_threads==fix(budget.max_threads) && ...
 isfield(budget,'watchdog_id') && strlength(string(budget.watchdog_id))>0, ...
 'E036A:Budget','Stage A requires one shared <=3h clock, <=4 threads and watchdog');
assert(toc(budget.total_timer)<budget.total_wall_seconds && ...
 toc(local_timer)<local_cap,'E036A:WallLimit','Stage A wall limit reached; no retry');
end
