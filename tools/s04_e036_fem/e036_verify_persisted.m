function [report,loaded]=e036_verify_persisted(proposal_path,checkpoint_path,expected)
%E036_VERIFY_PERSISTED Read-only accepted-proposal / native-step readback.
% This helper never solves, commits, saves, repairs, or changes either file.
% expected must explicitly contain cycle, substep and n_step. A cycle-end
% checkpoint without i_step_completed is not a substitute for a step record.
% Source schema: audited solve_fatigue_fracture.m, step-checkpoint save block
% at lines 326-340 of source 862992a60edc7f59335365beacb5c71fc8592a7a.
% Prepared 2026-10-21; not executed in MATLAB or checked with checkcode yet.
assert(isstruct(expected) && isscalar(expected) && ...
 all(isfield(expected,{'cycle','substep','n_step'})), ...
 'E036:ExpectedKey','Explicit cycle, substep and n_step are required');
key=[expected.cycle expected.substep expected.n_step];
assert(isnumeric(key) && isreal(key) && numel(key)==3 && ...
 all(isfinite(key)) && all(key==fix(key)) && all(key>=1) && ...
 expected.substep<=expected.n_step, ...
 'E036:ExpectedKey','Invalid physical-step key');
assert(isfile(proposal_path) && isfile(checkpoint_path), ...
 'E036:MissingFile','Both persisted files are required');
proposal_sha256=e036_sha256_file(proposal_path);
checkpoint_sha256=e036_sha256_file(checkpoint_path);
r=load(proposal_path,'e036_status','e036_audit','e036_proposal','e036_old');
c=load(checkpoint_path,'displ','p_field','p_field_old','history_vars_old', ...
 'SOL_CYCL_VAR','i_step_completed');
assert(all(isfield(r,{'e036_status','e036_audit','e036_proposal','e036_old'})), ...
 'E036:ReceiptSchema','Incomplete accepted-proposal receipt');
assert(all(isfield(c,{'displ','p_field','p_field_old','history_vars_old', ...
 'SOL_CYCL_VAR','i_step_completed'})), ...
 'E036:CheckpointSchema','A native step checkpoint is required; do not infer its substep');
assert(isequal(string(r.e036_status),"validated_proposal_before_native_assignment"), ...
 'E036:ReceiptStatus','Only an accepted proposal can be checked by this helper');
a=r.e036_audit;p=r.e036_proposal;o=r.e036_old;
assert(isstruct(a) && isscalar(a) && ...
 all(isfield(a,{'joint_pass','feasible','criterion','policy','u','d', ...
 'raw','f_solve','f_commit','history234_solve','old_version'})) && ...
 isstruct(p) && isscalar(p) && ...
 all(isfield(p,{'u','d','lower','raw','history','pre_version','version'})) && ...
 isstruct(o) && isscalar(o) && all(isfield(o,{'lower','history','version'})), ...
 'E036:ProposalSchema','Incomplete proposal, audit or predecessor');
assert(isequal(a.joint_pass,true) && isequal(a.feasible,true) && ...
 isnumeric(a.criterion) && isscalar(a.criterion) && isfinite(a.criterion) && a.criterion<=1, ...
 'E036:NotAccepted','Receipt does not describe an accepted candidate');
assert(isstruct(c.SOL_CYCL_VAR) && isscalar(c.SOL_CYCL_VAR) && ...
 isfield(c.SOL_CYCL_VAR,'n_cycle') && ...
 isequal(double(c.SOL_CYCL_VAR.n_cycle),double(expected.cycle)) && ...
 isequal(double(c.i_step_completed),double(expected.substep)), ...
 'E036:CheckpointKey','Checkpoint does not have the explicitly requested step key');
old_version=(expected.cycle-1)*expected.n_step+expected.substep-1;
assert(isequal(double(o.version),double(old_version)) && ...
 isequal(double(a.old_version),double(old_version)) && ...
 isequal(double(p.pre_version),double(old_version)) && ...
 isequal(double(p.version),double(old_version+1)), ...
 'E036:Version','Proposal versions do not match the requested physical step');
assertFinite(p.u);assertFinite(p.d);assertFinite(p.lower);
assertFinite(p.raw);assertFinite(p.history);
assertFinite(c.displ);assertFinite(c.p_field);assertFinite(c.p_field_old);
assertFinite(c.history_vars_old);assertFinite(o.lower);assertFinite(o.history);
assert(isequal(p.u,a.u) && isequal(p.d,a.d) && isequal(p.raw,a.raw) && ...
 isequal(p.lower,p.d), ...
 'E036:ProposalIdentity','Proposal and accepted audit fields differ');
assert(isequal(c.displ,p.u) && isequal(c.p_field,p.d) && ...
 isequal(c.p_field_old,p.lower) && isequal(c.history_vars_old,p.history), ...
 'E036:PersistedMismatch','Checkpoint fields differ from the accepted proposal');
assert(size(p.history,3)==4 && isequal(size(o.history),size(p.history)) && ...
 isequal(size(o.lower),size(p.d)), ...
 'E036:HistoryShape','Expected native four-channel history and nodal lower');
assertFinite(a.f_solve);assertFinite(a.f_commit);
assert(isequal(p.history(:,:,4),a.f_commit) && ...
 isequal(size(a.f_solve),size(a.f_commit)), ...
 'E036:HistoryIdentity','Saved history is not the proposed commit history');
assert(isequal(a.policy,e036_policy('fresh_original_tolerances','nodal_box_kkt')) || ...
 isequal(a.policy,e036_policy('fresh_strict_e011','nodal_box_kkt')), ...
 'E036:Policy','Saved policy is not one of the exact predeclared E036 policies');
assertFinite(a.history234_solve);
% Current-output slot 1 is raw only for the audited E036 native kernel:
% fem_live/at1_penalty_fatigue.f90 lines 94-99, SHA-256
% ea7e0bb9def96678115627014f53500c1081a5e892554e1120629a5bfd1702e6.
% This is not a reinterpretation of old E011/legacy slot-1 history semantics.
% Runtime admission must bind the MEX to this kernel before this helper is used.
assert(isequal(size(a.history234_solve),size(p.history(:,:,2:4))) && ...
 max(abs(a.history234_solve-p.history(:,:,2:4)),[],'all')<=a.policy.history_tol && ...
 isequal(p.raw,p.history(:,:,1)), ...
 'E036:HistoryIdentity','Solve/commit histories or stored raw channel disagree');
% Algebra only: the saved final active driver is an input to this check.
% No mesh/GP interpolation is available here to verify that driver from u/d.
old_A=o.history(:,:,2);old_P=o.history(:,:,3);new_P=p.history(:,:,3);
assert(all(old_A>=0 & old_P>=0 & new_P>=0,'all') && all(p.raw>=0,'all'), ...
 'E036:HistoryDomain','History/active/raw channels must be nonnegative');
expected_old_f=min(1,(1./(old_A+.5)).^2);
expected_A=old_A+max(new_P-old_P,0);
expected_f=min(1,(1./(expected_A+.5)).^2);
history_delta=max(abs(expected_A-p.history(:,:,2)),[],'all');
mapping_f_delta=max(abs(expected_f-p.history(:,:,4)),[],'all');
assert(history_delta<=a.policy.history_tol && mapping_f_delta<=a.policy.history_tol && ...
 max(abs(expected_old_f-o.history(:,:,4)),[],'all')<=a.policy.history_tol, ...
 'E036:HistoryMapping','Saved histories do not satisfy the single old-to-new update');
f_delta=max(abs(a.f_solve-a.f_commit),[],'all');
assert(f_delta<=a.policy.history_tol && all(p.d>=0 & p.d<=1 & ...
 p.d>=o.lower-a.policy.bound_tol), ...
 'E036:SavedState','Persisted fields violate the saved consistency or bound checks');
assert(strcmp(proposal_sha256,e036_sha256_file(proposal_path)) && ...
 strcmp(checkpoint_sha256,e036_sha256_file(checkpoint_path)), ...
 'E036:ReadbackDrift','Persisted file changed during load or verification');
report=struct('status','accepted_step_readback_matches_proposal', ...
 'proposal_path',char(proposal_path),'checkpoint_path',char(checkpoint_path), ...
 'proposal_sha256',proposal_sha256,'checkpoint_sha256',checkpoint_sha256, ...
 'cycle',expected.cycle,'substep',expected.substep,'n_step',expected.n_step, ...
 'version',p.version,'f_solve_commit_max_delta',f_delta, ...
 'history_mapping_max_delta',history_delta,'history_f_mapping_max_delta',mapping_f_delta, ...
 'comparison','exact serialized numeric arrays; no tolerance-based field match', ...
 'scope','readback identity and history algebra with saved active driver; no fresh assembly or physical validation', ...
 'native_solves',0,'files_written',0);
loaded=c; % Exactly the arrays checked above; no second unverified file read.
end

function assertFinite(x)
assert(isnumeric(x) && isreal(x) && ~isempty(x) && all(isfinite(x),'all'), ...
 'E036:Nonfinite','Expected a nonempty finite real numeric array');
end
