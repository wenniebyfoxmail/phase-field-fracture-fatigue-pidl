function e036_job_clock(budget,local_timer,local_cap)
%E036_JOB_CLOCK Cooperative checks; external watchdog covers native calls.
assert(isstruct(budget) && all(isfield(budget,{'total_timer','total_wall_seconds', ...
 'max_threads','watchdog_id','authority_file','authority_sha256','authority_id','global_deadline'})) && ...
 isa(budget.total_timer,'uint64') && isscalar(budget.total_timer) && ...
 isscalar(budget.total_wall_seconds) && isfinite(budget.total_wall_seconds) && ...
 budget.total_wall_seconds>0 && budget.max_threads>=1 && ...
 budget.max_threads<=4 && budget.max_threads==fix(budget.max_threads) && ...
 isfield(budget,'watchdog_id') && strlength(string(budget.watchdog_id))>0, ...
 'E036B:Budget','Stage B requires an explicit authority, per-job clock and <=4 threads');
assert(strcmp(e036_sha256_file(budget.authority_file),budget.authority_sha256), ...
 'E036B:AuthorityDrift','Authority changed during this job');
assert(isa(local_timer,'uint64') && isscalar(local_timer) && ...
 isscalar(local_cap) && isfinite(local_cap) && local_cap>0, ...
 'E036B:Budget','A finite independent task timeout is required');
if ~isempty(budget.global_deadline)
 assert(isdatetime(budget.global_deadline) && isscalar(budget.global_deadline) && ...
  ~isnat(budget.global_deadline) && datetime('now','TimeZone','UTC')<budget.global_deadline, ...
  'E036B:WallLimit','Explicit global deadline reached; no retry');
end
assert(toc(budget.total_timer)<budget.total_wall_seconds && ...
 toc(local_timer)<local_cap,'E036B:WallLimit','Per-job wall limit reached; no retry');
end
