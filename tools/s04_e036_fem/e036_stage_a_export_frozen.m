function report=e036_stage_a_export_frozen(sys,binding,pair,budget,output_path)
%E036_STAGE_A_EXPORT_FROZEN One archived c{1,20,60,83}s4, assembly only.
% pair: cycle, target_path/sha256, predecessor_path/sha256, trajectory.
% Historical final fields are common evaluation inputs, not E036 references.
clock=tic;cap=budget.total_wall_seconds;e036_stage_a_clock(budget,clock,cap);
assert(isstruct(pair) && all(isfield(pair,{'cycle','target_path','target_sha256', ...
 'predecessor_path','predecessor_sha256','trajectory'})) && ...
 ismember(pair.cycle,[1 20 60 83]) && strcmp(pair.trajectory,'S04_E011_FEM_Q4_C120'), ...
 'E036A:Pair','Only the four predeclared historical pairs are permitted');
assert(~isfile(output_path) && ~isfolder(output_path) && isfolder(fileparts(output_path)), ...
 'E036A:Output','Frozen export must be a fresh file');
assert(strcmp(e036_sha256_file(pair.target_path),pair.target_sha256) && ...
 strcmp(e036_sha256_file(pair.predecessor_path),pair.predecessor_sha256), ...
 'E036A:InputHash','Historical pair identity differs');
z=load(pair.target_path,'request28_snapshot');p=load(pair.predecessor_path,'request28_snapshot');
assert(isfield(z,'request28_snapshot') && isfield(p,'request28_snapshot'),'E036A:Schema','Missing archived snapshot');
z=z.request28_snapshot;p=p.request28_snapshot;
check_snapshot(z,pair.cycle,4,sys);check_snapshot(p,pair.cycle,3,sys);
nodes=sys.MESH.node(:,1:2);cells=sys.MESH.elem(:,1:4);
u=z.u_node(:);d=z.d_node;old_lower=p.d_node;old_history=p.history_vars_old;
assert(all(isfinite(u)) && all(isfinite(d)) && all(isfinite(old_lower)) && ...
 all(isfinite(old_history(:,:,2:4)),'all'),'E036A:Nonfinite','Invalid archived fields');
assert(all(d>=0 & d<=1 & d>=old_lower-1e-8) && all(old_lower>=0 & old_lower<=1), ...
 'E036A:Bounds','Archived fields violate the common domain');
traction=zeros(size(u));active_u=sys.DOFS.active_dof(:);active_d=sys.DOFS.active_dof_pf(:);
fixed_u=setdiff((1:numel(u))',active_u);fixed_d=setdiff((1:numel(d))',active_d);
fixed_u_values=u(fixed_u);fixed_d_values=d(fixed_d);
eq=str2func('phase_field.mex.fem.assembly.equilibrium.AMOR');
pf=str2func('phase_field.mex.fem.assembly.pf.AT1_PENALTY_FATIGUE');
[~,Ru,raw,~]=e036_stage_a_native_call(eq,budget,clock,cap,sys.MESH,sys.DOFS,sys.GEOM.t, ...
 sys.QUADRATURE,sys.MAT_CHAR,sys.CC,u,0.0,d,sys.stress_state.as_number,0.0);
Ru=Ru-traction;
[~,Rd,~,trial_history]=e036_stage_a_native_call(pf,budget,clock,cap,sys.MESH,sys.DOFS,sys.GEOM.t, ...
 sys.QUADRATURE,sys.MAT_CHAR,sys.CC,d,old_lower,raw,sys.stress_state.as_number,old_history);
assert(all(isfinite(Ru)) && all(isfinite(Rd)) && all(isfinite(raw),'all') && ...
 all(isfinite(trial_history),'all'),'E036A:Nonfinite','Native frozen assembly is nonfinite');
schema='e036_frozen_native_v1';
state_key=physical_key(pair,4,.11999988);predecessor_key=physical_key(pair,3,.08999988);
material=sys.MAT_CHAR;material.thickness=sys.GEOM.t;material.stress_state='plane_strain';
material.split_type='AMOR';material.diss_fct='AT1';quadrature=sys.QUADRATURE;
provenance=struct('binding',binding.options.provenance,'source_checks',binding.options.source_checks, ...
 'binary_checks',binding.options.binary_checks,'pair',pair, ...
 'archive_role','historical common frozen field; not accepted E036 solution', ...
 'u_order','blocked [all X; all Y]','cells_and_dofs','MATLAB one-based', ...
 'history_layout','element, gauss point, channel','native_solves',0,'history_commits',0, ...
 'slot1_note','old history retained as archived; no old-slot1 reinterpretation');
state_key_json=char(jsonencode(state_key));predecessor_key_json=char(jsonencode(predecessor_key));
material_json=char(jsonencode(material));provenance_json=char(jsonencode(provenance));
assert(strcmp(e036_sha256_file(pair.target_path),pair.target_sha256) && ...
 strcmp(e036_sha256_file(pair.predecessor_path),pair.predecessor_sha256), ...
 'E036A:InputDrift','Historical inputs changed during assembly');
e036_stage_a_clock(budget,clock,cap);
save(output_path,'schema','nodes','cells','u','d','old_lower','old_history','raw','Ru','Rd', ...
 'trial_history','active_u','active_d','fixed_u','fixed_d','fixed_u_values','fixed_d_values', ...
 'traction','state_key','predecessor_key','material','quadrature','provenance', ...
 'state_key_json','predecessor_key_json','material_json','provenance_json','-v7.3');
e036_stage_a_clock(budget,clock,cap);
report=struct('path',output_path,'sha256',e036_sha256_file(output_path), ...
 'cycle',pair.cycle,'substep',4,'native_solves',0,'assemblies_u',1,'assemblies_d',1, ...
 'elapsed_seconds',toc(clock),'scope','frozen same-state native arrays; no numerical acceptance claim');
e036_stage_a_clock(budget,clock,cap);
end
function check_snapshot(s,cycle,step,sys)
required={'cycle','substep','load_factor','damage_committed','history_committed','cyclemax_updated', ...
 'node_coords','connectivity','u_node','d_node','history_vars_old'};
assert(all(isfield(s,required)) && s.cycle==cycle && s.substep==step && ...
 s.damage_committed && s.history_committed && s.cyclemax_updated, ...
 'E036A:StateKey','Need the exact archived post-commit physical state');
assert(isequal(s.node_coords,sys.MESH.node(:,1:2)) && ...
 isequal(s.connectivity,sys.MESH.elem(:,1:4)) && isequal(size(s.u_node),[86756 2]) && ...
 isequal(size(s.d_node),[86756 1]) && isequal(size(s.history_vars_old),[86408 4 4]), ...
 'E036A:Support','Archived/native order or field support differs');
loads=[.02999988 .05999988 .08999988 .11999988 0];
assert(abs(s.load_factor*.12-loads(step))<=1e-14,'E036A:Load','Archived scalar load differs');
top=find(abs(sys.MESH.node(:,2)-max(sys.MESH.node(:,2)))<=1e-12);
bot=find(abs(sys.MESH.node(:,2)-min(sys.MESH.node(:,2)))<=1e-12);
assert(max(abs(s.u_node([bot;top],1)))<=5e-8 && max(abs(s.u_node(bot,2)))<=5e-8 && ...
 max(abs(s.u_node(top,2)-loads(step)))<=5e-8,'E036A:BC','Archived displacement BC differs');
fixed=setdiff((1:86756)',sys.DOFS.active_dof_pf(:));
assert(isequal(sort(fixed),[5;6;(696:944)']) && all(s.d_node(fixed)==1),'E036A:BC','Archived crack BC differs');
end
function key=physical_key(pair,step,load)
key=struct('trajectory',pair.trajectory,'nominal_umax',.12,'cycle',pair.cycle,'substep',step, ...
 'displacement',load,'timing','post_commit','gp_order','(+,+),(-,+),(+,-),(-,-)');
end
