function [sys,par,common,binding]=e036_stage_b_context(cfg,options,budget)
%E036_STAGE_B_CONTEXT Rebuild support, load existing E011 U0; never recover.
% This performs native setup/assembly only. No Newton, predictor or training.
% All paths/hashes must be supplied by the producer preflight. E011 U0 is a
% derived stored state, not a Stage0b native checkpoint. No state is invented.
clock=tic;cap=budget.total_wall_seconds;e036_job_clock(budget,clock,cap);
required(options,{'execution_approved','producer_hostname','source_root', ...
 'mesh_file','mesh_sha256','common_file','common_sha256','source_checks', ...
 'binary_checks','thread_controls_verified','provenance'});
assert(isequal(options.execution_approved,true) && ...
 isequal(options.thread_controls_verified,true) && ...
 strcmpi(getenv('COMPUTERNAME'),options.producer_hostname), ...
 'E036B:Authority','Approved Windows producer and thread controls required');
assert(strcmp(e036_sha256_file(options.mesh_file),options.mesh_sha256) && ...
 strcmp(e036_sha256_file(options.common_file),options.common_sha256), ...
 'E036B:InputHash','Input file hash mismatch');
assert(strcmp(options.mesh_sha256,'0e6db55abde5880200e2ce01bfe1a7fbb0d4a827362c15afbadbece111fdcb75') && ...
 strcmp(options.common_sha256,'59a0f81368d0c46a698f94fdfcb32158e96361714d7547f00deed996d4a7c181'), ...
 'E036B:InputIdentity','Only the recorded native Q4 mesh and E011 derived U0 are supported');
for k=1:numel(options.source_checks)
 c=options.source_checks(k);assert(strcmp(e036_sha256_file(fullfile(options.source_root,c.path)),c.sha256), ...
  'E036B:Source','Source identity changed');
end
names=string({options.binary_checks.name});
mandatory=["phase_field.System","phase_field.init.material_characteristic", ...
 "phase_field.init.dofs","phase_field.init.quadrature","phase_field.init.stiffness_matrix", ...
 "phase_field.fem.bc.set_boundaries","phase_field.fem.solver.params", ...
 "phase_field.fem.solver.step.params","phase_field.fem.solver.stag.params", ...
 "phase_field.fem.solver.newton_raphson","phase_field.fem.solver.step.pre_iter_update", ...
 "phase_field.fem.solver.stag.post_iter_update","phase_field.mex.fem.assembly.equilibrium.initial", ...
 "phase_field.mex.fem.assembly.equilibrium.AMOR","phase_field.mex.fem.assembly.pf.AT1_PENALTY_FATIGUE","cholmod2"];
assert(all(ismember(mandatory,names)),'E036B:Binding','Missing actual runtime bindings');
for k=1:numel(options.binary_checks)
 c=options.binary_checks(k);actual=which(c.name);
 assert(strcmpi(canonical(actual),canonical(c.path)) && strcmp(e036_sha256_file(actual),c.sha256), ...
  'E036B:Binding','Actual MATLAB resolution differs from the preflight');
end
z=load(options.common_file,'common','common_meta','initial_KK','node_coords', ...
 'connectivity','free_dof_u','free_dof_d');
required(z,{'common','common_meta','initial_KK','node_coords','connectivity','free_dof_u','free_dof_d'});
required(z.common,{'u','d','lower','raw','history','version'});common=z.common;
assert(common.version==0 && isequal(common.d,common.lower) && ...
 all(common.u==0) && all(common.raw==0,'all') && ...
 all(common.history(:,:,1:3)==0,'all') && all(common.history(:,:,4)==1,'all') && ...
 all(isfinite(common.d)) && all(common.d>=0 & common.d<=1), ...
 'E036B:U0','Stored U0 does not have the declared zero-load reset state');
assert(strcmp(z.common_meta.source_commit,'67942510c38c420c9ebc343e88b781a018cd1c7b'), ...
 'E036B:U0Source','Keep the recorded E011 derived-state source identity');
[MESH,GEOM]=specimen.external.abaqus_import(options.mesh_file,'t',1.0);
assert(isequal(MESH.node(:,1:2),z.node_coords) && isequal(MESH.elem(:,1:4),z.connectivity) && ...
 MESH.num_node==86756 && MESH.num_elem==86408 && MESH.nel==4, ...
 'E036B:Mesh','Stored U0 and actual native mesh differ');
top=find(abs(MESH.node(:,2)-max(MESH.node(:,2)))<=1e-12);
bot=find(abs(MESH.node(:,2)-min(MESH.node(:,2)))<=1e-12);
crack=find(abs(MESH.node(:,2))<=1e-12 & MESH.node(:,1)<=1e-12);
assert(isequal(sort(crack),[5;6;(696:944)']),'E036B:BC','Hard crack nodes differ');
NODE_BOUNDARIES=phase_field.fem.bc.set_boundaries('fix_X',[bot;top], ...
 'fix_Y',bot,'disp_Y',top,'non_hom_pf',crack);
DOFS=phase_field.init.dofs(MESH,NODE_BOUNDARIES);
assert(isequal(DOFS.active_dof,z.free_dof_u) && isequal(DOFS.active_dof_pf,z.free_dof_d), ...
 'E036B:DOFs','Stored and reconstructed native DOFs differ');
QUADRATURE=phase_field.init.quadrature(MESH.dim,'elem_type',phase_field.init.ElementType.QUAD4,'order',2);
MAT_CHAR=phase_field.init.material_characteristic(GEOM.L,'AT1','E',1,'ni',.3, ...
 'Gc',.01,'ell',.01,'res_stiff',0,'alpha_T',.5,'p',2);
policy=e036_policy('fresh_original_tolerances','nodal_box_kkt');
for name=string(fieldnames(policy.expected_material))'
 assert(abs(MAT_CHAR.(name)-policy.expected_material.(name))<=1e-12*max(1,abs(policy.expected_material.(name))), ...
  'E036B:Material','Actual native material differs');
end
required(cfg,{'requested_n_step','loading','discretization','u_max','R', ...
 'max_iter_displacement','max_iter_phase','max_iter_staggered'});
assert(cfg.u_max==.12 && cfg.max_iter_displacement>=1 && cfg.max_iter_displacement<=500 && ...
 cfg.max_iter_phase==250 && cfg.max_iter_staggered==1500,'E036B:Config','Stage B solver cap differs');
par.solver=phase_field.fem.solver.params('tol_displ',1e-6,'tol_p_field',4e-4, ...
 'max_iter_displ',cfg.max_iter_displacement,'max_iter_pf',cfg.max_iter_phase);
par.stag=phase_field.fem.solver.stag.params('tol',4e-4,'max_iter',1500);
par.step=phase_field.fem.solver.step.params('n_step',cfg.requested_n_step, ...
 'loading',cfg.loading,'discretization',cfg.discretization,'uy_final',cfg.u_max,'R',cfg.R,'line_search',false);
assert(par.step.n_step==5 && all(par.step.ux_increment==0) && ...
 max(abs(cumsum(par.step.uy_increment(:)')-[.02999988 .05999988 .08999988 .11999988 0]))<=1e-14, ...
 'E036B:Loads','The actual native cadence differs');
par.regularize_pf_newton=true;
hard=zeros(MESH.num_node,1);hard(crack)=1;
sys=phase_field.System(MAT_CHAR,GEOM,QUADRATURE,DOFS,NODE_BOUNDARIES,par.step, ...
 MESH,phase_field.StressState.PlaneStrain,hard,'AT1');
% Access builds native index/tangent structure once (assembly, no solve).
S=sys.STIFFNESS_MATRIX;
assert(isequal(size(z.initial_KK),size(S.KK)) && all(isfinite(nonzeros(z.initial_KK))), ...
 'E036B:InitialKK','Stored original predictor tangent is invalid');
S.KK=z.initial_KK;sys.STIFFNESS_MATRIX=S;
% System construction is reused support setup only. Stage A validation is
% consumed by the driver; each requested old state is separately admitted by
% e036_stage_b_predecessor. Do not repeat Stage A U0/disabled/frozen checks here.
binding=struct('options',options,'cfg',cfg,'common_meta',z.common_meta, ...
 'common_sha256',options.common_sha256,'mesh_sha256',options.mesh_sha256, ...
 'u0_scope','stored E011 derived U0; support construction only; no recovery', ...
 'native_solves',0,'initial_KK_timing',z.common_meta.initial_KK_timing);
e036_job_clock(budget,clock,cap);
end
function required(s,names)
assert(isstruct(s) && isscalar(s) && all(isfield(s,names)),'E036B:Schema','Required fields missing');
end
function path=canonical(path)
path=char(java.io.File(char(path)).getCanonicalPath());
end
