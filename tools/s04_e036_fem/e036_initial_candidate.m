function [state,projection]=e036_initial_candidate(initial,old,key,fixed_u,u_values,fixed_d,source_sha,completion_sha,predecessor_sha)
%E036_INITIAL_CANDIDATE Explicit projection of the declared L+ endpoint only.
% This changes the initial candidate, never the immutable old damage/history.
allowed={'u','d','state_key','source_snapshot_sha256','predecessor_checkpoint_sha256', ...
 'arm','mapping_mode','complete_endpoint','source_completion_sha256'};
assert(isstruct(initial) && isscalar(initial) && isequal(sort(fieldnames(initial)),sort(allowed')), ...
 'E036:OracleSchema','Initial fields may not carry old/history or unbound extra values');
assert(strcmp(initial.arm,'L+') && strcmp(initial.mapping_mode,'legacy') && ...
 isequal(initial.complete_endpoint,true) && isequal(initial.state_key,key) && ...
 strcmp(initial.source_snapshot_sha256,source_sha) && ...
 strcmp(initial.source_completion_sha256,completion_sha) && ...
 strcmp(initial.predecessor_checkpoint_sha256,predecessor_sha), ...
 'E036:OracleIdentity','Only the predeclared complete L+ endpoint and exact F1 predecessor are supported');
u=initial.u;d=initial.d;
assert(isa(u,'double') && isa(d,'double') && isequal(size(u),size(old.u)) && ...
 isequal(size(d),size(old.d)) && all(isfinite(u)) && all(isfinite(d)), ...
 'E036:OracleUnavailable','Missing/nonfinite endpoint cannot be replaced by another initial guess');
assert(isequal(old.d,old.lower) && all(old.lower>=0 & old.lower<=1), ...
 'E036:OraclePreimage','Immutable F1 predecessor bounds required');
raw_u=u;raw_d=d;u(fixed_u)=u_values;d=min(max(d,old.lower),1);d(fixed_d)=1;
du=u-raw_u;dd=d-raw_d;
state=struct('u',u,'d',d);
projection=struct('raw_u',raw_u,'raw_d',raw_d,'projected_u',u,'projected_d',d, ...
 'u_max_abs_change',max(abs(du)),'u_l2_change',norm(du),'u_changed_count',nnz(du), ...
 'd_max_abs_change',max(abs(dd)),'d_l2_change',norm(dd),'d_changed_count',nnz(dd), ...
 'state_key',key,'source_snapshot_sha256',source_sha,'source_completion_sha256',completion_sha,'predecessor_checkpoint_sha256',predecessor_sha, ...
 'rule','common displacement/hard-crack BC and nodal [immutable old damage,1]', ...
 'history_commits',0,'recovery_solves',0,'source_arm','L+');
end
