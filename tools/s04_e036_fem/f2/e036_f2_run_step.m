function result=e036_f2_run_step(sys,eq,pf,par,pre,request,policy,budget,authority,limits,out_dir)
%E036_F2_RUN_STEP One isolated c1s4 method, same original load predictor.
% Local preparation only. No execution is implied. Reuses original E036
% proposal/readback semantics; completion is expressly F2, never primary F1.
assert(isequal(request,struct('cycle',1,'substeps',4,'role','f2_solver')) || ...
 (request.cycle==1 && isequal(request.substeps(:)',4) && strcmp(request.role,'f2_solver')));
assert(isequal(authority.request,request) && isequal(authority.policy,policy) && ...
 isequal(authority.limits,limits) && strcmp(authority.method,'F2-frozen-f-nodal-box-u-d-u'));
assert(authority.execution_approved && authority.native_bindings_verified && authority.thread_controls_verified && ...
 strcmpi(getenv('COMPUTERNAME'),authority.producer_hostname) && ...
 strcmp(func2str(eq),authority.native_eq_name) && strcmp(func2str(pf),authority.native_pf_name));
assert(strcmp(authority.predecessor_sha256,'36193d74aba9b0d894524a391271412068bd8ebd220ce5d8b074d795f7eb937b') && ...
 strcmp(pre.admission.predecessor_sha256,authority.predecessor_sha256) && ...
 isequal(pre.admission.state_key,pre.state_key));
assert(isequal(policy,e036_policy('fresh_strict_e011','nodal_box_kkt')) && ...
 pre.version==3 && pre.state_key.cycle==1 && pre.state_key.substep==3 && ...
 abs(pre.state_key.displacement-.08999988)<=1e-14 && strcmp(pre.state_key.timing,'post_commit'));
assert(numel(sys.MAT_CHAR)==1 && sys.stress_state.as_number==1 && strcmp(sys.diss_fct,'AT1') && ...
 sys.GEOM.t==1 && all(sys.MESH.elem_material_id==1));
assert(isequal(size(sys.MESH.node(:,1:2)),[86756 2]) && isequal(size(sys.MESH.elem(:,1:4)),[86408 4]) && ...
 isequal(size(pre.u),[173512 1]) && isequal(size(pre.d),[86756 1]) && isequal(size(pre.history),[86408 4 4]) && ...
 isequal(pre.lower,pre.d) && all(pre.d>=0 & pre.d<=1));
b=authority.binding;
assert(isequal(b.nodes,sys.MESH.node(:,1:2)) && isequal(b.cells,sys.MESH.elem(:,1:4)) && ...
 isequal(b.Nxi,sys.QUADRATURE.Nxi) && isequal(b.dNdxi,sys.QUADRATURE.dNdxi) && ...
 isequal(b.gauss_W,sys.QUADRATURE.gauss_W) && isequal(b.active_u(:),sys.DOFS.active_dof(:)) && ...
 isequal(b.active_d(:),sys.DOFS.active_dof_pf(:)) && ...
 strcmp(b.ordered_mesh_sha256_f32_i64,pre.admission.ordered_mesh_sha256_f32_i64));
loads=[.02999988 .05999988 .08999988 .11999988 0];
assert(par.step.n_step==5 && ~par.step.line_search && all(par.step.ux_increment==0) && ...
 max(abs(cumsum(par.step.uy_increment(:)')-loads))<=1e-14);
assert(budget.max_threads==4 && budget.max_outer==1500 && limits.max_outer==1500 && ...
 limits.u_maxeval==250 && limits.d_maxeval==250 && limits.d_inner_tol==4e-8 && limits.f_tol==1e-10 && ...
 budget.total_wall_seconds==86400 && budget.step_wall_seconds==43200);
fixed_u=setdiff((1:numel(pre.u))',sys.DOFS.active_dof(:));
fixed_d=setdiff((1:numel(pre.d))',sys.DOFS.active_dof_pf(:));
assert(isequal(sort(fixed_d),[5;6;(696:944)']) && all(pre.d(fixed_d)==1));
y=sys.MESH.node(:,2);bot=find(y==min(y));top=find(y==max(y));
assert(isequal(sort(fixed_u),sort([bot;top;bot+86756;top+86756])));
assert(~isfolder(out_dir) && ~isfile(out_dir) && isfolder(fileparts(out_dir)));
assert(java.io.File(char(out_dir)).mkdir());
clock=tic;accepted=pre;initial_version=pre.version;stage='input_binding';result=[];out=[];
counts=struct('predictor_native_u',0,'predictor_factorizations',0);predictor=[];
step_dir=fullfile(out_dir,'c0001_s04');assert(java.io.File(step_dir).mkdir());
try
 check();persist(fullfile(out_dir,'input_binding.mat'),struct('predecessor',pre,'request',request, ...
  'policy',policy,'par',par,'authority',authority,'budget',budget,'limits',limits));
 persist(fullfile(step_dir,'predecessor.mat'),struct('pre',pre));
 stage='original_load_predictor';counts.predictor_native_u=counts.predictor_native_u+1;check();
 [kv,~,raw,~]=eq(sys.MESH,sys.DOFS,sys.GEOM.t,sys.QUADRATURE,sys.MAT_CHAR,sys.CC, ...
  pre.u,0.0,pre.d,sys.stress_state.as_number,0.0);check();
 assert(all(isfinite(kv)) && all(isfinite(raw),'all'));
 dgp=pre.d(sys.MESH.elem(:,1:4))*sys.QUADRATURE.Nxi;
 assert(max(abs((1-dgp).^2.*raw-pre.history(:,:,3)),[],'all')<=1e-10);
 sys.STIFFNESS_MATRIX.KK=sparse(sys.STIFFNESS_MATRIX.i_row,sys.STIFFNESS_MATRIX.j_col,kv);
 counts.predictor_factorizations=counts.predictor_factorizations+1;
 [u,~,traction]=phase_field.fem.solver.step.pre_iter_update(4,sys,pre.u,par.step);d=pre.d;check();
 assert(all(traction==0) && all(u([bot;top])==0) && all(u(bot+86756)==0) && ...
  all(u(top+86756)==loads(4)) && all(isfinite(u)));
 bc=struct('fixed_u',fixed_u,'fixed_d',fixed_d,'u',u(fixed_u),'d',d(fixed_d));
 predictor=struct('u',u,'d',d,'traction',traction,'bc',bc, ...
  'method','original native step.pre_iter_update at immutable F1 c1s3 stiffness', ...
  'source_function',which('phase_field.fem.solver.step.pre_iter_update'), ...
  'source_sha256',e036_sha256_file(which('phase_field.fem.solver.step.pre_iter_update')), ...
  'history_commits',0,'predecessor_sha256',authority.predecessor_sha256,'counts',counts);
 predictor_file=fullfile(step_dir,'initial_predictor.mat');persist(predictor_file,struct('predictor',predictor));
 predictor_sha256=e036_sha256_file(predictor_file);
 stage='f2_coupled_candidate';out=e036_f2_solve(sys,eq,pf,u,d,pre,bc,traction,policy,budget,limits,@progress);check();
 assert(out.accepted && out.audit.joint_pass && ~isempty(out.proposal) && ...
  out.predecessor_unchanged && out.history_commits==0 && out.trace(end).f_consistent, ...
  'E036F2:NotAccepted','F2 stopped without acceptance: %s',out.status);
 assert(isequaln(accepted,pre),'E036F2:Preimage','Accepted state changed during candidate solve');
 stage='proposal_persistence';
 e036_audit=out.audit;e036_proposal=out.proposal;e036_old=pre;
 e036_status='validated_proposal_before_native_assignment';e036_trace=out.trace;
 proof=struct('schema','e036-f2-c1s4-proof-v1','method',out.method,'accepted',true, ...
  'f_delta_max',out.trace(end).f_delta_max,'limits',limits,'validations',out.validations, ...
  'counts',out.counts,'predictor_counts',counts,'initial_predictor_sha256',predictor_sha256, ...
  'predecessor_sha256',authority.predecessor_sha256,'primary_F1_replacement',false);
 proposal_file=fullfile(step_dir,'proposal.mat');
 persist(proposal_file,struct('e036_audit',e036_audit,'e036_proposal',e036_proposal, ...
  'e036_old',e036_old,'e036_status',e036_status,'e036_trace',e036_trace,'f2_proof',proof));
 packet=struct('displ',e036_proposal.u,'p_field',e036_proposal.d,'p_field_old',e036_proposal.lower, ...
  'history_vars_old',e036_proposal.history,'SOL_CYCL_VAR',struct('n_cycle',1),'i_step_completed',4, ...
  'e036_checkpoint_scope','F2 method-specific c1s4 field schema; not primary F1 or full native resume');
 checkpoint_file=fullfile(step_dir,'step_checkpoint.mat');persist(checkpoint_file,packet);
 stage='readback';[readback,loaded]=e036_verify_persisted(proposal_file,checkpoint_file,struct('cycle',1,'substep',4,'n_step',5));
 q=load(proposal_file,'f2_proof');assert(isequaln(q.f2_proof,proof) && proof.f_delta_max<=limits.f_tol);
 readback_file=fullfile(step_dir,'readback.mat');persist(readback_file,struct('readback',readback));
 key=pre.state_key;key.substep=4;key.displacement=loads(4);
 next=pre;next.u=loaded.displ;next.d=loaded.p_field;next.lower=loaded.p_field_old;
 next.history=loaded.history_vars_old;next.version=4;next.state_key=key;
 next.admission=struct('source','verified F2 local c1s4 step','readback',readback);
 completion=struct('schema','e036-f2-c1s4-completion-v1','method',out.method,'state_key',key, ...
  'pre_version',3,'version',4,'history_commits',1,'checkpoint','step_checkpoint.mat','proposal','proposal.mat', ...
  'readback','readback.mat','proposal_sha256',readback.proposal_sha256, ...
  'checkpoint_sha256',readback.checkpoint_sha256,'readback_sha256',e036_sha256_file(readback_file), ...
  'initial_predictor','initial_predictor.mat','initial_predictor_sha256',predictor_sha256, ...
  'f2_proof',proof,'elapsed_seconds',toc(clock),'primary_F1_replacement',false);
 stage='publication';persist(fullfile(step_dir,'completion.mat'),struct('completion',completion),@verify);
 accepted=next; % Sole accepted-state assignment, from exact verified readback.
 result=struct('status','f2_completed','method',out.method,'request',request,'completion',completion, ...
  'history_commits',accepted.version-initial_version,'accepted',accepted, ...
  'elapsed_seconds',toc(clock),'primary_F1_replacement',false);
 persist(fullfile(out_dir,'f2_result.mat'),struct('result',result));check();
catch ex
 failure=struct('identifier',ex.identifier,'message',ex.message,'stage',stage, ...
  'history_commits',accepted.version-initial_version,'predecessor_unchanged',isequaln(accepted,pre), ...
  'elapsed_seconds',toc(clock),'retry_permitted',false,'primary_F1_replacement',false);
 try,persist(fullfile(out_dir,'failure.mat'),struct('failure',failure,'accepted',accepted, ...
  'pre',pre,'candidate_result',out,'predictor_counts',counts));catch save_ex
  warning('E036F2:FailurePersistence','Could not save failure: %s',save_ex.message);
 end
 rethrow(ex);
end
 function check()
  e036_job_clock(budget,budget.total_timer,budget.total_wall_seconds);
  assert(toc(clock)<=budget.step_wall_seconds,'E036F2:Time','Step anti-hang limit');
 end
 function progress(q)
  check();assert(q.history_commits==0 && q.no_history_commit);
  path=fullfile(out_dir,'progress.jsonl');fid=fopen(path,'a','n','UTF-8');assert(fid>=0);
  closer=onCleanup(@()fclose(fid)); %#ok<NASGU>
  fprintf(fid,'%s\n',jsonencode(q));[msg,err]=ferror(fid);assert(err==0,'E036F2:Progress','%s',msg);
 end
 function verify()
  check();assert(strcmp(e036_sha256_file(proposal_file),completion.proposal_sha256) && ...
   strcmp(e036_sha256_file(checkpoint_file),completion.checkpoint_sha256) && ...
   strcmp(e036_sha256_file(readback_file),completion.readback_sha256) && ...
   strcmp(e036_sha256_file(predictor_file),completion.initial_predictor_sha256));check();
 end
end
function persist(path,packet,before)
tmp=[path '.tmp'];assert(~isfile(path) && ~isfolder(path) && ~isfile(tmp) && ~isfolder(tmp));
save(tmp,'-struct','packet','-v7.3');if nargin==3,before();end
assert(~isfile(path) && ~isfolder(path));[ok,msg]=movefile(tmp,path);assert(ok,'E036F2:Save','%s',msg);
end
