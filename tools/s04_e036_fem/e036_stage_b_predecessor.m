function [pre,report]=e036_stage_b_predecessor(sys,eq,pf,common,binding,spec,request,budget,out_dir)
%E036_STAGE_B_PREDECESSOR Load exact fields, inspect current residual, read back.
% No solve/recovery, no projection, no history-channel repair and no commit.
required(spec,{'kind','path','sha256','state_key'});
allowed={'kind','path','sha256','state_key','origin_file','origin_sha256', ...
 'proposal_file','proposal_sha256','completion_file','completion_sha256', ...
 'main_window_result_file','main_window_result_sha256'};
assert(all(ismember(fieldnames(spec),allowed)),'E036B:Predecessor','Unsupported input (including future target)');
assert(~isfolder(out_dir) && ~isfile(out_dir) && isfolder(fileparts(out_dir)), ...
 'E036B:Output','Fresh predecessor output required');
assert(java.io.File(char(out_dir)).mkdir(),'E036B:Output','Could not create predecessor output');
key=spec.state_key;required(key,{'trajectory','nominal_umax','cycle','substep','displacement','timing','gp_order'});
first=request.substeps(1);pc=request.cycle;ps=first-1;
if ps==0 && pc>1,pc=pc-1;ps=5;end
loads=[.02999988 .05999988 .08999988 .11999988 0];load_value=0;
if ps>0,load_value=loads(ps);end
assert(key.cycle==pc && key.substep==ps && key.nominal_umax==.12 && ...
 abs(key.displacement-load_value)<=1e-14 && strcmp(key.timing,'post_commit') && ...
 strcmp(key.gp_order,'(+,+),(-,+),(+,-),(-,-)') && strlength(string(key.trajectory))>0, ...
 'E036B:PredecessorKey','Exact immediately preceding physical state required');
version=(request.cycle-1)*5+first-1;clock=tic;pre=[];audit=[];report=[];
try
 checked(spec.path,spec.sha256);origin=[];
 switch char(spec.kind)
  case 'stored_u0'
   assert(pc==1 && ps==0 && version==0 && strcmp(spec.sha256,binding.common_sha256) && ...
    strcmpi(canonical(spec.path),canonical(binding.options.common_file)), ...
    'E036B:U0','Only the explicitly bound stored E011 derived U0 is supported');
   pre=struct('u',common.u,'d',common.d,'lower',common.lower,'history',common.history, ...
    'version',0,'state_key',key);origin=binding.common_meta;
  case 'request28_post_commit'
   required(spec,{'origin_file','origin_sha256'});checked(spec.origin_file,spec.origin_sha256);
   origin=jsondecode(fileread(spec.origin_file));
   required(origin,{'schema','source_sha256','producer_source_path','state_key','provenance_ref'});
   assert(strcmp(origin.schema,'e036-predecessor-origin-v1') && strcmp(origin.source_sha256,spec.sha256) && ...
    isequal(origin.state_key,key) && strlength(string(origin.producer_source_path))>0 && ...
    strlength(string(origin.provenance_ref))>0 && strcmp(key.trajectory,'S04_E011_FEM_Q4_C120'), ...
    'E036B:Origin','Original E011 source path, bytes and physical key must be explicitly traced');
   z=load(spec.path,'request28_snapshot');required(z,{'request28_snapshot'});z=z.request28_snapshot;
   required(z,{'cycle','substep','load_factor','damage_committed','history_committed','cyclemax_updated', ...
    'node_coords','connectivity','u_node','d_node','history_vars_old'});
   assert(z.cycle==pc && z.substep==ps && z.damage_committed && z.history_committed && z.cyclemax_updated && ...
    abs(z.load_factor*.12-load_value)<=1e-14 && ...
    isequal(z.node_coords,sys.MESH.node(:,1:2)) && isequal(z.connectivity,sys.MESH.elem(:,1:4)) && ...
    isequal(size(z.u_node),[86756 2]),'E036B:Snapshot','Exact post-commit snapshot/mesh required');
   pre=struct('u',z.u_node(:),'d',z.d_node,'lower',z.d_node,'history',z.history_vars_old, ...
    'version',version,'state_key',key);
  case 'verified_window_step'
   required(spec,{'proposal_file','proposal_sha256','completion_file','completion_sha256'});
   checked(spec.proposal_file,spec.proposal_sha256);checked(spec.completion_file,spec.completion_sha256);
   q=load(spec.completion_file,'completion');required(q,{'completion'});q=q.completion;
   assert(isequal(q.state_key,key) && q.version==version && q.history_commits==1 && ...
    strcmp(q.proposal_sha256,spec.proposal_sha256) && strcmp(q.checkpoint_sha256,spec.sha256), ...
    'E036B:Completion','Verified predecessor completion identity differs');
   assert(strcmp(q.checkpoint,'step_checkpoint.mat') && strcmp(q.proposal,'proposal.mat') && ...
    strcmp(q.readback,'readback.mat'),'E036B:Completion','Unexpected completion file names');
   folder=fileparts(spec.completion_file);
   assert(strcmpi(canonical(spec.path),canonical(fullfile(folder,q.checkpoint))) && ...
    strcmpi(canonical(spec.proposal_file),canonical(fullfile(folder,q.proposal))), ...
    'E036B:Completion','Completion paths do not name the supplied files');
   checked(fullfile(folder,q.readback),q.readback_sha256);
   if strcmp(request.role,'tightening')
    required(spec,{'main_window_result_file','main_window_result_sha256'});
    checked(spec.main_window_result_file,spec.main_window_result_sha256);
    w=load(spec.main_window_result_file,'result');required(w,{'result'});w=w.result;
    assert(strcmp(w.status,'completed') && strcmp(w.request.role,'main') && ...
     w.request.cycle==83 && isequal(w.request.substeps(:)',1:5) && w.history_commits==5, ...
     'E036B:Tightening','A completed main c83 window is required');
    row=find(arrayfun(@(x)x.state_key.substep==3,w.rows));
    assert(isscalar(row) && strcmp(w.rows(row).checkpoint_sha256,spec.sha256) && ...
     strcmp(w.rows(row).proposal_sha256,spec.proposal_sha256), ...
     'E036B:Tightening','Tightening must reuse the exact main c83s3 predecessor');
   end
   [origin,z]=e036_verify_persisted(spec.proposal_file,spec.path,struct('cycle',pc,'substep',ps,'n_step',5));
   pre=struct('u',z.displ,'d',z.p_field,'lower',z.p_field_old,'history',z.history_vars_old, ...
    'version',version,'state_key',key);
  otherwise
   error('E036B:Predecessor','Unsupported predecessor source; no inferred cycle-end state');
 end
 save(fullfile(out_dir,'loaded_preimage.mat'),'pre','spec','origin','-v7.3');
 assert(isequal(size(pre.u),[173512 1]) && isequal(size(pre.d),[86756 1]) && ...
  isequal(pre.lower,pre.d) && isequal(size(pre.history),[86408 4 4]), ...
  'E036B:Shape','Predecessor must contain the exact blocked fields and four history channels');
 assert(isa(pre.u,'double') && isa(pre.d,'double') && isa(pre.history,'double') && ...
  all(isfinite(pre.u)) && all(isfinite(pre.d)) && all(isfinite(pre.history),'all'), ...
  'E036B:Nonfinite','All archived channels must be finite; never repair slot 1');
 assert(all(pre.d>=0 & pre.d<=1) && all(pre.history(:,:,2:3)>=0,'all'), ...
  'E036B:Domain','Invalid predecessor domain');
 A=pre.history(:,:,2);assert(max(abs(min(1,(1./(A+.5)).^2)-pre.history(:,:,4)),[],'all')<=1e-10, ...
  'E036B:History','Stored fatigue mapping is inconsistent');
 y=sys.MESH.node(:,2);bot=find(y==min(y));top=find(y==max(y));uv=reshape(pre.u,86756,2);
 fixed_u=setdiff((1:numel(pre.u))',sys.DOFS.active_dof(:));
 fixed_d=setdiff((1:numel(pre.d))',sys.DOFS.active_dof_pf(:));
 assert(isequal(sort(fixed_d),[5;6;(696:944)']) && all(pre.d(fixed_d)==1) && ...
  isequal(sort(fixed_u),sort([bot;top;bot+86756;top+86756])) && ...
  max(abs(uv([bot;top],1)))<=5e-8 && max(abs(uv(bot,2)))<=5e-8 && ...
  max(abs(uv(top,2)-load_value))<=5e-8,'E036B:BC','Actual predecessor boundaries differ');
 bc=struct('fixed_u',fixed_u,'fixed_d',fixed_d,'u',pre.u(fixed_u),'d',pre.d(fixed_d));
 policy=e036_policy('fresh_original_tolerances','nodal_box_kkt');
 eq_checked=@(varargin)e036_stage_a_native_call(eq,budget,clock,budget.total_wall_seconds,varargin{:});
 pf_checked=@(varargin)e036_stage_a_native_call(pf,budget,clock,budget.total_wall_seconds,varargin{:});
 [audit,~]=e036_native_candidate(sys,eq_checked,pf_checked,pre.u,pre.d,1,pre,bc,zeros(size(pre.u)),policy,[]);
 save(fullfile(out_dir,'native_admission.mat'),'audit','-v7.3');
 dgp=pre.d(sys.MESH.elem(:,1:4))*sys.QUADRATURE.Nxi;
 delta=max(abs((1-dgp).^2.*audit.raw-pre.history(:,:,3)),[],'all');
 assert(audit.joint_pass && delta<=1e-10,'E036B:Admission', ...
  'Predecessor current native residual or active-driver identity failed; no solve/recovery');
 checked(spec.path,spec.sha256);
 if isfield(spec,'origin_file'),checked(spec.origin_file,spec.origin_sha256);end
 if isfield(spec,'proposal_file'),checked(spec.proposal_file,spec.proposal_sha256);end
 if isfield(spec,'completion_file'),checked(spec.completion_file,spec.completion_sha256);end
 pre.admission=struct('accepted',true,'native_residual_checked',true, ...
  'checkpoint_readback_verified',true,'predecessor_sha256',spec.sha256,'state_key',key, ...
  'ordered_mesh_sha256_f32_i64','c675e3fd05399cf16cc56884396f46b2af9e6b8e3c5c349e188246692d8bc174');
 packet_path=fullfile(out_dir,'admitted_predecessor.mat');save(packet_path,'pre','-v7.3');
 packet_sha=e036_sha256_file(packet_path);loaded=load(packet_path,'pre');
 assert(isequaln(loaded.pre,pre) && strcmp(packet_sha,e036_sha256_file(packet_path)), ...
  'E036B:Readback','Persisted admitted predecessor differs from checked fields');
 pre=loaded.pre; % The returned fields are exactly those checked after persistence.
 report=struct('status','admitted_current_native_predecessor','source',spec,'admission',pre.admission, ...
  'packet_path',packet_path,'packet_sha256',packet_sha,'native_solves',0,'history_commits',0, ...
  'active_driver_max_delta',delta,'u_free_l2',audit.u_free_l2,'joint_criterion',audit.criterion, ...
  'readback_scope','exact local admitted preimage; not a full native resume checkpoint');
 save(fullfile(out_dir,'admission_report.mat'),'report','-v7.3');
 e036_stage_a_clock(budget,clock,budget.total_wall_seconds);
catch original
 failure=struct('identifier',original.identifier,'message',original.message,'native_solves',0,'retry_permitted',false);
 try,save(fullfile(out_dir,'failure.mat'),'failure','pre','audit','spec','-v7.3');catch,end
 rethrow(original);
end
end
function checked(path,sha)
assert(strcmp(e036_sha256_file(path),sha),'E036B:InputHash','Bound input changed');
end
function required(s,names)
assert(isstruct(s) && isscalar(s) && all(isfield(s,names)),'E036B:Schema','Required fields missing');
end
function p=canonical(p)
p=char(java.io.File(char(p)).getCanonicalPath());
end
