function assertResultStopPolicy(result, spec)
if ~isfield(result, 'producer') || ~isstruct(result.producer) || ...
        ~isfield(result.producer, 'completed_cycle') || ...
        ~isfield(result.producer, 'penetration')
    error('phase_field:audit:MissingIndependentStopEvidence', ...
        'The producer result lacks the frozen U0.1225 stopping evidence.');
end
event = result.producer.penetration;
required = ["first_hit_cycle", "confirmed_event_cycle"];
if ~isstruct(event) || ~all(isfield(event, required))
    error('phase_field:audit:MissingIndependentStopEvidence', ...
        'The producer penetration record is incomplete.');
end
completed = double(result.producer.completed_cycle);
first_hit = double(event.first_hit_cycle);
confirmed = double(event.confirmed_event_cycle);
if ~(isscalar(completed) && isfinite(completed) && completed >= 1 && ...
        completed <= spec.max_cycle)
    error('phase_field:audit:IndependentCycleCapViolation', ...
        'The producer exceeded the frozen U0.1225 c163 cap.');
end
if ~(isscalar(first_hit) && isfinite(first_hit) && ...
        first_hit >= 1 && first_hit <= spec.first_hit_last_cycle)
    error('phase_field:audit:IndependentFirstHitWindowViolation', ...
        ['The sealed archive is rejected: the frozen production path requires a ', ...
         'first penetration hit in c1--c160.']);
end
expected_confirmation = first_hit + spec.confirmation_cycles;
if ~(isscalar(confirmed) && confirmed == expected_confirmation && ...
        completed == confirmed)
    error('phase_field:audit:IndependentConfirmationMismatch', ...
        'The U0.1225 archive does not have the frozen three-cycle confirmation stop.');
end
end
