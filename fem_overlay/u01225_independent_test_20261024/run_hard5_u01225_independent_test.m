function result = run_hard5_u01225_independent_test()
%RUN_HARD5_U01225_INDEPENDENT_TEST Launch the one source-bound U0.1225 case.
%
% This function is a launch-only overlay.  It must be copied to a dedicated
% Windows launcher directory outside both the producer snapshot and output
% root.  It does not modify the snapshot and rejects a pre-existing output.

spec = hard5_u01225_independent_spec();
requireWindowsProducer();
assertCustodyContext(spec);
assertAbsent(spec.output_root, 'Independent output root');
assertDistinctPaths(fileparts(mfilename('fullpath')), spec.snapshot_root, ...
    'Overlay directory must be outside the frozen source snapshot.');
assertDistinctPaths(fileparts(mfilename('fullpath')), spec.output_root, ...
    'Overlay directory must be outside the FEM output root.');
assertDistinctPaths(spec.snapshot_root, spec.output_root, ...
    'Frozen source snapshot and independent FEM output root must not overlap.');

addpath(fullfile(spec.snapshot_root, 'Sources'), '-begin');
addpath(fullfile(spec.snapshot_root, 'Scripts', 'fatigue_fracture'), '-begin');
assertFrozenSnapshot(spec);
qualification = assertQualificationAuthority(spec);
assertNoForeignMatlab();

cfg = buildBoundConfiguration(spec, qualification);
options = struct( ...
    'case_root', fullfile(spec.output_root, spec.output_identity), ...
    'max_cycle', double(spec.max_cycle), ...
    'qualification_cycle', [], ...
    'execution_mode', "production_new", ...
    'validate_only', false, ...
    'command_line', "hard5 U0.1225 production_new single_run run_id=" + spec.run_id + ...
        " full_native_q4");

result = run_hard5_stage0b_case(cfg, options);
if ~isfield(result, 'run_id') || string(result.run_id) ~= string(spec.run_id)
    error('phase_field:audit:NewHard5RunIdMismatch', ...
        'The U0.1225 producer did not preserve the frozen run ID.');
end
if ~isfield(result, 'status') || string(result.status) ~= "sealed"
    error('phase_field:audit:Stage0bCaseNotSealed', ...
        'The U0.1225 independent condition did not produce a sealed archive.');
end
assertResultStopPolicy(result, spec);
end

function assertCustodyContext(spec)
lock_path = string(getenv('FW_U01225_CUSTODY_LOCK_PATH'));
if strlength(lock_path) == 0 || ~isfile(lock_path)
    error('phase_field:audit:IndependentCustodyRequired', ...
        ['This U0.1225 overlay may only run through the prepared custody ', ...
         'wrapper with its immutable launch lock.']);
end
if lower(canonicalPath(fileparts(lock_path))) ~= lower(canonicalPath(spec.custody_root))
    error('phase_field:audit:IndependentCustodyPath', ...
        'The custody lock must reside directly in the pinned custody root.');
end
launcher_root = canonicalPath(fileparts(mfilename('fullpath')));
if lower(launcher_root) ~= lower(canonicalPath(fullfile(spec.custody_root, 'launcher')))
    error('phase_field:audit:IndependentCustodyLauncherPath', ...
        'The overlay must execute only from the custody-protected launcher path.');
end
try
    lock = jsondecode(fileread(lock_path));
catch cause
    error('phase_field:audit:IndependentCustodyLockUnreadable', ...
        'The custody launch lock is unavailable: %s', cause.message);
end
required = ["schema", "candidate_id", "run_id", "output_root", "state", ...
    "policy_sha256", "input_bundle_manifest_sha256", ...
    "prelaunch_custody_evidence_sha256", "scoring_protocol_sha256", ...
    "strict_test_role_status"];
if ~isstruct(lock) || ~all(isfield(lock, required)) || ...
        string(lock.schema) ~= "fixed_weight_u01225_custody_launch_lock_v1" || ...
        string(lock.candidate_id) ~= "hard5_u01225_independent_test" || ...
        string(lock.run_id) ~= string(spec.run_id) || ...
        lower(string(lock.output_root)) ~= lower(string(spec.output_root)) || ...
        string(lock.state) ~= "launch_authorized" || ...
        string(lock.strict_test_role_status) ~= "STRICT_TEST_CUSTODY_READY"
    error('phase_field:audit:IndependentCustodyLockInvalid', ...
        'The custody launch lock does not bind this one permitted condition.');
end
policy_path = fullfile(launcher_root, 'custody_policy.json');
manifest_path = fullfile(launcher_root, 'SHA256SUMS.txt');
if ~isfile(policy_path) || ~isfile(manifest_path) || ...
        sha256ControlFile(policy_path) ~= lower(string(lock.policy_sha256)) || ...
        sha256ControlFile(manifest_path) ~= lower(string(lock.input_bundle_manifest_sha256))
    error('phase_field:audit:IndependentCustodyBundleMismatch', ...
        'The custody lock is not bound to the launcher policy and payload manifest.');
end
try
    policy = jsondecode(fileread(policy_path));
catch cause
    error('phase_field:audit:IndependentCustodyPolicyUnreadable', ...
        'The custody policy is unavailable: %s', cause.message);
end
if ~isstruct(policy) || ~isfield(policy, 'policy_status') || ...
        ~isfield(policy, 'candidate') || ...
        string(policy.policy_status) ~= "PRE_RESULT_CUSTODY_READY" || ...
        ~isfield(policy, 'strict_test_role_status') || ...
        string(policy.strict_test_role_status) ~= "STRICT_TEST_CUSTODY_READY" || ...
        ~isstruct(policy.candidate) || ...
        ~isfield(policy.candidate, 'candidate_id') || ...
        ~isfield(policy.candidate, 'run_id') || ...
        ~isfield(policy.candidate, 'split') || ...
        string(policy.candidate.candidate_id) ~= string(lock.candidate_id) || ...
        string(policy.candidate.run_id) ~= string(lock.run_id) || ...
        string(policy.candidate.split) ~= "independent_test" || ...
        ~isfield(policy, 'paths') || ...
        ~isfield(policy.paths, 'archive_root_relative') || ...
        ~isfield(policy.paths, 'launcher_relative') || ...
        ~isfield(policy.paths, 'receipt_relative') || ...
        string(policy.paths.archive_root_relative) ~= "archive_root" || ...
        string(policy.paths.launcher_relative) ~= "launcher" || ...
        string(policy.paths.receipt_relative) ~= "receipts" || ...
        ~isfield(policy, 'release') || ...
        ~isfield(policy.release, 'scoring_protocol') || ...
        ~isfield(policy.release.scoring_protocol, 'relative_path') || ...
        ~isfield(policy.release.scoring_protocol, 'sha256') || ...
        string(policy.release.scoring_protocol.relative_path) ~= "scoring_protocol.json" || ...
        ~isfield(policy, 'prelaunch_custody_evidence') || ...
        ~isfield(policy.prelaunch_custody_evidence, 'relative_path') || ...
        ~isfield(policy.prelaunch_custody_evidence, 'sha256') || ...
        ~isfield(policy.prelaunch_custody_evidence, 'status') || ...
        string(policy.prelaunch_custody_evidence.relative_path) ~= "prelaunch_custody_evidence.json" || ...
        string(policy.prelaunch_custody_evidence.status) ~= "PRE_RESULT_CUSTODY_EVIDENCE_READY" || ...
        ~isfield(policy.release, 'scoring_release_wrapper') || ...
        ~isfield(policy.release.scoring_release_wrapper, 'relative_path') || ...
        ~isfield(policy.release.scoring_release_wrapper, 'sha256') || ...
        string(policy.release.scoring_release_wrapper.relative_path) ~= "run_u01225_scoring_release.ps1"
    error('phase_field:audit:IndependentCustodyPolicyInvalid', ...
        'The launcher policy does not permit this independent-test launch.');
end
scoring_protocol_path = fullfile(launcher_root, 'scoring_protocol.json');
evidence_path = fullfile(launcher_root, 'prelaunch_custody_evidence.json');
scoring_release_wrapper_path = fullfile(launcher_root, 'run_u01225_scoring_release.ps1');
if ~isfile(scoring_protocol_path) || ...
        sha256ControlFile(scoring_protocol_path) ~= ...
            lower(string(policy.release.scoring_protocol.sha256)) || ...
        ~isfile(evidence_path) || ...
        sha256ControlFile(evidence_path) ~= ...
            lower(string(policy.prelaunch_custody_evidence.sha256)) || ...
        ~isfile(scoring_release_wrapper_path) || ...
        sha256ControlFile(scoring_release_wrapper_path) ~= ...
            lower(string(policy.release.scoring_release_wrapper.sha256)) || ...
        lower(string(lock.prelaunch_custody_evidence_sha256)) ~= ...
            lower(string(policy.prelaunch_custody_evidence.sha256)) || ...
        lower(string(lock.scoring_protocol_sha256)) ~= ...
            lower(string(policy.release.scoring_protocol.sha256))
    error('phase_field:audit:IndependentCustodyControlBindingMismatch', ...
        'The custody lock is not bound to its prelaunch evidence and scoring controls.');
end
try
    scoring_protocol = jsondecode(fileread(scoring_protocol_path));
catch cause
    error('phase_field:audit:IndependentCustodyScoringProtocolUnreadable', ...
        'The scoring protocol is unavailable: %s', cause.message);
end
try
    prelaunch_evidence = jsondecode(fileread(evidence_path));
catch cause
    error('phase_field:audit:IndependentCustodyEvidenceUnreadable', ...
        'The prelaunch custody evidence is unavailable: %s', cause.message);
end
if ~isstruct(prelaunch_evidence) || ...
        ~isfield(prelaunch_evidence, 'evidence_status') || ...
        ~isfield(prelaunch_evidence, 'candidate') || ...
        ~isfield(prelaunch_evidence.candidate, 'candidate_id') || ...
        ~isfield(prelaunch_evidence.candidate, 'run_id') || ...
        string(prelaunch_evidence.evidence_status) ~= "PRE_RESULT_CUSTODY_EVIDENCE_READY" || ...
        string(prelaunch_evidence.candidate.candidate_id) ~= string(lock.candidate_id) || ...
        string(prelaunch_evidence.candidate.run_id) ~= string(lock.run_id)
    error('phase_field:audit:IndependentCustodyEvidenceInvalid', ...
        'The prelaunch custody evidence does not bind this independent-test launch.');
end
if ~isstruct(scoring_protocol) || ...
        ~isfield(scoring_protocol, 'status') || ...
        ~isfield(scoring_protocol, 'candidate') || ...
        ~isfield(scoring_protocol.candidate, 'candidate_id') || ...
        ~isfield(scoring_protocol.candidate, 'run_id') || ...
        ~isfield(scoring_protocol.candidate, 'split') || ...
        string(scoring_protocol.status) ~= "PRECOMMITTED_NO_MODEL_OR_SCORE" || ...
        string(scoring_protocol.candidate.candidate_id) ~= string(lock.candidate_id) || ...
        string(scoring_protocol.candidate.run_id) ~= string(lock.run_id) || ...
        string(scoring_protocol.candidate.split) ~= "independent_test"
    error('phase_field:audit:IndependentCustodyScoringProtocolInvalid', ...
        'The scoring protocol does not bind this independent-test condition.');
end
end

function digest = sha256ControlFile(path)
try
    path = string(path);
    if contains(path, "'")
        error('phase_field:audit:IndependentCustodyControlPath', ...
            'A custody control path cannot contain a quote.');
    end
    command = sprintf(['powershell -NoProfile -Command ', ...
        '"(Get-FileHash -LiteralPath ''%s'' -Algorithm SHA256).Hash"'], char(path));
    [status, output] = system(command);
    digest = lower(strtrim(string(output)));
    if status ~= 0 || isempty(regexp(char(digest), '^[0-9a-f]{64}$', 'once'))
        error('phase_field:audit:IndependentCustodyControlHash', ...
            'PowerShell could not hash a custody control file.');
    end
catch cause
    error('phase_field:audit:IndependentCustodyBundleHashUnavailable', ...
        'Could not hash a custody control file: %s', cause.message);
end
end

function cfg = buildBoundConfiguration(spec, qualification)
loaded = load(fullfile(spec.qualification_case_root, ...
    'provenance', 'config_receipt.mat'), 'config_receipt');
if ~isfield(loaded, 'config_receipt') || ~isstruct(loaded.config_receipt) || ...
        ~isscalar(loaded.config_receipt)
    error('phase_field:audit:InvalidFrozenHard5Authority', ...
        'The sealed qualification config receipt is unavailable.');
end
q = loaded.config_receipt;
copy_names = ["initial_crack","initialization","recovery_projection", ...
    "rebuild_sys_after_recovery","reset_fatigue_after_recovery", ...
    "loading","discretization","u_max","R","res_stiff","alpha_T", ...
    "pf_tol","staggered_tol","displacement_tol", ...
    "max_iter_displacement","max_iter_phase","max_iter_staggered", ...
    "requested_n_step","n_step","nominal_load_factor","solver_loadfun", ...
    "effective_load_factor","nominal_uy","effective_uy", ...
    "penetration_right_x_min","penetration_threshold", ...
    "penetration_min_nodes","penetration_confirm_cycles"];
if ~all(isfield(q, copy_names))
    error('phase_field:audit:InvalidFrozenHard5Authority', ...
        'The qualification config lacks a locked Hard5 control.');
end

cfg = struct('case_label', "Hard5 native-Q4 production template", ...
    'reference_dir', "", 'driver_path', "", 'event_evidence_path', "", ...
    'output_identity', "__unbound__", 'run_id', "__unbound__", ...
    'execution_mode', "production_new");
for name = copy_names
    cfg.(name) = q.(name);
end
cfg.requested_cycles = 1;
cfg.defer_stop_until_cycle = 1;
assertQualificationControls(cfg, spec);

cfg.u_max = spec.u_max;
cfg.nominal_uy = spec.nominal_uy;
cfg.effective_uy = spec.effective_uy;
cfg.output_identity = spec.output_identity;
cfg.run_id = spec.run_id;
cfg.configuration_authority = qualification;
cfg.allowed_delta_fields = ["u_max","nominal_uy","effective_uy", ...
    "output_identity","run_id"];
cfg.delta_receipt = struct( ...
    'qualified_source_commit', string(spec.source_commit), ...
    'qualification_case_root', string(spec.qualification_case_root), ...
    'qualification_manifest_sha256', string(qualification.qualification_manifest_sha256), ...
    'qualification_config_sha256', string(qualification.qualification_config_sha256), ...
    'changed_fields', cfg.allowed_delta_fields);
end

function authority = assertQualificationAuthority(spec)
required = ["SHA256SUMS.txt","validation_receipt.json", ...
    "provenance\source_receipt.json","provenance\config_receipt.mat", ...
    "run_summary.json"];
if ~isfolder(spec.qualification_case_root)
    error('phase_field:audit:InvalidFrozenHard5Authority', ...
        'The pinned U0.12 qualification case root is absent.');
end
if numel(spec.qualification_files) ~= numel(required) || ...
        ~isequal(string({spec.qualification_files.path})', required')
    error('phase_field:audit:InvalidOverlaySpecification', ...
        'The overlay qualification-file contract is malformed.');
end
for k = 1:numel(spec.qualification_files)
    item = spec.qualification_files(k);
    path = fullfile(spec.qualification_case_root, item.path);
    if ~isfile(path) || phase_field.audit.sha256_file(path) ~= string(item.sha256)
        error('phase_field:audit:InvalidFrozenHard5Authority', ...
            'The pinned U0.12 qualification artifact is absent or changed: %s', path);
    end
end
receipt = jsondecode(fileread(fullfile(spec.qualification_case_root, ...
    'validation_receipt.json')));
source = jsondecode(fileread(fullfile(spec.qualification_case_root, ...
    'provenance', 'source_receipt.json')));
summary = jsondecode(fileread(fullfile(spec.qualification_case_root, ...
    'run_summary.json')));
valid_receipt = isfield(receipt, 'passed') && logical(receipt.passed) && ...
    isfield(receipt, 'reference_checked') && logical(receipt.reference_checked) && ...
    isfield(receipt, 'capture_neutrality_passed') && ...
    logical(receipt.capture_neutrality_passed) && ...
    isfield(receipt, 'run_id') && string(receipt.run_id) == string(spec.qualification_run_id);
valid_source = isfield(source, 'source_commit') && ...
    lower(string(source.source_commit)) == lower(string(spec.source_commit)) && ...
    isfield(source, 'source_dirty') && ~logical(source.source_dirty);
valid_summary = isfield(summary, 'provenance') && isstruct(summary.provenance) && ...
    isfield(summary.provenance, 'run_id') && ...
    string(summary.provenance.run_id) == string(spec.qualification_run_id) && ...
    isfield(summary.provenance, 'source_commit') && ...
    lower(string(summary.provenance.source_commit)) == lower(string(spec.source_commit)) && ...
    isfield(summary.provenance, 'source_dirty') && ~logical(summary.provenance.source_dirty);
if ~(valid_receipt && valid_source && valid_summary)
    error('phase_field:audit:InvalidFrozenHard5Authority', ...
        'The pinned U0.12 qualification provenance is not a clean neutral c1 authority.');
end
authority = struct( ...
    'qualification_case_root', string(spec.qualification_case_root), ...
    'qualified_source_commit', string(spec.source_commit), ...
    'qualification_manifest_sha256', string(spec.qualification_files(1).sha256), ...
    'qualification_config_sha256', string(spec.qualification_files(4).sha256));
end

function assertQualificationControls(cfg, spec)
expected_solver_loadfun = [1e-6, 0.25, 0.5, 0.75, 1.0, 1e-6];
expected_effective = expected_solver_loadfun(2:end) - expected_solver_loadfun(1);
valid = string(cfg.initial_crack) == "hard" && ...
    string(cfg.initialization) == "separate_zero_load_phase_recovery" && ...
    string(cfg.recovery_projection) == "clip_[0,1]" && ...
    ~logical(cfg.rebuild_sys_after_recovery) && logical(cfg.reset_fatigue_after_recovery) && ...
    string(cfg.loading) == "cyclic" && string(cfg.discretization) == "loading" && ...
    sameNumber(cfg.u_max, 0.12) && sameNumber(cfg.R, 0) && ...
    sameNumber(cfg.res_stiff, 0) && sameNumber(cfg.alpha_T, 0.5) && ...
    sameNumber(cfg.pf_tol, 4e-4) && sameNumber(cfg.staggered_tol, 4e-4) && ...
    sameNumber(cfg.displacement_tol, 1e-6) && ...
    sameNumber(cfg.max_iter_displacement, 250) && ...
    sameNumber(cfg.max_iter_phase, 250) && sameNumber(cfg.max_iter_staggered, 1000) && ...
    sameNumber(cfg.requested_n_step, 8) && sameNumber(cfg.n_step, 5) && ...
    sameNumber(cfg.nominal_load_factor, spec.nominal_load_factor) && ...
    sameNumber(cfg.solver_loadfun, expected_solver_loadfun) && ...
    sameNumber(cfg.effective_load_factor, expected_effective) && ...
    sameNumber(cfg.nominal_uy, 0.12 .* spec.nominal_load_factor) && ...
    sameNumber(cfg.effective_uy, 0.12 .* expected_effective) && ...
    sameNumber(cfg.penetration_right_x_min, 0.48) && ...
    sameNumber(cfg.penetration_threshold, 0.95) && ...
    sameNumber(cfg.penetration_min_nodes, 3) && ...
    sameNumber(cfg.penetration_confirm_cycles, spec.confirmation_cycles) && ...
    sameNumber(cfg.requested_cycles, 1) && sameNumber(cfg.defer_stop_until_cycle, 1);
if ~valid
    error('phase_field:audit:InvalidFrozenHard5Authority', ...
        'The pinned U0.12 config differs from the locked Hard5 controls.');
end
end

function assertFrozenSnapshot(spec)
if ~isfolder(spec.snapshot_root)
    error('phase_field:audit:FrozenProducerSnapshotMissing', ...
        'The pinned producer snapshot is absent.');
end
[status, commit] = system(sprintf('git -C "%s" rev-parse HEAD', spec.snapshot_root));
[dirty_status, dirty] = system(sprintf('git -C "%s" status --porcelain', spec.snapshot_root));
if status ~= 0 || dirty_status ~= 0 || ...
        lower(strtrim(string(commit))) ~= lower(string(spec.source_commit)) || ...
        strlength(strtrim(string(dirty))) ~= 0
    error('phase_field:audit:UnqualifiedNewHard5Producer', ...
        'The producer snapshot must be clean and equal the pinned commit.');
end
for k = 1:numel(spec.snapshot_files)
    item = spec.snapshot_files(k);
    path = fullfile(spec.snapshot_root, item.path);
    if ~isfile(path) || phase_field.audit.sha256_file(path) ~= string(item.sha256)
        error('phase_field:audit:FrozenProducerSnapshotChanged', ...
            'A pinned producer file is absent or changed: %s', path);
    end
end
end

function assertNoForeignMatlab()
current_pid = feature('getpid');
command = sprintf(['powershell -NoProfile -Command "$all=@(Get-CimInstance Win32_Process); ', ...
    '$related=New-Object ''System.Collections.Generic.HashSet[int]''; ', ...
    '[void]$related.Add(%d); ', ...
    '$changed=$true; while($changed){$changed=$false; foreach($node in $all){', ...
    'if($related.Contains([int]$node.ParentProcessId) -and -not $related.Contains([int]$node.ProcessId)){', ...
    '[void]$related.Add([int]$node.ProcessId); $changed=$true}}}; ', ...
    '$cursor=%d; while($cursor -gt 0){', ...
    '$node=$all | Where-Object ProcessId -eq $cursor | Select-Object -First 1; ', ...
    'if(-not $node){break}; $cursor=[int]$node.ParentProcessId; ', ...
    '$parent=$all | Where-Object ProcessId -eq $cursor | Select-Object -First 1; ', ...
    'if($parent -and $parent.Name -match ''^MATLAB(\.exe)?$''){', ...
    '[void]$related.Add([int]$parent.ProcessId)}}; ', ...
    '$p=$all | Where-Object { $_.Name -match ''^MATLAB(\.exe)?$'' -and ', ...
    '-not $related.Contains([int]$_.ProcessId) }; ', ...
    'if($p){$p | Select-Object ProcessId,ParentProcessId,CommandLine ', ...
    '| ConvertTo-Json -Compress; exit 7}else{exit 0}"'], current_pid, current_pid);
[status, output] = system(command);
if status == 0
    return;
end
if status == 7
    error('phase_field:audit:Stage0bExperimentAlreadyRunning', ...
        'Detected another MATLAB/FEM process: %s', strtrim(output));
end
error('phase_field:audit:Stage0bProcessProbeFailed', ...
    'Could not establish whether another MATLAB/FEM experiment is active.');
end

function assertAbsent(path, label)
if isfolder(path) || isfile(path)
    error('phase_field:audit:Stage0bOutputRootAlreadyExists', ...
        '%s must be absent: %s', label, path);
end
end

function assertDistinctPaths(first, second, message)
first = lower(canonicalPath(first));
second = lower(canonicalPath(second));
separator = string(filesep);
if first == second || startsWith(first, second + separator) || ...
        startsWith(second, first + separator)
    error('phase_field:audit:Stage0bPathIsolationViolation', '%s', message);
end
end

