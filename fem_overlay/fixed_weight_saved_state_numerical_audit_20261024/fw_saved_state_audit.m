function verifyTargetDisplacementBoundary(u_node, binding, imposed_displacement, path)
if ~isa(u_node, 'double') || ~isreal(u_node) || ~all(isfinite(u_node(:))) || ...
        ~isscalar(imposed_displacement) || ~isfinite(imposed_displacement)
    error('fixed_weight:numerical_audit:TargetBoundaryType', ...
        'Target displacement or imposed load is malformed: %s', path);
end
precision = 8 * eps('double') * max(abs(double(imposed_displacement)), realmin('double'));
checks = { ...
    u_node(binding.fix_x, 1), zeros(numel(binding.fix_x), 1), 'fix_X/u_x'; ...
    u_node(binding.fix_y, 2), zeros(numel(binding.fix_y), 1), 'fix_Y/u_y'; ...
    u_node(binding.disp_x, 1), zeros(numel(binding.disp_x), 1), 'disp_X/u_x'; ...
    u_node(binding.disp_y, 2), double(imposed_displacement) .* ones(numel(binding.disp_y), 1), 'disp_Y/u_y' ...
    };
for index = 1:size(checks, 1)
    delta = abs(checks{index, 1} - checks{index, 2});
    if any(delta > precision)
        error('fixed_weight:numerical_audit:TargetBoundary', ...
            ['Target displacement violates reconstructed %s constraints at %s ', ...
             '(max abs %.17g; precision bound %.17g).'], ...
            checks{index, 3}, path, max(delta), precision);
    end
end
end


