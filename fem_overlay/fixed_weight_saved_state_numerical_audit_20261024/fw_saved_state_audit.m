function relative = normalizeArchiveRelative(value)
relative = replace(string(value), char(92), '/');
if ~isscalar(relative) || strlength(relative) == 0 || ...
        strlength(strtrim(relative)) ~= strlength(relative) || ...
        startsWith(relative, '/') || hasWindowsDrivePrefix(relative) || ...
        contains(relative, ':')
    error('fixed_weight:numerical_audit:ArchiveRelativePath', ...
        'Archive-relative path is malformed or absolute: %s', string(value));
end
pieces = split(relative, '/');
if any(pieces == "" | pieces == "." | pieces == "..")
    error('fixed_weight:numerical_audit:ArchiveRelativePath', ...
        'Archive-relative path contains an empty or traversal component: %s', relative);
end
relative = join(pieces, '/');
end


