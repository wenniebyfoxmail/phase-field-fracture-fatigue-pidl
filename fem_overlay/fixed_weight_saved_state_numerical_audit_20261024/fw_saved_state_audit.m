    'manifest_sha256', string(lock.manifest_sha256), ...
    'manifest_member_count', numel(manifest), 'provenance', provenance, ...
    'logical_state_count', height(index), 'payload_inventory', inventory, ...
    'matlab_authoritative', true, 'payloads_decoded', false);
admission.index = index;
end


