function admission = verifyArchiveAdmission(root, lock)
% This is the authoritative, MATLAB-side archive admission check.  It hashes
% every manifest member and validates topology/provenance before MATLAB loads a
% static or dynamic MAT payload.  Python is a supplemental cross-check only.
root = canonicalPath(root);
if ~isfolder(root)
    error('fixed_weight:numerical_audit:ArchiveRoot', 'Archive root is not a directory: %s', root);
end
[~, archive_name] = fileparts(root);
if string(archive_name) ~= string(lock.name)
    error('fixed_weight:numerical_audit:ArchiveName', ...
        'Archive root does not match its immutable lock: %s', root);
end
manifest = parseArchiveManifest(root, lock.manifest_sha256);
verifyManifestMembers(manifest);
verifyLockedFiles(root, lock, manifest);
provenance = verifyArchiveProvenance(root, lock);
