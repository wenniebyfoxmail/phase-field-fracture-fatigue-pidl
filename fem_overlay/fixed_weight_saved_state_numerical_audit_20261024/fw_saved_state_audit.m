function result = evaluateSavedTransition(system_state, previous, target)
% The source has no Neumann DOFs in this locked archive, hence D_RHS=0 exactly.
sys = system_state.sys;
external = zeros(sys.DOFS.num_dof, 1);
u = target.u_node(:);
converged = struct('displ', u, 'p_field', target.d_node, ...
    'strain_en_undgr', target.strain_en_undgr_gp);
frozen = struct('p_field_old', previous.d_node, ...
    'history_vars_old', previous.history_gp, 'load_factor', target.metadata.effective_load_factor);
equilibrium = system_state.equilibrium;
phase = system_state.phase;
[~, r_u_assembled, psi_recomputed, ~] = equilibrium( ...
    sys.MESH, sys.DOFS, sys.GEOM.t, sys.QUADRATURE, sys.MAT_CHAR, sys.CC, ...
    converged.displ, 0.0, converged.p_field, sys.stress_state.as_number, ...
    frozen.history_vars_old);
if ~isa(r_u_assembled, 'double') || ~isreal(r_u_assembled) || ...
        ~all(isfinite(r_u_assembled(:))) || ~iscolumn(r_u_assembled) || ...
        numel(r_u_assembled) ~= sys.DOFS.num_dof
    error('fixed_weight:numerical_audit:MechanicsResidualShape', ...
        'The native mechanics assembler did not return finite real double residuals per DOF.');
end
if ~isa(psi_recomputed, 'double') || ~isreal(psi_recomputed) || ...
        ~isequal(size(psi_recomputed), size(target.strain_en_undgr_gp)) || ...
        ~all(isfinite(psi_recomputed(:)))
    error('fixed_weight:numerical_audit:RecomputedPsiShape', ...
        'The native mechanics assembler did not return finite Q4 undegraded GP energy.');
end
psi_delta = psi_recomputed - target.strain_en_undgr_gp;
psi_max_abs = max(abs(psi_delta(:)));
if ~isequal(psi_recomputed, target.strain_en_undgr_gp)
    error('fixed_weight:numerical_audit:RecomputedPsiMismatch', ...
        ['The recomputed undegraded GP energy differs from the sealed payload ', ...
         '(max abs %.17g); no tolerance or repair is permitted.'], psi_max_abs);
end
converged.strain_en_undgr = psi_recomputed;
r_u_full = r_u_assembled - external;
[~, r_d_full, ~, ~] = phase( ...
    sys.MESH, sys.DOFS, sys.GEOM.t, sys.QUADRATURE, sys.MAT_CHAR, sys.CC, ...
    converged.p_field, frozen.p_field_old, converged.strain_en_undgr, ...
    sys.stress_state.as_number, frozen.history_vars_old);
[~, ~, ~, history_commit] = phase( ...
    sys.MESH, sys.DOFS, sys.GEOM.t, sys.QUADRATURE, sys.MAT_CHAR, sys.CC, ...
    converged.p_field, converged.p_field, converged.strain_en_undgr, ...
    sys.stress_state.as_number, frozen.history_vars_old);
if ~isa(r_d_full, 'double') || ~isreal(r_d_full) || ~all(isfinite(r_d_full(:))) || ...
        ~iscolumn(r_d_full) || numel(r_d_full) ~= numel(target.d_node) || ...
        ~isa(history_commit, 'double') || ~isreal(history_commit) || ...
        ~all(isfinite(history_commit(:))) || ...
        ~isequal(size(history_commit), size(target.history_gp))
    error('fixed_weight:numerical_audit:PhaseResidualShape', ...
        'The native phase assembler returned non-real, nonfinite, or malformed outputs.');
end
r_u_free = r_u_full(sys.DOFS.active_dof);
r_d_free = r_d_full(sys.DOFS.active_dof_pf);
kkt = projectedKkt(r_d_full, target.d_node, previous.d_node, sys.DOFS.active_dof_pf, 1e-12);
history_delta = history_commit - target.history_gp;
result = struct( ...
    'mechanics_free_l2', norm(r_u_free, 2), ...
    'mechanics_free_linf', norm(r_u_free, Inf), ...
    'mechanics_full_l2', norm(r_u_full, 2), ...
    'phase_free_l2', norm(r_d_free, 2), ...
    'phase_free_linf', norm(r_d_free, Inf), ...
    'phase_full_l2', norm(r_d_full, 2), ...
    'kkt', kkt, ...
    'history_exact', isequal(history_commit, target.history_gp), ...
    'history_max_abs', max(abs(history_delta(:))), ...
    'history_channel_max_abs', [max(abs(history_delta(:,:,1)), [], 'all'), ...
        max(abs(history_delta(:,:,2)), [], 'all'), max(abs(history_delta(:,:,3)), [], 'all'), ...
        max(abs(history_delta(:,:,4)), [], 'all')], ...
    'recomputed_psi_exact', true, ...
    'recomputed_psi_vs_payload_max_abs', psi_max_abs, ...
    'raw_H_vs_psi_max_abs', max(abs(target.history_gp(:,:,1) - psi_recomputed), [], 'all'), ...
    'raw_q_vs_payload_degraded_max_abs', max(abs(target.history_gp(:,:,3) - target.strain_en_degr_gp), [], 'all'), ...
    'raw_H_min', min(target.history_gp(:,:,1), [], 'all'), ...
    'raw_q_min', min(target.history_gp(:,:,3), [], 'all'), ...
    'raw_H_negative_count', nnz(target.history_gp(:,:,1) < 0), ...
    'raw_q_negative_count', nnz(target.history_gp(:,:,3) < 0) ...
    );
end


function metrics = projectedKkt(residual, d, lower, active, epsilon)
if ~iscolumn(residual) || ~iscolumn(d) || ~iscolumn(lower) || ...
        numel(residual) ~= numel(d) || numel(lower) ~= numel(d)
    error('fixed_weight:numerical_audit:ProjectedKktShape', ...
        'Residual, damage, and lower-bound vectors must be equal-length columns.');
end
active = double(active(:));
if any(active < 1 | active > numel(d) | active ~= fix(active)) || ...
        numel(unique(active)) ~= numel(active)
    error('fixed_weight:numerical_audit:ProjectedKktActiveDof', ...
        'Phase active DOFs must be unique in-range integer indices.');
end
free_d = d(active);
lower_d = lower(active);
projected = residual(active);
upper = abs(free_d - 1) <= epsilon;
at_lower = ~upper & abs(free_d - lower_d) <= epsilon & free_d < 1 - epsilon;
interior = ~(upper | at_lower);
projected(at_lower) = min(projected(at_lower), 0);
projected(upper) = max(projected(upper), 0);
metrics = struct('l2', norm(projected, 2), 'linf', norm(projected, Inf), ...
    'lower_active_count', nnz(at_lower), 'interior_count', nnz(interior), ...
    'upper_active_count', nnz(upper), 'lower_primal_violation', max(max(lower - d, 0)), ...
    'upper_primal_violation', max(max(d - 1, 0)), 'epsilon', epsilon);
end


