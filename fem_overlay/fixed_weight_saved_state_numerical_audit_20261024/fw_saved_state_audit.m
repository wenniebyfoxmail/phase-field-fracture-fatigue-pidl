function receipt = fw_saved_state_audit(cfg)
%FW_SAVED_STATE_AUDIT Reassemble saved FEM states without a solver loop.
%
% This function is intentionally not a FEM run.  It accepts only the two
% sealed development archives, verifies their bytes before each payload load,
% reconstructs the static native system, and evaluates the assembler at the
% saved accepted state.  Results describe saved-state residual/KKT/history
% facts; they do not establish Newton, staggered fixed-point, or Δd convergence.

arguments
    cfg (1,1) struct
end

mustHave(cfg, ["execute", "archive_roots", "source_root", "audit_root", ...
    "python_launcher_path", "preflight_script", "package_root", ...
    "package_manifest_sha256", "python_launcher_sha256"]);
if ~isequal(cfg.execute, true)
    error('fixed_weight:numerical_audit:ExplicitExecutionRequired', ...
        'Set cfg.execute=true only when the reviewed audit is deliberately launched.');
end
package_root = canonicalPath(string(cfg.package_root));
expected_package_root = canonicalPath(string(fileparts(mfilename('fullpath'))));
if package_root ~= expected_package_root
    error('fixed_weight:numerical_audit:PackageRoot', ...
        'cfg.package_root must name this reviewed package directory.');
end
package = verifyPackage(package_root, string(cfg.package_manifest_sha256), ...
    string(cfg.preflight_script));
if ~iscell(cfg.archive_roots) || numel(cfg.archive_roots) ~= 2
    error('fixed_weight:numerical_audit:ArchiveRoots', ...
        'cfg.archive_roots must contain exactly the U0.115 and U0.125 roots.');
end

roots = string(cfg.archive_roots(:));
root_paths = strings(size(roots));
for index = 1:numel(roots)
    root_paths(index) = canonicalPath(roots(index));
end
if numel(unique(root_paths)) ~= 2
    error('fixed_weight:numerical_audit:ArchiveRoots', 'Archive roots must be distinct.');
end
locks = archiveLocks();
archive_admissions = cell(2, 1);
for archive_index = 1:numel(root_paths)
    root = root_paths(archive_index);
    [~, name] = fileparts(root);
    if ~isfield(locks, name)
        error('fixed_weight:numerical_audit:UnknownArchive', ...
            'Only the two fixed locked archives are admissible: %s', root);
    end
    % This MATLAB-side check is authoritative for archive admission.  It does
    % not decode any MAT payload and occurs before the optional Python check.
    archive_admissions{archive_index} = verifyArchiveAdmission(root, locks.(name));
end
archive_admission_receipts = cellfun(@archiveAdmissionReceipt, archive_admissions, ...
    'UniformOutput', false);
if numel(unique(string(cellfun(@(item) item.archive_name, archive_admissions, ...
        'UniformOutput', false)))) ~= 2
    error('fixed_weight:numerical_audit:ArchiveRoots', ...
        'Each locked archive may appear exactly once.');
end
python_launcher = verifyPythonLauncher(string(cfg.python_launcher_path), ...
    string(cfg.python_launcher_sha256));
audit_root = canonicalPath(string(cfg.audit_root));
source_root = canonicalPath(string(cfg.source_root));
if isfolder(audit_root) || isfile(audit_root)
    error('fixed_weight:numerical_audit:OutputExists', ...
        'Refusing to reuse or overwrite the audit output directory: %s', audit_root);
end
if any(arrayfun(@(root) isWithin(audit_root, root), root_paths)) || isWithin(audit_root, source_root)
    error('fixed_weight:numerical_audit:UnsafeOutput', ...
        'Audit output must be outside every FEM archive and the source checkout.');
end
[created, message] = mkdir(audit_root);
if ~created
    error('fixed_weight:numerical_audit:OutputCreate', ...
        'Cannot create isolated audit output directory %s: %s', audit_root, message);
end

preflight = fullfile(audit_root, 'preflight.json');
command = sprintf('%s -3 -B -s -P %s %s %s --output %s', shellQuote(python_launcher.path), ...
    shellQuote(cfg.preflight_script), shellQuote(root_paths(1)), shellQuote(root_paths(2)), ...
    shellQuote(preflight));
[status, output] = system(command);
if status ~= 0 || ~isfile(preflight)
    error('fixed_weight:numerical_audit:SupplementalPreflightFailed', ...
        'Supplemental Python cross-check failed after MATLAB archive admission:\n%s', output);
end
preflight_receipt = verifySupplementalPreflightReceipt(preflight);

source = bindSource(source_root);
records = repmat(emptyRecord(), 880, 1);
cursor = 0;
archive_receipts = cell(2,1);
for archive_index = 1:numel(root_paths)
    root = root_paths(archive_index);
    [~, name] = fileparts(root);
    [archive_records, archive_receipt] = auditArchive(root, locks.(name), source, ...
        archive_admissions{archive_index});
    next = cursor + numel(archive_records);
    records(cursor + 1:next) = archive_records;
    cursor = next;
    archive_receipts{archive_index} = archive_receipt;
end
if cursor ~= 880
    error('fixed_weight:numerical_audit:Coverage', ...
        'Expected 880 chronological physical transitions, observed %d.', cursor);
end

metrics = struct2table(records);
writetable(metrics, fullfile(audit_root, 'saved_state_transition_metrics.csv'));
receipt = struct( ...
    'schema', 'fixed_weight_saved_state_numerical_audit_v1', ...
    'status', 'completed_saved_state_audit', ...
    'scope', ['post-clip saved-state residual/KKT/history reassembly; ', ...
              'not a solver-inner convergence qualification'], ...
    'package', package, ...
    'source', source, ...
    'matlab_archive_admission', {archive_admission_receipts}, ...
    'supplemental_python_preflight', preflight_receipt, ...
    'python_launcher', python_launcher, ...
    'archive_receipts', {archive_receipts}, ...
    'physical_transition_count', cursor, ...
    'metric_csv', string(fullfile(audit_root, 'saved_state_transition_metrics.csv')), ...
    'raw_archives_modified', false, ...
    'fem_solver_started', false, ...
    'native_assembler_calls_used', true, ...
    'training_started', false, ...
    'runtime_binary_source_equivalence_proved', false, ...
    'numerical_admission_decision', 'not_evaluated', ...
    'not_proved', [ ...
        "Newton iteration residual history", ...
        "staggered fixed-point convergence", ...
        "staggered delta-d convergence", ...
        "source-to-MEX build equivalence", ...
        "a physical benchmark or independent-test claim"] ...
    );
% jsonencode returns a char vector.  Do not use `+ newline` here: char plus
% char is element-wise numeric addition in MATLAB, which corrupts every JSON
% byte.  sprintf creates the one terminal newline without changing JSON text.
receipt_text = sprintf('%s\n', jsonencode(receipt, PrettyPrint=true));
writeText(fullfile(audit_root, 'saved_state_audit_receipt.json'), receipt_text);
end


function [records, receipt] = auditArchive(root, lock, source, prior_admission)
% Revalidate immediately before the first MAT load to close the interval after
% the top-level admission check and the supplemental Python cross-check.
admission = verifyArchiveAdmission(root, lock);
if ~isequal(admission.index, prior_admission.index) || ...
        ~isequal(admission.manifest_sha256, prior_admission.manifest_sha256)
    error('fixed_weight:numerical_audit:ArchiveDrift', ...
        'Archive admission changed before the static MAT payload was opened.');
end
index = admission.index;
static_path = archiveMemberPath(root, 'static/native_q4_mesh_dofs_quadrature.mat');
mustMatch(root, 'static/native_q4_mesh_dofs_quadrature.mat', lock.static_sha256);
static = load(static_path, 'stage0b_static');
if ~isfield(static, 'stage0b_static')
    error('fixed_weight:numerical_audit:StaticSchema', 'stage0b_static is absent.');
end
native = static.stage0b_static;
system_state = reconstructSystem(native, lock, source);

initial_row = rowFor(index, 1, 0);
initial = loadState(root, initial_row, native, 0.0, system_state.boundary_binding);
initial_label = "post_clip_zero_load_recovery_pre_cycle_committed";
if initial.metadata.substep ~= 0 || string(initial.metadata.timing) ~= "pre_cycle_committed"
    error('fixed_weight:numerical_audit:InitialTiming', 'Unexpected c0001_s00 semantics.');
end
initial_contract = verifyRecoveredInitialState(initial);

records = repmat(emptyRecord(), lock.cycles * 5, 1);
cursor = 0;
previous = initial;
for cycle = 1:lock.cycles
    if cycle > 1
        alias = rowFor(index, cycle, 0);
        verifyAlias(alias, previous.row, cycle);
    end
    for substep = 1:5
        target_row = rowFor(index, cycle, substep);
        target = loadState(root, target_row, native, system_state.effective_uy(substep), ...
            system_state.boundary_binding);
        result = evaluateSavedTransition(system_state, previous, target);
        cursor = cursor + 1;
        records(cursor) = makeRecord(lock, previous, target, result, initial_label);
        previous = target;
    end
end
if cursor ~= lock.cycles * 5
    error('fixed_weight:numerical_audit:Coverage', 'Archive transition count is incomplete.');
end
receipt = struct( ...
    'archive_root', string(root), ...
    'run_id', lock.run_id, ...
    'source_commit', source.commit, ...
    'matlab_archive_admission', archiveAdmissionReceipt(admission), ...
    'physical_transitions', cursor, ...
    'initial_semantics', initial_label, ...
    'initial_contract', initial_contract, ...
    'history_input_rule', ['target d/psi with immediately previous physical ', ...
        'd/history; target committed history is never fed back as history_prev'], ...
    'mechanics_external_load', 'zero after verified absence of Neumann DOFs/traction faces', ...
    'raw_archive_write_attempted', false, ...
    'fem_solver_started', false, ...
    'not_a_staggered_convergence_test', true ...
    );
end


function source = bindSource(root)
if ~isfolder(root) || ~isfolder(fullfile(root, 'Sources')) || ...
        ~isfolder(fullfile(root, 'Dependencies'))
    error('fixed_weight:numerical_audit:SourceTree', ...
        'source_root must be a complete original FEM checkout with Sources and Dependencies.');
end
[code, head] = system(sprintf('git -C %s rev-parse HEAD', shellQuote(root)));
if code ~= 0 || ~strcmpi(strtrim(head), '862992a60edc7f59335365beacb5c71fc8592a7a')
    error('fixed_weight:numerical_audit:SourceCommit', 'Source checkout is not the locked producer commit.');
end
[code, dirty] = system(sprintf('git -C %s status --porcelain', shellQuote(root)));
if code ~= 0 || strlength(strtrim(string(dirty))) ~= 0
    error('fixed_weight:numerical_audit:SourceDirty', 'Source checkout must be clean.');
end
addpath(genpath(fullfile(root, 'Dependencies')), '-begin');
addpath(genpath(fullfile(root, 'Sources')), '-begin');
equilibrium = str2func('phase_field.mex.fem.assembly.equilibrium.AMOR');
phase = str2func('phase_field.mex.fem.assembly.pf.AT1_PENALTY_FATIGUE');
handles = {equilibrium, phase};
qualified = string({func2str(equilibrium), func2str(phase)});
runtime_binaries = repmat(struct('qualified_name', "", 'path', "", 'sha256', ""), 2, 1);
required_mex_suffix = "." + string(mexext);
for index = 1:numel(handles)
    resolved_raw = string(which(char(qualified(index))));
    if strlength(resolved_raw) == 0
        error('fixed_weight:numerical_audit:SourceResolution', ...
            'The required native assembler is not on the reviewed source path: %s', qualified(index));
    end
    resolved = canonicalPath(resolved_raw);
    if ~isWithin(resolved, root)
        error('fixed_weight:numerical_audit:SourceResolution', ...
            'A required native assembler does not resolve inside source_root.');
    end
    if ~endsWith(lower(resolved), lower(required_mex_suffix))
        error('fixed_weight:numerical_audit:NativeMexResolution', ...
            'The required native assembler must resolve to the current-platform MEX binary: %s', resolved);
    end
    runtime_binaries(index) = struct('qualified_name', qualified(index), ...
        'path', resolved, 'sha256', sha256File(resolved));
end
source_blobs = verifySourceInterfaceBlobs(root);
source = struct('root', root, 'commit', "862992a60edc7f59335365beacb5c71fc8592a7a", ...
    'equilibrium_assembler', string(func2str(equilibrium)), ...
    'phase_assembler', string(func2str(phase)), ...
    'interface_blobs', source_blobs, ...
    'runtime_binaries', runtime_binaries, ...
    'runtime_binary_source_equivalence_proved', false);
end


function blobs = verifySourceInterfaceBlobs(root)
% Lock the reviewed source call semantics as well as the checkout commit.
locked = [ ...
    "Sources/+phase_field/+mex/Modules/fem/assembly/equilibrium/amor.f90", ...
    "Sources/+phase_field/+mex/Modules/fem/assembly/pf/at1_penalty_fatigue.f90", ...
    "Sources/+phase_field/+fem/+solver/+stag/post_iter_update.m", ...
    "Sources/+phase_field/+mex/+fem/+assembly/+equilibrium/AMOR.f90", ...
    "Sources/+phase_field/+mex/+fem/+assembly/+pf/AT1_PENALTY_FATIGUE.f90", ...
    "Sources/+phase_field/System.m", ...
    "Sources/+phase_field/+fem/+solver/+step/params.m", ...
    "Scripts/fatigue_fracture/solve_fatigue_fracture.m" ...
    ];
expected = [ ...
    "6a30c52161b2999889b7bc1b57a17cbd6e4c6db5", ...
    "d3d03cdd2ee1d894893f1cbb584a7e94947ec6b7", ...
    "e74c95ac7b4a439bbc7815561ff45c071428c065", ...
    "", "", "", "", "" ...
    ];
blobs = repmat(struct('relative_path', "", 'git_blob', "", 'expected_git_blob', ""), numel(locked), 1);
for index = 1:numel(locked)
    [code, actual] = system(sprintf('git -C %s rev-parse %s', ...
        shellQuote(root), shellQuote("HEAD:" + locked(index))));
    actual = lower(string(strtrim(actual)));
    if code ~= 0 || (strlength(expected(index)) > 0 && actual ~= expected(index))
        error('fixed_weight:numerical_audit:SourceInterfaceBlob', ...
            'Reviewed source interface blob mismatch: %s', locked(index));
    end
    blobs(index) = struct('relative_path', locked(index), 'git_blob', actual, ...
        'expected_git_blob', expected(index));
end
end


function system_state = reconstructSystem(native, lock, source)
required = ["mesh","dofs","quadrature","material_parameters", ...
    "boundary_node_masks","boundary_conditions","geometry","stress_state", ...
    "dissipation","case_config","history_channel_labels"];
mustHave(native, required);
cfg = native.case_config;
mustHave(native.dofs, ["num_dof_node", "num_dof", "hom_dirichlet_bc", ...
    "non_hom_dirichlet_bc", "dirichlet_bc", "neumann_bc", "active_dof", ...
    "hom_dirichlet_bc_pf", "non_hom_dirichlet_bc_pf", "dirichlet_bc_pf", ...
    "active_dof_pf"]);
mustHave(native.boundary_conditions, "elem_tract");
mustHave(native.mesh, "native_mesh");
mustHave(native.mesh.native_mesh, ["node","elem","elem_material_id","num_node","num_elem","nel"]);
schedule = lockedSchedule(lock);
if ~isequal(string(native.history_channel_labels), ["H","alpha_bar","q_prev","f"])
    error('fixed_weight:numerical_audit:StaticConfig', 'Static configuration does not match the locked contract.');
end
verifyCaseConfig(cfg, lock, schedule);
verifyStaticMeshMaterialBinding(native, cfg);
dof_binding = verifyDofBinding(native.dofs, native.mesh.native_mesh.num_node);
if ~isa(native.stress_state, 'phase_field.StressState') || string(native.dissipation) ~= "AT1"
    error('fixed_weight:numerical_audit:StaticSystem', ...
        'Static stress state or AT1 dissipation cannot be reconstructed exactly.');
end
step = phase_field.fem.solver.step.params( ...
    'n_step', double(cfg.requested_n_step), 'loading', char(cfg.loading), ...
    'discretization', char(cfg.discretization), 'uy_final', double(cfg.u_max), ...
    'R', double(cfg.R), 'line_search', false);
% uy_increment spans the five transitions after the s00 zero-load anchor.
if double(step.n_step) ~= 5 || ...
        ~sameNumbers(cumsum(step.uy_increment), schedule.imposed_displacement(2:end), 1e-14)
    error('fixed_weight:numerical_audit:LoadReconstruction', ...
        'Source step parameters do not reproduce the sealed effective load path.');
end
if ~isempty(native.dofs.neumann_bc) || ~isempty(native.boundary_conditions.elem_tract)
    error('fixed_weight:numerical_audit:ExternalLoad', ...
        'This audited route only supports the sealed displacement-controlled zero-traction archive.');
end
initial_d = zeros(native.mesh.native_mesh.num_node, 1);
sys = phase_field.System(native.material_parameters, native.geometry, native.quadrature, ...
    native.dofs, native.boundary_node_masks, step, native.mesh.native_mesh, ...
    native.stress_state, initial_d, char(native.dissipation));
if ~isequal(sys.BOUNDARY_CONDS, native.boundary_conditions)
    error('fixed_weight:numerical_audit:BoundaryReconstruction', ...
        'Reconstructed boundary conditions differ from the sealed static payload.');
end
verifyReconstructedDofs(sys.DOFS, native.dofs);
boundary_binding = verifyBoundaryBinding(native.boundary_node_masks, ...
    native.mesh.native_mesh, sys.DOFS, sys.NODE_BOUNDARIES);
% The audit loop indexes physical targets s01..s05, never the s00 anchor.
system_state = struct('sys', sys, ...
    'equilibrium', str2func(char(source.equilibrium_assembler)), ...
    'phase', str2func(char(source.phase_assembler)), ...
    'dof_binding', dof_binding, ...
    'boundary_binding', boundary_binding, ...
    'effective_uy', schedule.imposed_displacement(2:end));
end


function verifyCaseConfig(cfg, lock, schedule)
required = ["u_max","requested_n_step","n_step","loading","discretization", ...
    "R","res_stiff","alpha_T","nominal_load_factor", ...
    "effective_load_factor","nominal_uy","effective_uy","solver_loadfun"];
mustHave(cfg, required);
if ~sameNumbers(double(cfg.u_max), lock.u_max, 1e-14) || ...
        double(cfg.requested_n_step) ~= 8 || double(cfg.n_step) ~= 5 || ...
        string(cfg.loading) ~= "cyclic" || string(cfg.discretization) ~= "loading" || ...
        ~sameNumbers(double(cfg.R), 0.0, 1e-14) || ...
        ~sameNumbers(double(cfg.res_stiff), 0.0, 1e-14) || ...
        ~sameNumbers(double(cfg.alpha_T), 0.5, 1e-14) || ...
        ~sameNumbers(cfg.nominal_load_factor, schedule.nominal(2:end), 1e-14) || ...
        ~sameNumbers(cfg.effective_load_factor, schedule.effective(2:end), 1e-14) || ...
        ~sameNumbers(cfg.nominal_uy, lock.u_max .* schedule.nominal(2:end), 1e-14) || ...
        ~sameNumbers(cfg.effective_uy, schedule.imposed_displacement(2:end), 1e-14) || ...
        ~sameNumbers(cfg.solver_loadfun, schedule.solver_loadfun, 1e-14)
    error('fixed_weight:numerical_audit:CaseConfig', ...
        'Static case configuration does not reproduce the locked Hard5 schedule.');
end
end


function schedule = lockedSchedule(lock)
solver_loadfun = [1e-6, 0.25, 0.5, 0.75, 1.0, 1e-6];
nominal = [0.0, 0.25, 0.5, 0.75, 1.0, 0.0];
effective = [0.0, solver_loadfun(2:end) - solver_loadfun(1)];
schedule = struct('solver_loadfun', solver_loadfun, 'nominal', nominal, ...
    'effective', effective, 'imposed_displacement', lock.u_max .* effective);
end


function verifyStaticMeshMaterialBinding(native, cfg)
mustHave(native.mesh, ["node_coordinates","cells_1based","element_type"]);
mesh = native.mesh.native_mesh;
if string(native.mesh.element_type) ~= "Q4" || double(mesh.nel) ~= 4 || ...
        double(mesh.num_node) ~= size(mesh.node, 1) || ...
        double(mesh.num_elem) ~= size(mesh.elem, 1) || ...
        size(mesh.node, 2) ~= 2 || size(mesh.elem, 2) < 4 || ...
        ~isequal(double(native.mesh.node_coordinates), double(mesh.node)) || ...
        ~isequal(double(native.mesh.cells_1based), double(mesh.elem(:, 1:4)))
    error('fixed_weight:numerical_audit:MeshBinding', ...
        'Sealed native mesh fields cannot be bound as the required Q4 mesh.');
end
mustHave(native.quadrature, ["num_gauss_pts","gauss_pts","gauss_W","Nxi","dNdxi"]);
if double(native.quadrature.num_gauss_pts) ~= 4 || ...
        ~isequal(size(native.quadrature.gauss_pts), [4,2]) || ...
        ~isequal(size(native.quadrature.gauss_W), [4,1]) || ...
        ~isequal(size(native.quadrature.Nxi), [4,4]) || ...
        ~isequal(size(native.quadrature.dNdxi), [2,4,4])
    error('fixed_weight:numerical_audit:QuadratureBinding', ...
        'Sealed quadrature does not satisfy the required native Q4 contract.');
end
material = native.material_parameters;
mustHave(material, ["E","ni","Gc","ell","res_stiff","alpha_T","p"]);
if numel(material) ~= 1 || ...
        ~sameNumbers(material.E, 1.0, 1e-14) || ...
        ~sameNumbers(material.ni, 0.3, 1e-14) || ...
        ~sameNumbers(material.Gc, 0.01, 1e-14) || ...
        ~sameNumbers(material.ell, 0.01, 1e-14) || ...
        ~sameNumbers(material.res_stiff, cfg.res_stiff, 1e-14) || ...
        ~sameNumbers(material.alpha_T, cfg.alpha_T, 1e-14) || ...
        ~sameNumbers(material.p, 2.0, 1e-14)
    error('fixed_weight:numerical_audit:MaterialBinding', ...
        'Sealed material fields do not match the locked Hard5 AT1 fatigue contract.');
end
end


function binding = verifyDofBinding(dofs, n_node)
if ~isreal(dofs.num_dof) || ~isreal(dofs.active_dof) || ~isreal(dofs.active_dof_pf)
    error('fixed_weight:numerical_audit:DofBinding', ...
        'The sealed native DOF fields must be real-valued.');
end
num_dof = double(dofs.num_dof);
if ~isscalar(num_dof) || ~isfinite(num_dof) || num_dof ~= fix(num_dof) || ...
        num_dof ~= 2 * double(n_node)
    error('fixed_weight:numerical_audit:DofBinding', ...
        'The sealed displacement DOF count must equal 2*num_node.');
end
active_displacement = double(dofs.active_dof(:));
active_phase = double(dofs.active_dof_pf(:));
if isempty(active_displacement) || isempty(active_phase) || ...
        any(~isfinite(active_displacement)) || any(~isfinite(active_phase)) || ...
        any(active_displacement ~= fix(active_displacement)) || ...
        any(active_phase ~= fix(active_phase)) || ...
        any(active_displacement < 1 | active_displacement > num_dof) || ...
        any(active_phase < 1 | active_phase > double(n_node)) || ...
        numel(unique(active_displacement)) ~= numel(active_displacement) || ...
        numel(unique(active_phase)) ~= numel(active_phase)
    error('fixed_weight:numerical_audit:DofBinding', ...
        'The sealed active displacement/phase DOF sets are malformed.');
end
binding = struct('num_node', double(n_node), 'num_dof', num_dof, ...
    'active_displacement_count', numel(active_displacement), ...
    'active_phase_count', numel(active_phase));
end


function verifyReconstructedDofs(reconstructed, sealed)
required = ["num_dof_node", "num_dof", "hom_dirichlet_bc", ...
    "non_hom_dirichlet_bc", "dirichlet_bc", "neumann_bc", "active_dof", ...
    "hom_dirichlet_bc_pf", "non_hom_dirichlet_bc_pf", "dirichlet_bc_pf", ...
    "active_dof_pf"];
mustHave(reconstructed, required);
mustHave(sealed, required);
for field = required
    if ~isequal(reconstructed.(field), sealed.(field))
        error('fixed_weight:numerical_audit:ReconstructedDofs', ...
            'Reconstructed sys.DOFS.%s differs from the sealed native DOF payload.', char(field));
    end
end
end


function binding = verifyBoundaryBinding(native_masks, mesh, dofs, reconstructed_masks)
required = ["fix_X", "fix_Y", "disp_X", "disp_Y", "tract_X", "tract_Y", ...
    "hom_pf", "non_hom_pf"];
mustHave(native_masks, required);
mustHave(reconstructed_masks, required);
if ~isequal(reconstructed_masks, native_masks)
    error('fixed_weight:numerical_audit:ReconstructedBoundary', ...
        'Reconstructed NODE_BOUNDARIES differs from the sealed native payload.');
end
n_node = double(mesh.num_node);
if ~isscalar(n_node) || ~isfinite(n_node) || n_node ~= fix(n_node) || ...
        ~isequal(n_node, size(mesh.node, 1)) || size(mesh.node, 2) ~= 2
    error('fixed_weight:numerical_audit:BoundaryBinding', ...
        'Native mesh cannot support the sealed tensile boundary contract.');
end
bottom = find(mesh.node(:, 2) == min(mesh.node(:, 2)));
top = find(mesh.node(:, 2) == max(mesh.node(:, 2)));
fix_x = nodeMaskIndices(native_masks.fix_X, n_node, 'fix_X');
fix_y = nodeMaskIndices(native_masks.fix_Y, n_node, 'fix_Y');
disp_x = nodeMaskIndices(native_masks.disp_X, n_node, 'disp_X');
disp_y = nodeMaskIndices(native_masks.disp_Y, n_node, 'disp_Y');
