function digest = sha256File(path)
if ~isfile(path)
    error('fixed_weight:numerical_audit:MissingFile', 'Cannot hash missing file: %s', path);
end
md = java.security.MessageDigest.getInstance('SHA-256');
fid = fopen(path, 'rb');
if fid < 0
    error('fixed_weight:numerical_audit:FileOpen', 'Cannot open file for hashing: %s', path);
end
cleanup = onCleanup(@() fclose(fid)); %#ok<NASGU>
while true
    bytes = fread(fid, 1024 * 1024, '*uint8');
    if isempty(bytes)
        break;
    end
    md.update(bytes);
end
raw = typecast(md.digest(), 'uint8');
digest = lower(string(reshape(dec2hex(raw, 2).', 1, [])));
end


function yes = isSha256(value)
%ISSH256 Match a scalar SHA-256 digest with MATLAB's regular-expression API.
%
% `matches` supports wildcard patterns rather than regular expressions.  Use
% `regexp` explicitly so malformed manifest, payload, and launcher hashes
% fail closed under the MATLAB runtime used for the audit.
value = string(value);
yes = isscalar(value) && ~ismissing(value) && strlength(value) == 64 && ...
    ~isempty(regexp(char(lower(value)), '^[0-9a-f]{64}$', 'once'));
end


