function index = readIndex(path, lock)
options = detectImportOptions(path, 'TextType', 'string');
% Preserve every CSV token through the contract conversion below.  R2025b
% otherwise infers the load columns as double; string(double) then uses a
% display precision that can turn 0.249999 into "0.25" before finiteColumn
% reparses it.  The producer's 1e-14 schedule identity check must see the
% original decimal token, rather than a presentation-rounded value.
options = setvartype(options, options.VariableNames, 'string');
index = readtable(path, options);
required = ["state_key","cycle","substep","timing","is_alias", ...
    "source_state_key","payload_file","payload_sha256","converged", ...
    "nominal_load_factor","effective_load_factor","imposed_displacement"];
if ~all(ismember(required, string(index.Properties.VariableNames))) || height(index) ~= lock.cycles * 6
    error('fixed_weight:numerical_audit:IndexSchema', 'State index has the wrong schema or row count.');
end
index.state_key = string(index.state_key);
index.timing = string(index.timing);
index.is_alias = string(index.is_alias);
index.source_state_key = string(index.source_state_key);
index.payload_file = string(index.payload_file);
index.payload_sha256 = lower(string(index.payload_sha256));
index.converged = string(index.converged);
index.cycle = integerColumn(index.cycle, 'cycle');
index.substep = integerColumn(index.substep, 'substep');
index.nominal_load_factor = finiteColumn(index.nominal_load_factor, 'nominal_load_factor');
index.effective_load_factor = finiteColumn(index.effective_load_factor, 'effective_load_factor');
index.imposed_displacement = finiteColumn(index.imposed_displacement, 'imposed_displacement');
for payload_index = 1:height(index)
    index.payload_file(payload_index) = normalizeArchiveRelative(index.payload_file(payload_index));
end
schedule = lockedSchedule(lock);
expected_keys = strings(lock.cycles * 6, 1);
cursor = 0;
for cycle = 1:lock.cycles
    for substep = 0:5
        cursor = cursor + 1;
        expected_key = string(sprintf('c%04d_s%02d', cycle, substep));
        expected_keys(cursor) = expected_key;
        row = table2struct(index(cursor, :));
        if row.cycle ~= cycle || row.substep ~= substep || row.state_key ~= expected_key || ...
                row.timing ~= ternary(substep == 0, "pre_cycle_committed", "post_history_commit") || ...
                row.converged ~= "1" || ~isSha256(row.payload_sha256) || ...
                ~sameNumbers(row.nominal_load_factor, schedule.nominal(substep + 1), 1e-14) || ...
                ~sameNumbers(row.effective_load_factor, schedule.effective(substep + 1), 1e-14) || ...
                ~sameNumbers(row.imposed_displacement, schedule.imposed_displacement(substep + 1), 1e-14)
            error('fixed_weight:numerical_audit:IndexOrder', 'Chronological index mismatch.');
        end
        if substep == 0 && cycle > 1
            prior = table2struct(index(cursor - 1, :));
            if row.is_alias ~= "1" || row.source_state_key ~= prior.state_key || ...
                    row.payload_file ~= prior.payload_file || row.payload_sha256 ~= prior.payload_sha256
                error('fixed_weight:numerical_audit:IndexAlias', ...
                    'Invalid c%04d_s00 alias chain.', cycle);
            end
        elseif row.is_alias ~= "0" || row.source_state_key ~= expected_key
            error('fixed_weight:numerical_audit:IndexIdentity', ...
                'Physical state must be a converged nonalias native payload: %s', expected_key);
        end
    end
end
if ~isequal(index.state_key(:), expected_keys)
    error('fixed_weight:numerical_audit:IndexOrder', ...
        'State index is not in the required physical chronology.');
end
end


