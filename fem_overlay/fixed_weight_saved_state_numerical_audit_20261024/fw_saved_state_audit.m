function manifest = parseArchiveManifest(root, expected_sha256)
manifest_path = archiveMemberPath(root, 'SHA256SUMS.txt');
if sha256File(manifest_path) ~= lower(string(expected_sha256))
    error('fixed_weight:numerical_audit:ManifestHash', ...
        'SHA256SUMS.txt does not match the immutable archive lock.');
end
text = replace(string(fileread(manifest_path)), char(65279), '');
lines = splitlines(text);
if ~isempty(lines) && lines(end) == ""
    lines(end) = [];
end
if isempty(lines) || any(lines == "")
    error('fixed_weight:numerical_audit:ManifestSyntax', ...
        'Archive manifest must contain only nonempty digest records.');
end
manifest = repmat(struct('relative', "", 'sha256', "", 'path', ""), numel(lines), 1);
seen = strings(0, 1);
for line_index = 1:numel(lines)
    tokens = regexp(char(lines(line_index)), '^([0-9A-Fa-f]{64})\s+\*?(.+)$', 'tokens', 'once');
    if isempty(tokens)
        error('fixed_weight:numerical_audit:ManifestSyntax', ...
            'Malformed SHA256SUMS.txt record at line %d.', line_index);
    end
    relative = normalizeArchiveRelative(string(tokens{2}));
    if relative == "SHA256SUMS.txt" || any(seen == relative)
        error('fixed_weight:numerical_audit:ManifestSyntax', ...
            'Manifest contains a duplicate or self-referential member: %s', relative);
    end
    seen(end + 1, 1) = relative; %#ok<AGROW>
    manifest(line_index) = struct('relative', relative, ...
        'sha256', lower(string(tokens{1})), 'path', archiveMemberPath(root, relative));
end
end


function verifyManifestMembers(manifest)
for member_index = 1:numel(manifest)
    member = manifest(member_index);
    if sha256File(member.path) ~= member.sha256
        error('fixed_weight:numerical_audit:ManifestMemberHash', ...
            'Manifest hash mismatch: %s', member.relative);
    end
end
end


function verifyLockedFiles(root, lock, manifest)
required = [ ...
    "state_index.csv", string(lock.index_sha256); ...
    "static/native_q4_mesh_dofs_quadrature.mat", string(lock.static_sha256); ...
    "provenance/config_receipt.mat", string(lock.config_sha256); ...
    "provenance/source_receipt.json", string(lock.source_receipt_sha256); ...
    "run_summary.json", string(lock.summary_sha256) ...
    ];
for index = 1:size(required, 1)
    relative = required(index, 1);
    expected = lower(required(index, 2));
    path = archiveMemberPath(root, relative);
    if sha256File(path) ~= expected
        error('fixed_weight:numerical_audit:IdentityHash', ...
            'Identity hash mismatch: %s', path);
    end
    member_index = find(string({manifest.relative}) == relative, 1);
    if isempty(member_index) || manifest(member_index).sha256 ~= expected
        error('fixed_weight:numerical_audit:ManifestBinding', ...
            'Locked archive identity file is not manifest-bound: %s', relative);
    end
end
end


