        ~isequal(dofs.hom_dirichlet_bc, expected_hom) || ...
        ~isequal(dofs.non_hom_dirichlet_bc, expected_non_hom) || ...
        ~isequal(dofs.dirichlet_bc, expected_dirichlet) || ...
