function equal = sameNumbers(actual, expected, tolerance)
% The producer configuration itself compares this schedule at 1e-14.
% This is an identity check for stored load metadata, never an acceptance
% tolerance for residuals, KKT values, damage, or history.
actual = double(actual(:));
expected = double(expected(:));
equal = isequal(size(actual), size(expected)) && all(isfinite(actual)) && ...
    all(isfinite(expected)) && all(abs(actual - expected) <= tolerance);
end


