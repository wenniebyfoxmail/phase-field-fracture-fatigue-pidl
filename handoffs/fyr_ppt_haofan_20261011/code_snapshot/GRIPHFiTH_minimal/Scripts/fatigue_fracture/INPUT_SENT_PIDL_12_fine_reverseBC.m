% =========================================================================
% SENT fatigue case — uy_final=0.12, PIDL fine mesh with reverseBC
%
% Purpose:
%   Run the coarser PIDL-fine FEM mesh (SENT_pidl_fine_lh5.inp) with the
%   same AT1/AMOR/PENALTY settings used by the main PIDL-series FEM cases,
%   but with the PIDL-like horizontal clamp: u_x=0 on top+bottom.
%
% Compared with INPUT_SENT_PIDL_12_fine.m:
%   Only the X boundary condition changes from bottom-left anchor to
%   top+bottom clamp.
%
% Compared with INPUT_SENT_PIDL_12_reverseBC.m:
%   Only the mesh changes from SENT_mesh.inp to SENT_pidl_fine_lh5.inp.
% =========================================================================

split_type = 'AMOR';
diss_fct   = 'AT1';
irrev      = 'PENALTY';

example_name = 'SENT_PIDL_12_fine_reverseBC';

% =========================================================================
%   MESH — gmsh-generated PIDL fine mesh, h_tip = ell/5 = 0.002 mm
% =========================================================================
[MESH, GEOM] = specimen.external.abaqus_import(...
    'Dependencies/SENT_mesh/SENT_pidl_fine_lh5.inp', ...
    't', 1 ...
);

% =========================================================================
%   MATERIAL — identical to INPUT_SENT_PIDL_12.m / fine / reverseBC
% =========================================================================
MAT_CHAR(1) = phase_field.init.material_characteristic(...
    GEOM.L, diss_fct, ...
    'E',         1.0, ...
    'ni',        0.3, ...
    'Gc',        0.01, ...
    'ell',       0.01, ...
    'res_stiff', 1e-6, ...
    'alpha_T',   0.5, ...
    'p',         2.0 ...
);

MESH.elem_material_id = ones(MESH.num_elem, 1);

% =========================================================================
%   BOUNDARY CONDITIONS — reverseBC: fix_X on entire top+bottom
% =========================================================================
bottom     = find(MESH.node(:,2) == -0.5);
top        = find(MESH.node(:,2) ==  0.5);
top_bottom = unique([top; bottom]);

NODE_BOUNDARIES = phase_field.fem.bc.set_boundaries(...
    'fix_X',  top_bottom, ...
    'fix_Y',  bottom, ...
    'disp_Y', top ...
);

DOFS = phase_field.init.dofs(MESH, NODE_BOUNDARIES);

QUADRATURE = phase_field.init.quadrature(MESH.dim);

stress_state = phase_field.StressState.PlaneStrain;

% =========================================================================
%   SOLVER PARAMETERS — identical to PIDL_12 fine
% =========================================================================
SOL_PAR = phase_field.fem.solver.params(...
    'tol_displ',      1e-6, ...
    'tol_p_field',    1e-5, ...
    'max_iter_displ', 250, ...
    'max_iter_pf',    250 ...
);

SOL_STAG_PAR = phase_field.fem.solver.stag.params('tol', 1e-4, 'max_iter', 1000);

SOL_STEP_PAR = phase_field.fem.solver.step.params(...
    'n_step',         8, ...
    'loading',        'cyclic', ...
    'discretization', 'loading', ...
    'uy_final',       0.12, ...
    'R',              0.0, ...
    'line_search',    true ...
);

SOL_CYCL_PAR = phase_field.fem.solver.cycl.params(...
    'max_cycle',   120, ...
    'da_paraview', 0.01 ...
);

SOL_JUMP_PAR = phase_field.fem.solver.cycl_jump.params(...
    'cycl_jump', false ...
);

CRACK_PAR = phase_field.fem.crack.params(MAT_CHAR, diss_fct);

% =========================================================================
%   CHECKPOINT & VTK
% =========================================================================
checkpoint_freq = 10;
vtk_freq        = 10;

fprintf('=== PIDL fine mesh reverseBC, u=0.12 ===\n');
fprintf('  Mesh: %d nodes, %d quads (SENT_pidl_fine_lh5.inp)\n', MESH.num_node, MESH.num_elem);
fprintf('  Model: AT1 + AMOR + PENALTY, alpha_T=0.5, p=2\n');
fprintf('  BC: fix_X top+bottom, fix_Y bottom, disp_Y top\n');
