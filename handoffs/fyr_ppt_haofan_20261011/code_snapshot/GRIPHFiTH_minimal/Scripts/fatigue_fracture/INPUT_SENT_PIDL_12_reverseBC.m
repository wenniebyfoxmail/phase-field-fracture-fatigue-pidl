% =========================================================================
% SENT fatigue — uy=0.12, reverseBC diagnostic
%
% Identical to INPUT_SENT_PIDL_12.m EXCEPT:
%   fix_X applied to ALL top+bottom nodes (not just bottom_left anchor).
%   This mimics the old PIDL default horizontal clamp (u_x=0 on top+bottom)
%   to test whether the FEM/PIDL field gap is mainly a BC confound.
%
% vtk_freq=9999: skip VTK to save disk. psi_fields (per-cycle .mat) have
%   all needed data: d_elem, psi_elem, alpha_bar_elem, f_alpha_elem.
% =========================================================================

split_type = 'AMOR';
diss_fct   = 'AT1';
irrev      = 'PENALTY';

example_name = 'SENT_PIDL_12_reverseBC';

% =========================================================================
%   MESH
% =========================================================================
[MESH, GEOM] = specimen.external.abaqus_import(...
    'Dependencies/SENT_mesh/SENT_mesh.inp', 't', 1);

% =========================================================================
%   MATERIAL — normalized (E=1, Gc=0.01, ell=0.01)
% =========================================================================
MAT_CHAR(1) = phase_field.init.material_characteristic(...
    GEOM.L, diss_fct, ...
    'E',         1.0, ...
    'ni',        0.3, ...
    'Gc',        0.01, ...
    'ell',       0.01, ...
    'res_stiff', 1e-6, ...
    'alpha_T',   0.5, ...
    'p',         2.0 ...
);
MESH.elem_material_id = ones(MESH.num_elem, 1);

% =========================================================================
%   BOUNDARY CONDITIONS — reverseBC: fix_X on entire top+bottom (diagnostic)
%   Normal BC: fix_X on bottom_left only.
%   Here: fix_X on top_bottom to match old PIDL default horizontal clamp.
% =========================================================================
bottom      = find(MESH.node(:,2) == -0.5);
top         = find(MESH.node(:,2) ==  0.5);
top_bottom  = unique([top; bottom]);

NODE_BOUNDARIES = phase_field.fem.bc.set_boundaries(...
    'fix_X',  top_bottom, ...
    'fix_Y',  bottom, ...
    'disp_Y', top ...
);

DOFS = phase_field.init.dofs(MESH, NODE_BOUNDARIES);
QUADRATURE = phase_field.init.quadrature(MESH.dim);
stress_state = phase_field.StressState.PlaneStrain;

% =========================================================================
%   SOLVER PARAMETERS
% =========================================================================
SOL_PAR = phase_field.fem.solver.params(...
    'tol_displ',      1e-6, ...
    'tol_p_field',    1e-5, ...
    'max_iter_displ', 250, ...
    'max_iter_pf',    250 ...
);
SOL_STAG_PAR = phase_field.fem.solver.stag.params('tol', 1e-4, 'max_iter', 1000);
SOL_STEP_PAR = phase_field.fem.solver.step.params(...
    'n_step',         8, ...
    'loading',        'cyclic', ...
    'discretization', 'loading', ...
    'uy_final',       0.12, ...
    'R',              0.0, ...
    'line_search',    true ...
);
SOL_CYCL_PAR = phase_field.fem.solver.cycl.params(...
    'max_cycle',   120, ...
    'da_paraview', 0.01 ...
);
SOL_JUMP_PAR = phase_field.fem.solver.cycl_jump.params('cycl_jump', false);
CRACK_PAR = phase_field.fem.crack.params(MAT_CHAR, diss_fct);

% =========================================================================
%   OUTPUT — no VTK (save disk), psi_fields saved per-cycle by solver
% =========================================================================
checkpoint_freq = 10;
vtk_freq        = 10;
