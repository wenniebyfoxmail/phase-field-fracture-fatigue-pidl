% =========================================================================
% SENT fatigue — reverseBC u=0.12 with PIDL-like diffuse pre-crack
%
% Reciprocal diagnostic for PIDL void-notch alignment:
%   - Keep material in the initial crack corridor (no duplicated crack-face
%     nodes and no traction-free internal crack boundary).
%   - Prescribe a hard damaged phase-field band, d = 1, over the PIDL-style
%     pre-crack corridor x_centered <= 0 and |y_centered| <= 0.02.
%   - Initialize alpha_bar = 1 in elements whose centroids lie in that band.
%
% Coordinates from specimen.internal.plate are [0,1] x [0,1], so the requested
% centered mask x <= 0, |y| <= 0.02 is implemented as:
%   x <= 0.5, |y - 0.5| <= 0.02.
% =========================================================================

split_type = 'AMOR';
diss_fct   = 'AT1';
irrev      = 'PENALTY';

example_name = 'SENT_PIDL_12_diffuse_precrack_reverseBC';

% Continuous material mesh with refinement along the pre-crack/crack path.
% This matches the mesh_C resolution family, but uses phase_field rather than
% sharp_notch so the pre-crack corridor remains material.
[MESH, GEOM, NODESETS, ELEMSETS] = specimen.internal.plate(...
    'L', 1.0, 'B', 1.0, 't', 1.0, ...
    'notch_type', 'phase_field', ...
    'Nx', 250, 'Ny', 20, ...
    'Lref_x', 0.0, 'Lref_y', 0.1, ...
    'Nref_x', 0,   'Nref_y', 50, ...
    'y_notch',  0.5, ...
    'Lnotch_x', 0.5 ...
);
fprintf('diffuse pre-crack mesh: %d nodes, %d elements\n', MESH.num_node, MESH.num_elem);

MAT_CHAR(1) = phase_field.init.material_characteristic(...
    GEOM.L, diss_fct, ...
    'E',         1.0, ...
    'ni',        0.3, ...
    'Gc',        0.01, ...
    'ell',       0.01, ...
    'res_stiff', 1e-6, ...
    'alpha_T',   0.5, ...
    'p',         2.0 ...
);
MESH.elem_material_id = ones(MESH.num_elem, 1);

precrack_nodes = find(MESH.node(:,1) <= 0.5 & abs(MESH.node(:,2) - 0.5) <= 0.02);
precrack_elem_mask = false(MESH.num_elem, 1);
precrack_centroids = zeros(MESH.num_elem, 2);
for e = 1:MESH.num_elem
    xy = MESH.node(MESH.elem(e,:), :);
    precrack_centroids(e,:) = mean(xy, 1);
end
precrack_elem_mask(:) = precrack_centroids(:,1) <= 0.5 & abs(precrack_centroids(:,2) - 0.5) <= 0.02;
precrack_elems = find(precrack_elem_mask);
fprintf('[INPUT] diffuse precrack nodes d=1 = %d, elems alpha_bar=1 = %d\n', ...
    numel(precrack_nodes), numel(precrack_elems));

top_bottom = unique([NODESETS('top'); NODESETS('bottom')]);

NODE_BOUNDARIES = phase_field.fem.bc.set_boundaries(...
    'fix_X',      top_bottom, ...
    'fix_Y',      NODESETS('bottom'), ...
    'disp_Y',     NODESETS('top'), ...
    'non_hom_pf', precrack_nodes ...
);

DOFS = phase_field.init.dofs(MESH, NODE_BOUNDARIES);
QUADRATURE = phase_field.init.quadrature(MESH.dim);
stress_state = phase_field.StressState.PlaneStrain;

SOL_PAR = phase_field.fem.solver.params(...
    'tol_displ',      1e-6, ...
    'tol_p_field',    1e-5, ...
    'max_iter_displ', 250, ...
    'max_iter_pf',    250 ...
);
SOL_STAG_PAR = phase_field.fem.solver.stag.params('tol', 1e-4, 'max_iter', 1000);
SOL_STEP_PAR = phase_field.fem.solver.step.params(...
    'n_step',         8, ...
    'loading',        'cyclic', ...
    'discretization', 'loading', ...
    'uy_final',       0.12, ...
    'R',              0.0, ...
    'line_search',    true ...
);
SOL_CYCL_PAR = phase_field.fem.solver.cycl.params(...
    'max_cycle',   120, ...
    'da_paraview', 0.01 ...
);
SOL_JUMP_PAR = phase_field.fem.solver.cycl_jump.params('cycl_jump', false);
CRACK_PAR = phase_field.fem.crack.params(MAT_CHAR, diss_fct);

checkpoint_freq = 10;
vtk_freq        = 10;

diffuse_precrack_metadata = struct();
diffuse_precrack_metadata.centered_mask = 'x <= 0 and |y| <= 0.02';
diffuse_precrack_metadata.plate_mask = 'x <= 0.5 and |y - 0.5| <= 0.02';
diffuse_precrack_metadata.width = 0.04;
diffuse_precrack_metadata.profile = 'hard d=1 Dirichlet band on nodes; alpha_bar=1 initialized on centroid-selected elements';
diffuse_precrack_metadata.material_or_void = 'material retained; no duplicated crack-face nodes';
