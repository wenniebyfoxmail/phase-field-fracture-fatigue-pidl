"""Render exact fixed-group outputs; no source selection or evidence recompute."""
import argparse
import json
from pathlib import Path
import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np
from md03_grouped_observability import GROUP, NAMES, XS, YS
from md01_cached_stage_forecast import save,sha

LABELS=['Motion','Light','Smooth','Light +\nsmooth','Gap 1','Gap 2','Gap 4','Gap 2 +\nboth']


def render(source,out):
    out.mkdir(parents=True,exist_ok=False)
    summary=json.loads((source/'summary.json').read_text());rows={r['case']:r for r in summary['rows']}
    spec=json.loads((source/'specification.json').read_text());band=spec['band']
    extent=(band[0],band[2],band[3],band[1]);grid_extent=(XS[0]-4,XS[-1]+4,YS[-1]+8,YS[0]-8)
    plt.rcParams.update({'font.size':9})
    diverge=plt.get_cmap('RdBu_r').copy();diverge.set_bad('#B0B0B0')
    viridis=plt.get_cmap('viridis').copy();viridis.set_bad('#B0B0B0')
    provenance=('\n## Data provenance\n'+str(source)+
        '. Inputspecification and summaries/NPZs generated by scripts/md03_grouped_observability.py. '
        'Only existing89/132/175, old mask, saved global transforms. Full band[2500,1720,3000,2080]. '
        '39x21fixedprobes x2598..2902,y1740..2060, step8/16. '
        f'Renderer{Path(__file__)}. No new inference/classification/forecast during rendering.\n')
    limitations=('\n## Limitations and claim boundary\nOne beam, two dependent pairs;175already-exposed development. '
        'Horizontal jump extrapolated from six31x31 patches at offsets±24/48/72, not physical aperture or old half-depth. '
        'Wide spatial footprint can smear/produce lobes; this map is not a crack segmentation or exact path. '
        'NCC high is not proof of physical correspondence; nonlinear deformation/texture/interpolation can imitate jumps. '
        'Gray masked pixels mean search-boundary/constant-texture unassessable, not zero crack. '
        'No truth-based crack accuracy, confidence interval, absolute time/load or new prediction gains. '
        'Controls use simple straight fully dark synthetic gaps on89texture, favourable generator, not real crack truth.\n')
    def export(fig,stem,text):
        fig.savefig(out/(stem+'.png'),dpi=220);plt.close(fig)
        (out/(stem+'.md')).write_text(text+provenance+limitations)
    def load(name):
        with np.load(source/name/'evidence.npz') as z:return {k:z[k] for k in z.files}
    def oldpanel(ax,z):
        ax.imshow(z['b_image'],cmap='gray',vmin=0,vmax=255,extent=extent,interpolation='nearest')
        ax.contour(np.arange(band[0],band[2])+.5,np.arange(band[1],band[3])+.5,
                   z['old_mask'].astype(float),levels=[.5],colors=['#56B4E9'],linewidths=.6)
        ax.axvline(2750,color='#E69F00',ls='--',lw=.8)
    def imagefield(ax,z,key,vmin,vmax,cmap):
        return ax.imshow(np.ma.array(z[key],mask=~z['valid']),extent=grid_extent,
                         interpolation='nearest',cmap=cmap,vmin=vmin,vmax=vmax,aspect='auto')
    fig,axs=plt.subplots(2,5,figsize=(17,7.6),layout='constrained')
    images={}
    for axes,name in zip(axs,['real_89_132','real_132_175']):
        z=load(name);row=rows[name];a,b=name.split('_')[1:]
        oldpanel(axes[0],z);axes[0].set_title(f'{a} → {b}: B + OLD cyan mask\norange fixed x2750')
        images['motion']=axes[1].imshow(z['motion_residual'],extent=extent,cmap=diverge,vmin=-255,vmax=255,interpolation='nearest')
        axes[1].set_title('Saved-motion residual\npositive = later darker')
        images['J']=imagefield(axes[2],z,'jump_x',-4,4,diverge)
        axes[2].set_title('Two-sided jump J (image px)\npositive = horizontal separation')
        images['Q']=imagefield(axes[3],z,'gap_contrast',-255,255,diverge)
        axes[3].set_title('Local darkening Q (gray levels)\nrelative to two flanks')
        images['quality']=imagefield(axes[4],z,'ncc_min',0,1,viridis)
        axes[4].set_title(f'Min NCC among six matches\nassessable {row["assessable_probes"]}/819; no NCC cutoff')
        for ax in axes:ax.set_xlabel('native x (px)');ax.set_ylabel('native y (px)')
    for c,key,label in [(1,'motion','Gray levels'),(2,'J','Image px (clipped display ±4)'),(3,'Q','Gray levels'),(4,'quality','NCC')]:
        fig.colorbar(images[key],ax=axs[:,c].ravel().tolist(),shrink=.63,pad=.01).set_label(label)
    fig.suptitle('D3 grouped real-image evidence | first row design89→132; second exposed development132→175\n'
                 'No new crack threshold. Fixed grid has a wide texture-matching footprint, NOT a crack mask.',fontsize=12)
    export(fig,'F01_real_grouped_evidence','# How to read: grouped real-image evidence\n\n## Figure question\n'
        'Does source-darkness, compensated intensity and two-sided texture motion point to the same identifiable opening?\n'
        '\n## Panels and visual grammar\nRows89→132 design and132→175 exposeddevelopment. '
        'Columns Bgray+oldcyanmask/orange fixedmidspan, oldsaved-motionresidual±255, J±4imagepixels, '
        'Q±255graylevels, minimum NCC0..1. Same fixed grayscale/colours across pairs. '
        'Jdisplayclipped±4, no measurement clipping; all numeric fields retained. '
        'Gridmaps cover interior probes only, not full ROI resolution; old and motion arms display whole scoringband. '
        'Numeric grouped comparisons use identical5x31central footprints at each valid probe.\n'
        '\n## Key numerical takeaway\n'+json.dumps([rows['real_89_132'],rows['real_132_175']],indent=2))
    fig,axs=plt.subplots(3,1,figsize=(12,9.5),layout='constrained',sharex=True)
    for ax,key,label in zip(axs,['jump_x','gap_contrast','old_fraction'],
             ['Horizontal jump J (image px)','Relative darkening Q (gray levels)','Old dark-mask fraction in central footprint']):
        for i,name in enumerate(NAMES):
            r=rows[name];s=r['center'][key];color='#0072B2' if r['known_gap']==0 else '#D55E00'
            ax.errorbar(i,s['median'],yerr=[[s['median']-s['p10']],[s['p90']-s['median']]],fmt='o',
                        color=color,capsize=3,lw=1.3)
        ax.axhline(0,color='#555555',lw=.7);ax.set_ylabel(label);ax.grid(axis='y',alpha=.18)
    axs[0].plot(np.arange(8),[rows[n]['known_gap'] for n in NAMES],'kx',ms=8,label='Known injected gap (controls only)')
    axs[0].legend(fontsize=9)
    axs[-1].set_xticks(range(8),LABELS);axs[-1].set_xlabel('All eight fixed controls on the same historical89 texture')
    fig.suptitle('D3 control response | fixed x2750, all21 y positions\n'
        'Points: median; bars: spatial10–90% range (NOT uncertainty / independent replicates)',fontsize=12)
    export(fig,'F02_control_responses','# How to read: all fixed control responses\n\n## Figure question\n'
        'Can the evidence separate known nuisance changes from inserted openings at the same source/position?\n'
        '\n## Panels and visual grammar\nAll8cases in fixed order, bluezero-gap nuisances and orange injectedgap. '
        'TopmedianJimagepx vs black known-gapcross, middleQgraylevels, bottomoldcandidatefraction. '
        'Bars10–90% across21fixedypositions atx2750, NOT CI. No success threshold or fitted classificationcut. '
        'Same central5x31footprints for allarms, valid matching support only; centre all21assessable in every case.\n'
        '\n## Key numerical takeaway\n'+json.dumps([dict(case=n,gap=rows[n]['known_gap'],center=rows[n]['center']) for n in NAMES],indent=2))
    fig,axs=plt.subplots(4,4,figsize=(14,12),layout='constrained')
    for i,name in enumerate(NAMES):
        r,c=divmod(i,2);c*=2;z=load(name)
        oldpanel(axs[r,c],z);axs[r,c].set_title(name+'\ncontrol gray + frozen observer')
        j=imagefield(axs[r,c+1],z,'jump_x',-4,4,diverge)
        axs[r,c+1].set_title('J map | known gap '+str(rows[name]['known_gap'])+' image px')
        for ax in axs[r,c:c+2]:ax.set_xlabel('native x (px)');ax.set_ylabel('native y (px)')
    fig.colorbar(j,ax=axs[:,[1,3]].ravel().tolist(),shrink=.5,pad=.015).set_label('J (image px), display clipped ±4')
    fig.suptitle('D3 | All eight control images and full probe fields\nOld observer unchanged on synthetic cases; no new real masks',fontsize=12)
    export(fig,'F03_all_control_fields','# How to read: all control images and probe fields\n\n## Figure question\n'
        'Where do controls alter the image and two-sided evidence, including off-centre ambiguity?\n'
        '\n## Panels and visual grammar\nFourrows/twocasegroups perrow in fixed8caseorder. '
        'Each case shows controlBgray0..255 plus frozen-observercyan contours/orange fixedx2750, '
        'then Jfieldshared±4imagepx. Grayunassessable search-edge probes. Wholeband shown, no winning-crop selection. '
        'A broad/bipolar Jresponse can arise when sixpatches straddle the gap: not an exact crack path.\n'
        '\n## Key numerical takeaway\n'+json.dumps([dict(case=n,assessable=rows[n]['assessable_probes'],
                     censored=rows[n]['censored_probes'],center_J=rows[n]['center']['jump_x']) for n in NAMES],indent=2))
    save(out/'render_receipt.json',dict(execution='succeeded',source_summary_sha256=sha(source/'summary.json'),
              renderer_sha256=sha(__file__),outputs={str(p):sha(p) for p in out.glob('F*') if p.is_file()}))


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--source',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    args=p.parse_args();render(args.source,args.output)
